#!/usr/bin/env node
/**
 * Cold-start budget of the hooks settings.json wires. Every hook pays its node start on each tool call, so a
 * hook that grows a heavy require or a slow init shows up here. Zero dependencies — `node:test` on Node 18+.
 *
 *   node --test tools/hook-coldstart.test.mjs
 *
 * Each `node -e require(<hooks>/X.js)` entry is run as `node hooks/X.js` with a minimal payload of its event, median of
 * 3 runs, against the machine's own floor: median of 3 `node -e 0` runs + COLDSTART_NODE_MS (default 250), so a slow box
 * does not fail it. pwsh hooks pay a floor of their own, `pwsh -NoProfile -NonInteractive -Command exit`, checked
 * against COLDSTART_PWSH_MS (default 1500) and skipped without pwsh. A measure over its limit is re-taken once (the
 * baseline too), so a load spike from parallel test files does not fail it. COLDSTART_SKIP=1 skips the file.
 *
 * Safety: every spawn runs in a temp directory that is not a repo, with CLAUDE_CONFIG_DIR and CLAUDE_ENV_FILE inside
 * it and CLAUDE_DONE_CLAIM unset.
 *
 * Generated by Claude Code at the user's request.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createServer } from 'node:net';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RUNS = 3;
const NODE_MS = Number(process.env.COLDSTART_NODE_MS ?? 250);
const PWSH_MS = Number(process.env.COLDSTART_PWSH_MS ?? 1500);
const SKIP = process.env.COLDSTART_SKIP === '1';

/** Never measured: worktree-root.js (WorktreeCreate creates a real worktree) — ensure-edge-cdp.ps1 is pwsh, not a node hook. */
const EXCLUDED = new Set(['worktree-root']);

const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

function timed(command, args, options) {
  const start = process.hrtime.bigint();
  const r = spawnSync(command, args, { stdio: ['pipe', 'ignore', 'ignore'], windowsHide: true, timeout: 30_000, ...options });
  const ms = Number(process.hrtime.bigint() - start) / 1e6;
  // A hook that crashes on load is fast for the wrong reason: hooks always exit 0.
  if (r.error || r.status !== 0) throw new Error(`${command} ${args.join(' ')} failed: ${r.error?.code ?? `exit ${r.status}`}`);
  return ms;
}

/** `[{ name, event, tool }]` for every `require(<hooks>/X.js)` hook of settings.json. */
function wiredHooks() {
  const settings = JSON.parse(readFileSync(join(ROOT, 'settings.json'), 'utf8'));
  const found = new Map();
  for (const [event, groups] of Object.entries(settings.hooks ?? {})) {
    for (const group of groups) {
      for (const hook of group.hooks ?? []) {
        if (hook.command !== 'node' || hook.args?.[0] !== '-e') continue;
        const m = /\+'\/([\w.-]+)\.js'\)/.exec(hook.args[1] ?? '');
        if (!m || EXCLUDED.has(m[1]) || found.has(m[1])) continue;
        const tool = (group.matcher ?? '').split('|')[0].replace(/\.\*$/, 'x');
        found.set(m[1], { name: m[1], event, tool: tool || 'Bash' });
      }
    }
  }
  return [...found.values()];
}

const payload = ({ event, tool }, cwd) => JSON.stringify({
  session_id: 'coldstart', transcript_path: join(cwd, 'transcript.jsonl'), cwd, hook_event_name: event,
  tool_name: tool, tool_input: { command: 'echo coldstart', file_path: join(cwd, 'x.txt') }, source: 'startup',
});

test('every wired node hook starts within the machine baseline plus COLDSTART_NODE_MS', { skip: SKIP }, async () => {
  const work = mkdtempSync(join(tmpdir(), 'hook-coldstart-'));
  const config = join(work, 'config');
  const cwd = join(work, 'cwd');
  const edgeData = join(work, 'local', 'Microsoft', 'Edge', 'User Data');
  mkdirSync(config, { recursive: true });
  mkdirSync(cwd, { recursive: true });
  mkdirSync(edgeData, { recursive: true });
  // edge-cdp.js takes its fast path (no Edge, no pwsh) when the port in DevToolsActivePort answers.
  const server = createServer((socket) => socket.destroy());
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  writeFileSync(join(edgeData, 'DevToolsActivePort'), `${server.address().port}\n/devtools/browser/x\n`);
  const env = { ...process.env, CLAUDE_CONFIG_DIR: config, CLAUDE_ENV_FILE: join(work, 'env.sh'), LOCALAPPDATA: join(work, 'local') };
  delete env.CLAUDE_DONE_CLAIM;
  delete env.CLAUDE_HOOKS;
  try {
    const measureBaseline = () => median(Array.from({ length: RUNS }, () => timed(process.execPath, ['-e', '0'], { env, cwd })));
    const baseline = measureBaseline();
    const hooks = wiredHooks();
    assert.ok(hooks.length > 0, 'no node hook found in settings.json');
    const slow = [];
    for (const hook of hooks) {
      const input = payload(hook, cwd);
      const measure = () => median(Array.from({ length: RUNS }, () => timed(process.execPath, [join(ROOT, 'hooks', `${hook.name}.js`)], { env, cwd, input })));
      let limit = baseline + NODE_MS;
      let ms = measure();
      // Parallel test files load the machine unevenly: a hook over the limit is re-measured against a fresh
      // baseline of its own, and only a hook slow both times fails.
      if (ms > limit) { limit = measureBaseline() + NODE_MS; ms = measure(); }
      if (ms > limit) slow.push(`${hook.name} ${Math.round(ms)} ms > ${Math.round(limit)}`);
    }
    assert.deepEqual(slow, [], `slow hooks (median of ${RUNS}; threshold = node baseline + ${NODE_MS} ms): ${slow.join(', ')}`);
  } finally {
    server.close();
    rmSync(work, { recursive: true, force: true });
  }
});

const hasPwsh = !SKIP && spawnSync('pwsh', ['-NoProfile', '-Command', 'exit'], { stdio: 'ignore', windowsHide: true }).status === 0;

test('the pwsh floor every pwsh hook pays stays under COLDSTART_PWSH_MS', { skip: SKIP || !hasPwsh }, () => {
  const args = ['-NoProfile', '-NonInteractive', '-Command', 'exit'];
  const measure = () => median(Array.from({ length: RUNS }, () => timed('pwsh', args, {})));
  let ms = measure();
  if (ms > PWSH_MS) ms = measure();  // a load spike from parallel test files: fail only when slow twice
  assert.ok(ms <= PWSH_MS, `pwsh start: median ${Math.round(ms)} ms over the threshold ${PWSH_MS} ms`);
});
