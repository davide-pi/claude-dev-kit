#!/usr/bin/env node
/**
 * Tests for hooks/done-claim.js (Stop, tier 1), part 1: claim words, silences, turn boundaries, the
 * perimeter close and the /clear hand-off. The verdict-table proof is in done-claim-verdict.test.mjs;
 * the shared helpers are in done-claim.harness.mjs. Zero dependencies — `node:test` on Node 18+.
 *
 *   node --test "tools/*.test.mjs"
 *
 * Transcripts are fabricated JSONL in a temp dir, shaped like the harness writes them: user
 * prompts, assistant entries with text and tool_use blocks, user entries carrying tool results.
 * Most cases are the silences — opt-in off, a loop guard, a turn that edited nothing, evidence or
 * an honest "non verificato" — because a Stop hook that blocks too often is switched off.
 *
 * Generated by Claude Code at the user's request.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { created, prompt, say, tool, result, stop, edited, VERDICT, PRINTED, peer, head, row, verdict, stopWithContext, committed } from './done-claim.harness.mjs';

test('English claim words without proof are blocked; "works" before a qualifier is not a claim', () => {
  assert.match(stop(edited('All tests passes now.')).reason, /"passes"/);
  assert.match(stop(edited('The change is verified.')).reason, /"verified"/);
  assert.match(stop(edited('It works.')).reason, /"works"/);
  assert.equal(stop(edited('The new helper works for every locale.')).reason, '');
  assert.equal(stop(edited('All tests passes, `npm test` → 12 passed.')).reason, '');
  assert.equal(stop(edited('The handler now passes the token to the service.')).reason, '');
  assert.equal(stop(edited('The middleware passes the request through.')).reason, '');
  assert.equal(stop(edited('The signature should be verified by the caller.')).reason, '');
  assert.equal(stop(edited("The migration hasn't been verified against a real database.")).reason, '');
  assert.equal(stop(edited('This could not be verified here.')).reason, '');
  assert.equal(stop(edited('The old path no longer works.')).reason, '');
  assert.match(stop(edited('It works as expected.')).reason, /"works"/);
  assert.match(stop(edited('Login works as intended now.')).reason, /"works"/);
});

test('an edit turn ending "fatto" with no evidence is blocked and logged', () => {
  const { reason, dir } = stop(edited('Fatto: il totale ora somma le righe.'));
  assert.match(reason, /"Fatto"/);
  assert.match(reason, /non verificato/);
  assert.match(reason, /Livello \| Comando \| Riga che decide \| Stato/);
  assert.match(reason, /never in a code block/);
  assert.doesNotMatch(reason, /in un blocco ```/);
  const log = readFileSync(join(dir, '.cache', 'done-claim.log'), 'utf8').trim().split('\n');
  assert.equal(log.length, 1);
  assert.equal(JSON.parse(log[0]).word, 'Fatto');
  assert.equal(JSON.parse(log[0]).rule, 'claim-without-evidence');
});

test('a shell command ran after the last edit → silent: its output is already in context, and counted', () => {
  const { reason, dir } = stop([prompt('sistema il bug'), tool('Edit'), result(), tool('Bash'), result(), say('Fatto: il totale ora somma le righe.')]);
  assert.equal(reason, '');
  const log = readFileSync(join(dir, '.cache', 'done-claim.log'), 'utf8').trim().split('\n');
  assert.equal(JSON.parse(log[0]).rule, 'shell-ran');
  assert.equal(stop([prompt('x'), tool('Edit'), result(), tool('PowerShell'), result(), say('Done.')]).reason, '');
});

test('a shell command that ran BEFORE the last edit proves nothing about it → blocked', () => {
  const entries = [prompt('x'), tool('Bash'), result(), tool('Edit'), result(), say('Fatto.')];
  assert.match(stop(entries).reason, /"Fatto"/);
});

