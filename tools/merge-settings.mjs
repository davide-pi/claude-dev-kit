#!/usr/bin/env node
/**
 * Merges the kit's settings.json template with a personal overlay. Zero dependencies — plain Node 18+.
 *
 *   node tools/merge-settings.mjs --template settings.json --overlay ~/.claude/settings.overlay.json
 *   node tools/merge-settings.mjs --template … --overlay … --out ~/.claude/settings.json
 *   node tools/merge-settings.mjs --template … --overlay … --check ~/.claude/settings.json
 *
 * The template is what the kit ships; the overlay is what is yours (model, output style, extra allow
 * rules, a hook of your own) and lives beside the live config, never in the repo. The merge is a pure
 * function of the two files, so the live settings.json can always be compared with it again.
 *
 * Rules, applied key by key, the overlay on top:
 *
 *   - objects merge deeply;
 *   - scalars: the overlay wins, and so does an overlay value of another type;
 *   - arrays of strings: ordered union, template first, no duplicates (`permissions.allow`, `ask`, …);
 *   - `hooks.<Event>` arrays: union by matcher and command. An overlay group whose matcher the template
 *     has gets its missing hooks added to that group; any other group is appended. A hook is the same
 *     hook when `command` and `args` are (an `http` hook: its `url`); the overlay's other fields
 *     (timeout, statusMessage, …) then override the template's;
 *   - `fallbackModel` (an ordered choice): the overlay replaces it, never appended;
 *   - any other array (objects, mixed): the overlay replaces it;
 *   - an overlay key set to `null` removes that key from the result (no way to remove one array item:
 *     remove the key, then list the items you want).
 *
 * `--out` writes the result (2-space JSON, trailing newline) to <out>.tmp, then renames it; with neither `--out` nor `--check` it is
 * printed. `--check <live>` exits 1 and lists the differing keys (`~` differs, `+` missing from the
 * live file, `-` only in the live file) when the live file is not the merge result. Exit 2: bad usage or
 * an unreadable or invalid file.
 *
 * Generated by Claude Code at the user's request.
 */

import { readFileSync, writeFileSync, renameSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const isObject = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isStrings = (a) => a.every((v) => typeof v === 'string');
const clone = (v) => JSON.parse(JSON.stringify(v));

/** Ordered lists that are a choice (first = preferred), not a set: the overlay replaces them. */
const REPLACED_LISTS = new Set(['fallbackModel']);

/** `{type, command, args}` → one comparable string; a hook with no command is told apart by its url. */
const hookKey = (hook) => JSON.stringify([hook?.command ?? hook?.url ?? hook, hook?.args ?? []]);

/** Two lists of hook groups → one: groups of the same matcher are one group, hooks never twice. */
function mergeHookGroups(base, over) {
  const out = clone(base);
  for (const group of over) {
    const home = out.find((g) => (g?.matcher ?? '') === (group?.matcher ?? ''));
    if (!home || !Array.isArray(home.hooks) || !Array.isArray(group?.hooks)) { out.push(clone(group)); continue; }
    for (const hook of group.hooks) {
      const same = home.hooks.find((h) => hookKey(h) === hookKey(hook));
      if (same && isObject(same) && isObject(hook)) Object.assign(same, clone(hook));
      else if (!same) home.hooks.push(clone(hook));
    }
  }
  return out;
}

function mergeValue(base, over, path) {
  if (isObject(base) && isObject(over)) return mergeObjects(base, over, path);
  if (Array.isArray(base) && Array.isArray(over)) {
    if (path.length === 1 && REPLACED_LISTS.has(path[0])) return clone(over);
    if (path.length === 2 && path[0] === 'hooks') return mergeHookGroups(base, over);
    if (isStrings(base) && isStrings(over)) return [...new Set([...base, ...over])];
  }
  return clone(over);
}

function mergeObjects(base, over, path) {
  const out = clone(base);
  for (const [key, value] of Object.entries(over)) {
    if (value === null) delete out[key];
    else out[key] = key in out ? mergeValue(out[key], value, [...path, key]) : clone(value);
  }
  return out;
}

/** The template with the overlay on top. Neither argument is modified. */
export function mergeSettings(template, overlay) {
  if (!isObject(template) || !isObject(overlay)) throw new Error('template and overlay must both be JSON objects');
  return mergeObjects(template, overlay, []);
}

/** The keys that differ between the expected and the live settings, one line each. */
export function diffSettings(expected, live, path = []) {
  const name = (key) => [...path, key].join('.');
  if (isObject(expected) && isObject(live)) {
    return [...new Set([...Object.keys(expected), ...Object.keys(live)])].flatMap((key) => {
      if (!(key in live)) return [`+ ${name(key)}`];
      if (!(key in expected)) return [`- ${name(key)}`];
      return diffSettings(expected[key], live[key], [...path, key]);
    });
  }
  const where = path.join('.');
  if (Array.isArray(expected) && Array.isArray(live) && isStrings(expected) && isStrings(live)) {
    const missing = expected.filter((v) => !live.includes(v));
    const extra = live.filter((v) => !expected.includes(v));
    const same = !missing.length && !extra.length;
    if (same && expected.every((v, i) => v === live[i])) return [];
    const parts = [...missing.map((v) => `+ ${v}`), ...extra.map((v) => `- ${v}`)];
    return [`~ ${where}${same ? ' (order)' : ` [${parts.join(', ')}]`}`];
  }
  return JSON.stringify(expected) === JSON.stringify(live) ? [] : [`~ ${where}`];
}

function readJson(file, what) {
  try {
    return JSON.parse(readFileSync(resolve(file), 'utf8'));
  } catch (error) {
    throw new Error(`${what} ${file}: ${error.message}`);
  }
}

function parseArgs(argv) {
  const known = new Set(['--template', '--overlay', '--out', '--check']);
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!known.has(argv[i]) || argv[i + 1] === undefined) throw new Error(`unexpected argument: ${argv[i]}`);
    args[argv[i].slice(2)] = argv[i + 1];
  }
  if (!args.template || !args.overlay) throw new Error('--template and --overlay are required');
  return args;
}

function main(argv) {
  const usage = 'usage: node merge-settings.mjs --template <settings.json> --overlay <overlay.json> [--out <path>] [--check <live settings.json>]';
  let args;
  try { args = parseArgs(argv); } catch (error) { console.error(`${error.message}\n${usage}`); return 2; }
  try {
    const merged = mergeSettings(readJson(args.template, 'template'), readJson(args.overlay, 'overlay'));
    const text = `${JSON.stringify(merged, null, 2)}\n`;
    if (args.out) {
      const target = resolve(args.out);
      writeFileSync(`${target}.tmp`, text);
      renameSync(`${target}.tmp`, target);
    }
    if (args.check) {
      const differing = diffSettings(merged, readJson(args.check, 'live settings'));
      if (differing.length) { console.log(differing.join('\n')); return 1; }
      return 0;
    }
    if (!args.out) process.stdout.write(text);
    return 0;
  } catch (error) {
    console.error(error.message);
    return 2;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
