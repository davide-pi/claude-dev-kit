#!/usr/bin/env node
/**
 * Where the tokens of the last N days went, read from the session transcripts. Zero dependencies —
 * plain Node 18+. Read-only: it never writes and never calls the network.
 *
 *   node tools/cost-audit.mjs                       # last 30 days of ~/.claude/projects
 *   node tools/cost-audit.mjs --days 14 --top 30
 *   node tools/cost-audit.mjs --projects <dir> --log <done-claim.log> [--now <ISO date>]
 *
 * One number to judge a change by, taken before and after it: a settings tweak (auto-compact), a nudge
 * hook, a plugin switched off. Reported for the window:
 *
 *   - baseline per session: the first assistant message's input (`input + cache_creation + cache_read`),
 *     i.e. what a session costs before the user has typed anything of substance;
 *   - the share of main-thread input tokens spent in turns whose context was above 200k and 300k
 *     (a turn at 400k costs ten times a turn at 40k, so this share is the lever);
 *   - Skill tool loads per skill, and tool calls per MCP server (all threads, subagents included);
 *   - hook injections (`additionalContext` attachments), by the hook that wrote them when the text is
 *     recognisable, else by event;
 *   - the `done-claim` log: entries per rule and claim word.
 *
 * "Main thread" is a transcript outside a `subagents/` folder whose entries are not `isSidechain`. An
 * assistant message is counted once even when the transcript repeats it per content block (same
 * `message.id`). Transcripts are the harness's own format and can change: a field that is not there
 * is skipped, never an error.
 *
 * Generated by Claude Code at the user's request.
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const DAY_MS = 864e5;
const THRESHOLDS = [200_000, 300_000];

/** Text a hook's injected line starts with → the hook that wrote it. Anything else is named by event. */
const HOOK_MARKERS = [
  [/^⏱/, 'worklog-pending'],
  [/^Contesto (?:a|al) /, 'context-nudge'],
  [/^Terzo edit/, 'edit-nudge'],
  [/^ALM:/, 'workspace-context'],
  [/^branch /, 'session-brief'],
];

const configDir = () => process.env.CLAUDE_CONFIG_DIR || join(homedir(), '.claude');

function* walk(dir) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return; }
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) yield* walk(full);
    else if (e.isFile() && e.name.endsWith('.jsonl')) yield full;
  }
}

function* entriesOf(file) {
  let text;
  try { text = readFileSync(file, 'utf8'); } catch { return; }
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try { yield JSON.parse(line); } catch { /* a torn line */ }
  }
}

const contextOf = (usage) => (usage.input_tokens || 0) + (usage.cache_creation_input_tokens || 0) + (usage.cache_read_input_tokens || 0);
const bump = (map, key, by = 1) => map.set(key, (map.get(key) || 0) + by);
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor((s.length - 1) / 2)] : 0; };

function hookName(attachment) {
  const text = [].concat(attachment.content ?? []).join('\n');
  return HOOK_MARKERS.find(([re]) => re.test(text))?.[1] ?? `${attachment.hookEvent || attachment.hookName || 'unknown'} (other)`;
}

/** The numbers, as plain data: `report()` only formats them. */
export function audit({ projects, days = 30, now = Date.now(), log } = {}) {
  const since = now - days * DAY_MS;
  const inWindow = (ts) => { const t = Date.parse(ts); return Number.isFinite(t) && t >= since && t <= now; };
  const sessions = [];
  const skills = new Map();
  const mcp = new Map();
  const hooks = new Map();
  const share = { total: 0, over: THRESHOLDS.map(() => 0), turns: 0 };

  for (const file of walk(projects)) {
    const sidechainFile = /[\\/]subagents[\\/]/.test(file);
    const seenMessages = new Set();
    const seenTools = new Set();
    let first = null;
    for (const e of entriesOf(file)) {
      if (!e.timestamp || !inWindow(e.timestamp)) continue;
      const main = !sidechainFile && !e.isSidechain;

      if (e.type === 'attachment' && e.attachment?.type === 'hook_additional_context' && main) {
        bump(hooks, hookName(e.attachment));
        continue;
      }
      if (e.type !== 'assistant' || !e.message) continue;

      for (const b of Array.isArray(e.message.content) ? e.message.content : []) {
        if (b?.type !== 'tool_use' || seenTools.has(b.id)) continue;
        seenTools.add(b.id);
        if (b.name === 'Skill' && b.input?.skill) bump(skills, b.input.skill);
        else if (typeof b.name === 'string' && b.name.startsWith('mcp__')) bump(mcp, b.name.split('__')[1]);
      }

      const usage = e.message.usage;
      const key = e.message.id;
      if (!main || !usage || (key && seenMessages.has(key))) continue;
      if (key) seenMessages.add(key);
      const context = contextOf(usage);
      if (!context) continue;
      first ??= { session: basename(file, '.jsonl'), project: basename(dirname(file)), at: e.timestamp, baseline: context };
      share.total += context;
      share.turns += 1;
      THRESHOLDS.forEach((limit, i) => { if (context > limit) share.over[i] += context; });
    }
    if (first) sessions.push(first);
  }

  const doneClaim = new Map();
  if (log && existsSync(log)) {
    for (const line of readFileSync(log, 'utf8').split('\n')) {
      try {
        const r = JSON.parse(line);
        if (inWindow(r.at)) bump(doneClaim, `${r.rule} / ${String(r.word).toLowerCase()}`);
      } catch { /* blank or torn */ }
    }
  }

  sessions.sort((a, b) => b.at.localeCompare(a.at));
  return { days, sessions, skills, mcp, hooks, doneClaim, share, thresholds: THRESHOLDS };
}

const k = (n) => `${Math.round(n / 1000)}k`;
const pct = (part, whole) => (whole ? `${((100 * part) / whole).toFixed(1)} %` : 'n/a');
const sorted = (map) => [...map.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

function section(title, map) {
  const rows = sorted(map);
  return [`## ${title}`, ...(rows.length ? rows.map(([name, n]) => `  ${String(n).padStart(5)}  ${name}`) : ['  none'])];
}

export function report(result, top = 15) {
  const { sessions, share, thresholds } = result;
  const baselines = sessions.map((s) => s.baseline);
  const out = [`# Cost audit - last ${result.days} days`, '', '## Baseline per session (first assistant message input, tokens)'];
  if (!sessions.length) out.push('  no sessions in the window');
  else {
    out.push(`  sessions ${sessions.length}, min ${k(Math.min(...baselines))}, median ${k(median(baselines))}, max ${k(Math.max(...baselines))}`);
    for (const s of sessions.slice(0, top)) {
      out.push(`  ${s.at.slice(0, 16).replace('T', ' ')}  ${String(k(s.baseline)).padStart(5)}  ${s.session.slice(0, 8)}  ${s.project}`);
    }
    if (sessions.length > top) out.push(`  ... ${sessions.length - top} older (--top to list more)`);
  }
  out.push('', '## Main-thread input tokens by context size');
  out.push(`  turns ${share.turns}, input ${(share.total / 1e6).toFixed(1)}M`);
  thresholds.forEach((limit, i) => out.push(`  in turns with context > ${k(limit)}: ${pct(share.over[i], share.total)}`));
  out.push('', ...section('Skill loads (Skill tool)', result.skills));
  out.push('', ...section('Tool calls per MCP server', result.mcp));
  out.push('', ...section('Hook injections (additionalContext)', result.hooks));
  out.push('', ...section('done-claim log (rule / word)', result.doneClaim));
  return `${out.join('\n')}\n`;
}

function parseArgs(argv) {
  const known = new Set(['--projects', '--days', '--top', '--log', '--now']);
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    if (!known.has(argv[i]) || argv[i + 1] === undefined) throw new Error(`unexpected argument: ${argv[i]}`);
    args[argv[i].slice(2)] = argv[i + 1];
  }
  return args;
}

function main(argv) {
  let args;
  try { args = parseArgs(argv); } catch (error) {
    console.error(`${error.message}\nusage: node cost-audit.mjs [--projects <dir>] [--days <n>] [--top <n>] [--log <done-claim.log>] [--now <ISO date>]`);
    return 2;
  }
  const days = args.days === undefined ? 30 : Number(args.days);
  const now = args.now === undefined ? Date.now() : Date.parse(args.now);
  if (!(days > 0) || !Number.isFinite(now)) { console.error('--days must be a positive number and --now a valid date'); return 2; }
  const projects = resolve(args.projects || join(configDir(), 'projects'));
  if (!existsSync(projects)) { console.error(`no such directory: ${projects}`); return 2; }
  const log = args.log || join(configDir(), '.cache', 'done-claim.log');
  process.stdout.write(report(audit({ projects, days, now, log }), args.top === undefined ? 15 : Number(args.top)));
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
