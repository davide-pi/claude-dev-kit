#!/usr/bin/env node
/**
 * Tests for hooks/lib/az-pin.js, through hooks/guard-shell.js (its only caller): the rewrite that
 * pins the Azure CLI identity of the working directory on an `az` command. Zero dependencies —
 * `node:test` on Node 18+.
 *
 *   node --test "tools/*.test.mjs"
 *
 * Hermetic: every case gets its own config dir (the fabricated workspaces.json and settings.json whose
 * allow list the rewrite is bound to) and its own home (where `~/.azure-<identity>` may or may not
 * exist). The rewrite is returned as `allow` + `updatedInput`, so most cases are refusals: anything the
 * allow list does not already cover must stay with the normal permission flow.
 *
 * Generated by Claude Code at the user's request.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const GUARD = join(dirname(fileURLToPath(import.meta.url)), '..', 'hooks', 'guard-shell.js');
const created = [];
process.on('exit', () => {
  for (const dir of created) { try { rmSync(dir, { recursive: true, force: true }); } catch { /* tmp */ } }
});

const ROOTS = [
  { path: 'D:\\work\\product', platform: 'azure-devops', org: 'org-a', project: 'Product', identity: 'work' },
  { path: 'D:\\work\\gh', platform: 'github', org: 'gh-org' },
  { path: 'D:\\work\\ghost', platform: 'azure-devops', org: 'org-b', project: 'Ghost', identity: 'absent' },
];
const ALLOW = [
  'Bash(az boards query*)', 'Bash(az account show*)', 'Bash(ls *)',
  'PowerShell(az boards query*)', 'PowerShell(az account show*)', 'PowerShell(Get-ChildItem *)',
];
const MAPPED = 'D:\\work\\product\\repo-a';

/** A sandbox: config dir (map + settings), a home with the listed az dirs. */
function sandbox({ homeName = 'home', map = { roots: ROOTS }, settings = { permissions: { allow: ALLOW } }, azDirs = ['work'] } = {}) {
  const base = mkdtempSync(join(tmpdir(), 'azid-'));
  created.push(base);
  const config = join(base, 'config');
  const home = join(base, homeName);
  mkdirSync(config);
  mkdirSync(home);
  if (map) writeFileSync(join(config, 'workspaces.json'), JSON.stringify(map));
  if (settings) writeFileSync(join(config, 'settings.json'), JSON.stringify(settings));
  for (const id of azDirs) mkdirSync(join(home, `.azure-${id}`));
  return { config, home, azDir: join(home, '.azure-work').replace(/\\/g, '/') };
}

/** The guard's hookSpecificOutput for one command, null when it said nothing. */
function guard(box, command, { tool = 'PowerShell', cwd = MAPPED } = {}) {
  const r = spawnSync(process.execPath, [GUARD], {
    input: JSON.stringify({ tool_name: tool, tool_input: { command, description: 'd' }, cwd }),
    encoding: 'utf8',
    env: { ...process.env, CLAUDE_CONFIG_DIR: box.config, HOME: box.home, USERPROFILE: box.home },
  });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout.trim() ? JSON.parse(r.stdout).hookSpecificOutput : null;
}

const pinned = (box, command, options) => {
  const out = guard(box, command, options);
  assert.equal(out?.permissionDecision, 'allow', command);
  assert.equal(out.updatedInput.description, 'd', 'the rest of the tool input is preserved');
  return out.updatedInput.command;
};

test('PowerShell: the command is prefixed with the mapped identity, single-quoted', () => {
  const box = sandbox();
  assert.equal(pinned(box, 'az boards query --wiql "select [System.Id] from workitems"'),
    `$env:AZURE_CONFIG_DIR='${box.azDir}'; az boards query --wiql "select [System.Id] from workitems"`);
  assert.equal(pinned(box, 'az account show --query user.name -o tsv'),
    `$env:AZURE_CONFIG_DIR='${box.azDir}'; az account show --query user.name -o tsv`);
});

test('Bash: one plain command takes an inline assignment, a chained one an export', () => {
  const box = sandbox();
  assert.equal(pinned(box, 'az account show', { tool: 'Bash' }), `AZURE_CONFIG_DIR='${box.azDir}' az account show`);
  assert.equal(pinned(box, 'az account show && az boards query --wiql x', { tool: 'Bash' }),
    `export AZURE_CONFIG_DIR='${box.azDir}'; az account show && az boards query --wiql x`);
  assert.equal(pinned(box, 'az account show; ls /tmp', { tool: 'Bash' }),
    `export AZURE_CONFIG_DIR='${box.azDir}'; az account show; ls /tmp`);
});

test('PowerShell: a chained command is pinned once, for the whole line', () => {
  const box = sandbox();
  assert.equal(pinned(box, 'az account show; az boards query --wiql x'),
    `$env:AZURE_CONFIG_DIR='${box.azDir}'; az account show; az boards query --wiql x`);
});

test('a home with a space or a quote survives both shells (the rewritten line is run for real)', () => {
  for (const homeName of ['my home', "o'neil"]) {
    const box = sandbox({ homeName });
    const bash = spawnSync('bash', ['-c', 'echo ok'], { encoding: 'utf8' });
    if (bash.status === 0) {
      const line = pinned(box, 'az account show', { tool: 'Bash' });
      const r = spawnSync('bash', ['-c', `az() { printf %s "$AZURE_CONFIG_DIR"; }; ${line}`], { encoding: 'utf8' });
      assert.equal(r.stdout, box.azDir, `bash, ${homeName}`);
      const chained = pinned(box, 'az account show && az account show', { tool: 'Bash' });
      const c = spawnSync('bash', ['-c', `az() { printf %s "$AZURE_CONFIG_DIR"; }; ${chained}`], { encoding: 'utf8' });
      assert.equal(c.stdout, box.azDir + box.azDir, `bash, chained, ${homeName}`);
    }
    const pwsh = spawnSync('pwsh', ['-NoProfile', '-Command', '1'], { encoding: 'utf8' });
    if (pwsh.status === 0) {
      const line = pinned(box, 'az account show');
      const r = spawnSync('pwsh', ['-NoProfile', '-Command', `function az { $env:AZURE_CONFIG_DIR }; ${line}`], { encoding: 'utf8' });
      assert.equal(r.stdout.trim(), box.azDir, `pwsh, ${homeName}`);
    }
  }
});

test('left alone: a command that already chooses its config dir, and `# raw`', () => {
  const box = sandbox();
  assert.equal(guard(box, "$env:AZURE_CONFIG_DIR='C:/other'; az account show"), null);
  assert.equal(guard(box, 'AZURE_CONFIG_DIR=/other az account show', { tool: 'Bash' }), null);
  assert.equal(guard(box, 'az account show # raw'), null);
  assert.equal(guard(box, 'az account show #raw', { tool: 'Bash' }), null);
});

test('left alone: an unmapped directory, a root with no identity, an identity whose dir is missing', () => {
  const box = sandbox();
  assert.equal(guard(box, 'az account show', { cwd: 'E:\\elsewhere' }), null);
  assert.equal(guard(box, 'az account show', { cwd: 'D:\\work\\gh\\tool' }), null, 'a github root has no identity');
  assert.equal(guard(box, 'az account show', { cwd: 'D:\\work\\ghost\\x' }), null, '~/.azure-absent does not exist');
});

test('left alone: no map, a malformed map, no settings, no allow list', () => {
  assert.equal(guard(sandbox({ map: null }), 'az account show'), null);
  const bad = sandbox();
  writeFileSync(join(bad.config, 'workspaces.json'), '{ not json');
  assert.equal(guard(bad, 'az account show'), null);
  assert.equal(guard(sandbox({ settings: null }), 'az account show'), null);
  assert.equal(guard(sandbox({ settings: { permissions: {} } }), 'az account show'), null);
});

test('never grants: a command the allow list does not cover is not rewritten, so not auto-allowed', () => {
  const box = sandbox();
  for (const command of [
    'az boards work-item update --id 1 --state Done',     // a write: no allow rule
    'az repos pr list --status active',
    'cd src && az account show',                          // `cd` is no allowed command
    'az account show | ConvertFrom-Json',                 // neither is the pipe target
    'az account show; Remove-Item -Recurse x',
  ]) {
    assert.equal(guard(box, command), null, command);
  }
  // A rule of the other tool does not count.
  assert.equal(guard(sandbox({ settings: { permissions: { allow: ['Bash(az account show*)'] } } }), 'az account show'), null);
});

test('never grants: redirection, substitution, a subshell or a backtick keeps the line out', () => {
  const box = sandbox();
  for (const command of [
    'az account show > out.json',
    'az account show 2> err.txt',
    'az boards query --wiql "$(Get-Content q.wiql)"',
    'az boards query --wiql (Get-Content q.wiql)',
    'az boards query `\n  --wiql x',
    'az account show | & { Remove-Item x }',
  ]) {
    assert.equal(guard(box, command), null, command);
  }
  assert.equal(guard(box, 'az account show `echo hi`', { tool: 'Bash' }), null);
});

test('a line that merely names az is left alone', () => {
  const box = sandbox();
  for (const command of ['echo "az account show"', 'Get-ChildItem az', 'ls /tmp/az']) {
    assert.equal(guard(box, command, { tool: command.startsWith('ls') ? 'Bash' : 'PowerShell' }), null, command);
  }
});

test('composes with the guards and the output filter: one rewrite, an ask is never rewritten', () => {
  const box = sandbox();
  // A command that asks (`az account set` is machine-global): the ask wins, nothing is rewritten.
  const asked = guard(box, 'az account show; az account set --subscription Sub');
  assert.equal(asked.permissionDecision, 'ask');
  assert.equal(asked.updatedInput, undefined);
  // The output filter still rewrites what it always did, in a mapped directory, with no az prefix.
  const filtered = guard(box, 'dotnet test');
  assert.equal(filtered.permissionDecision, 'allow');
  assert.match(filtered.updatedInput.command, /^\$global:__rc = 0; & \{ dotnet test 2>&1;/);
  assert.doesNotMatch(filtered.updatedInput.command, /AZURE_CONFIG_DIR/);
});
