#!/usr/bin/env node
/**
 * Tests for hooks/format-on-edit.js. Zero dependencies — `node:test` on Node 18+.
 *
 *   node --test "tools/*.test.mjs"
 *
 * The whole file runs the hook with `--dry-run`, which prints the formatter invocation instead of
 * performing it. That is the only way to assert the routing on any machine: the real run needs the
 * .NET SDK, an installed node_modules tree, or both, and a test that formats real files would
 * rewrite them. So every case fabricates a project layout in a temp directory and asserts *which*
 * formatter the hook chose — and, far more often, that it chose none.
 *
 * Generated by Claude Code at the user's request.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const HOOK = join(dirname(fileURLToPath(import.meta.url)), '..', 'hooks', 'format-on-edit.js');
const created = [];

process.on('exit', () => {
  for (const root of created) {
    try { rmSync(root, { recursive: true, force: true }); } catch { /* tmp, let the OS have it */ }
  }
});

/**
 * Build a project layout under a temp root. `files` maps a relative path to its content;
 * a path ending in `/` creates a directory. Returns the absolute root.
 */
function fixture(files) {
  const root = mkdtempSync(join(tmpdir(), 'fmt-'));
  created.push(root);
  for (const [rel, content] of Object.entries(files)) {
    const full = join(root, rel);
    if (rel.endsWith('/')) { mkdirSync(full, { recursive: true }); continue; }
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
  return root;
}

/** Run the hook in dry-run mode and return what it decided to invoke ('' = nothing). */
function run(payload) {
  const input = typeof payload === 'string' ? payload : JSON.stringify(payload);
  const result = spawnSync(process.execPath, [HOOK, '--dry-run'], { input, encoding: 'utf8' });
  assert.equal(result.status, 0, 'the hook must always exit 0, whatever happens');
  return result.stdout.trim();
}

/** An installed prettier, as the package manager leaves it: the shims of `.bin` (both spellings, one per platform). */
const INSTALLED = { 'node_modules/.bin/prettier': '', 'node_modules/.bin/prettier.cmd': '' };

const onFile = (file_path) => run({ tool_name: 'Write', tool_input: { file_path } });

test('a C# file in a project that configures a style is formatted with the .NET formatter', () => {
  const root = fixture({
    '.editorconfig': '[*.cs]\nindent_size = 4\n',
    'src/App/App.csproj': '<Project Sdk="Microsoft.NET.Sdk" />',
    'src/App/Orders/OrderService.cs': 'class OrderService { }',
  });
  const plan = onFile(join(root, 'src/App/Orders/OrderService.cs'));
  assert.match(plan, /^dotnet format whitespace /);
  assert.match(plan, /whitespace .*[\\/]src[\\/]App --folder/, 'the nearest project directory scopes the run');
  assert.match(plan, /--include .*OrderService\.cs/, 'only the file just touched');
  assert.doesNotMatch(plan, /\.csproj/, 'files, not the project: no MSBuild load and no restore mid-session');
});

test('a web file in a project that configures a formatter goes through its installed prettier, not a package runner', () => {
  const root = fixture({
    'package.json': '{ "name": "web", "devDependencies": {} }',
    '.prettierrc': '{ "singleQuote": true }',
    ...INSTALLED,
    'src/app/order-list.component.ts': 'export class OrderList {}',
  });
  const plan = onFile(join(root, 'src/app/order-list.component.ts'));
  assert.match(plan, /^prettier --write /);
  assert.doesNotMatch(plan, /npx/);
  assert.match(plan, /order-list\.component\.ts/);
});

test('the formatter key may live in the package manifest instead of its own file', () => {
  const root = fixture({
    'package.json': '{ "name": "web", "prettier": { "printWidth": 100 } }',
    ...INSTALLED,
    'src/main.tsx': 'export default function App() { return null; }',
  });
  assert.match(onFile(join(root, 'src/main.tsx')), /^prettier --write /);
});

// ── Doing nothing is the common case, and the one that must never surprise ─────────────────────

test('a file outside any project is left alone', () => {
  const root = fixture({ 'scratch/Notes.cs': 'class Notes { }', 'scratch/script.ts': 'export {};' });
  assert.equal(onFile(join(root, 'scratch/Notes.cs')), '');
  assert.equal(onFile(join(root, 'scratch/script.ts')), '');
});

test('a project with no style configured is left alone', () => {
  // A .csproj but no .editorconfig: the project never chose a style, so there is none to apply.
  const noStyle = fixture({
    'src/App/App.csproj': '<Project Sdk="Microsoft.NET.Sdk" />',
    'src/App/Program.cs': 'class Program { }',
  });
  assert.equal(onFile(join(noStyle, 'src/App/Program.cs')), '');

  // A package.json but no formatter configured anywhere.
  const noFormatter = fixture({
    'package.json': '{ "name": "web" }',
    ...INSTALLED,
    'src/main.ts': 'export {};',
  });
  assert.equal(onFile(join(noFormatter, 'src/main.ts')), '');
});

test('a project whose dependencies are not installed is left alone', () => {
  // Without node_modules the local runner would have to fetch the formatter: never, mid-session.
  const root = fixture({
    'package.json': '{ "name": "web" }',
    '.prettierrc': '{}',
    'src/main.ts': 'export {};',
  });
  assert.equal(onFile(join(root, 'src/main.ts')), '');
});

test('generated and dependency trees are never formatted', () => {
  const root = fixture({
    'package.json': '{ "name": "web" }',
    '.prettierrc': '{}',
    'node_modules/left-pad/index.js': 'module.exports = 1;',
    'src/App/App.csproj': '<Project Sdk="Microsoft.NET.Sdk" />',
    '.editorconfig': '[*.cs]\nindent_size = 4\n',
    'src/App/obj/Debug/App.AssemblyInfo.cs': '// generated',
  });
  assert.equal(onFile(join(root, 'node_modules/left-pad/index.js')), '');
  assert.equal(onFile(join(root, 'src/App/obj/Debug/App.AssemblyInfo.cs')), '');
});

test('an extension with no formatter of its own is left alone', () => {
  const root = fixture({
    '.editorconfig': 'root = true\n',
    'package.json': '{ "name": "web" }',
    '.prettierrc': '{}',
    ...INSTALLED,
    'notes.txt': 'hello',
    'data.csv': 'a,b',
    'query.sql': 'SELECT 1',
  });
  for (const rel of ['notes.txt', 'data.csv', 'query.sql']) {
    assert.equal(onFile(join(root, rel)), '', rel);
  }
});

test('anything unusable is a no-op rather than a failed tool call', () => {
  assert.equal(run(''), '');
  assert.equal(run('not json at all'), '');
  assert.equal(run('{}'), '');
  assert.equal(run({ tool_input: {} }), '');
  assert.equal(run({ tool_input: { file_path: '' } }), '');
  assert.equal(onFile(join(tmpdir(), 'does-not-exist-format-hook', 'Program.cs')), '');
  assert.equal(onFile(tmpdir()), '', 'a directory is not a file to format');
});

test('.json is never formatted, and a node_modules without prettier in it is left alone', () => {
  const root = fixture({
    'package.json': '{ "name": "web", "prettier": {} }',
    ...INSTALLED,
    'settings.json': '{}',
    'src/data.jsonc': '{}',
    'src/a.ts': 'export {};',
  });
  assert.equal(onFile(join(root, 'settings.json')), '');
  assert.equal(onFile(join(root, 'package.json')), '');
  assert.match(onFile(join(root, 'src/a.ts')), /^prettier --write /);

  const bare = fixture({ 'package.json': '{ "name": "web", "prettier": {} }', 'node_modules/': '', 'src/a.ts': 'export {};' });
  assert.equal(onFile(join(bare, 'src/a.ts')), '', 'no installed prettier: nothing to run, and nothing to download');
});

test('the installed prettier is run directly through its bin script, with the file and no package runner', () => {
  const root = fixture({
    'package.json': '{ "name": "web", "prettier": {} }',
    'node_modules/prettier/package.json': '{ "name": "prettier", "bin": { "prettier": "bin/prettier.cjs" } }',
    'node_modules/prettier/bin/prettier.cjs': "require('fs').writeFileSync(process.argv[1] + '.ran', process.argv.slice(2).join('|'));",
    'src/a.ts': 'export {};',
  });
  const file = join(root, 'src/a.ts');
  const result = spawnSync(process.execPath, [HOOK], {
    input: JSON.stringify({ tool_name: 'Write', tool_input: { file_path: file } }), encoding: 'utf8',
  });
  assert.equal(result.status, 0);
  assert.equal(readFileSync(join(root, 'node_modules/prettier/bin/prettier.cjs.ran'), 'utf8'), `--write|${file}`);
});
