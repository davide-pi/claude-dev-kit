#!/usr/bin/env node
/**
 * The `deliver` sweep: after the final gate, closes the process trees the gate started that are still alive and lists
 * every other process that started during the run and names the work folder. It closes nothing on that list.
 *
 *   node sweep.mjs --root <repoRoot> --since <ISO start of the run> [--close]
 *
 * A process is the gate's only when its pid and its start time both match a `{ pid, started }` the gate recorded in
 * `<git dir>/deliver/gate.json` (`procs`): a reused pid is not. Start times are compared to the second, with 2 s of
 * slack, because the gate stamps its own clock at spawn and the process table (CIM `CreationDate` on Windows, `ps
 * lstart` elsewhere) has whole-second precision. A process "names the work folder" when its executable path or
 * command line contains `--root`; one that does not is out of reach of this check. A process that started before
 * `--since`, this script and its parent chain are never reported; descendants of a gate process go with its tree.
 *
 * Output: one row per process `pid | name | started | owner: gate|unknown | action: closed|listed`, then a last JSON
 * line `{"closed":n,"listed":n}`. Without `--close` every row is `listed`. A gate tree is closed with `taskkill /T /F`
 * on Windows and a process-group kill elsewhere. Exit 0; 2 on a usage error. Processes are read through argv, never
 * a shell.
 *
 * Generated by Claude Code at the user's request.
 */

import { spawnSync, execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { readFileSync, realpathSync } from 'node:fs';
import { join, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const { gitDirOf } = createRequire(import.meta.url)('../hooks/lib/git-dir.js');
const WIN = process.platform === 'win32';
const SLACK_MS = 2000;

/** Every process as `{ pid, ppid, name, started (ISO), cmd, path }`; empty when the table can't be read. */
export function readProcesses() {
  try {
    return WIN ? readWindows() : readPosix();
  } catch {
    return [];
  }
}

function readWindows() {
  const query = "Get-CimInstance Win32_Process | Select-Object ProcessId,ParentProcessId,Name,CommandLine,ExecutablePath,"
    + "@{n='Started';e={if ($_.CreationDate) { $_.CreationDate.ToUniversalTime().ToString('o') }}} | ConvertTo-Json -Compress";
  const res = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', query], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, windowsHide: true });
  if (res.status !== 0) return [];
  const rows = [].concat(JSON.parse(res.stdout));
  return rows.filter((r) => r.Started).map((r) => ({
    pid: r.ProcessId, ppid: r.ParentProcessId, name: r.Name ?? '', started: r.Started, cmd: r.CommandLine ?? '', path: r.ExecutablePath ?? '',
  }));
}

function readPosix() {
  const res = spawnSync('ps', ['-eo', 'pid=,ppid=,lstart=,args='], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (res.status !== 0) return [];
  const procs = [];
  for (const line of res.stdout.split('\n')) {
    const m = /^\s*(\d+)\s+(\d+)\s+(\w{3}\s+\w{3}\s+\d+\s+[\d:]{8}\s+\d{4})\s+(.*)$/.exec(line);
    const t = m ? Date.parse(m[3]) : NaN;
    if (!m || Number.isNaN(t)) continue;
    procs.push({ pid: Number(m[1]), ppid: Number(m[2]), name: basename(m[4].split(/\s+/)[0]), started: new Date(t).toISOString(), cmd: m[4], path: '' });
  }
  return procs;
}

/** Closes a process and everything it started; false when the system refused. */
export function killTree(pid) {
  try {
    if (WIN) execFileSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true });
    else process.kill(-pid, 'SIGKILL');
    return true;
  } catch {
    return false;
  }
}

const norm = (s) => { const t = String(s ?? '').replace(/\\/g, '/').replace(/\/+$/, ''); return WIN ? t.toLowerCase() : t; };
const ms = (iso) => Date.parse(iso);

/**
 * `{ rows, closed, listed }`: rows are `{ pid, name, started, owner, action }`. `recorded` is the gate's `[{ pid, started }]`;
 * `readProcesses` and `kill` are injectable.
 */
export function sweep({ root, since, close = false, recorded = [], readProcesses: read = readProcesses, kill = killTree, selfPid = process.pid }) {
  const sinceMs = ms(since) - SLACK_MS;
  const procs = read();
  const byPid = new Map(procs.map((p) => [p.pid, p]));

  const skip = new Set();
  for (let pid = selfPid; pid && !skip.has(pid); pid = byPid.get(pid)?.ppid) skip.add(pid);

  const isGate = (p) => recorded.some((r) => r.pid === p.pid && Math.abs(ms(r.started) - ms(p.started)) <= SLACK_MS);
  const inRun = (p) => ms(p.started) >= sinceMs && !skip.has(p.pid);
  const gate = procs.filter((p) => inRun(p) && isGate(p));

  const covered = new Set(gate.map((p) => p.pid));
  for (let grew = true; grew;) {
    grew = false;
    for (const p of procs) if (!covered.has(p.pid) && covered.has(p.ppid)) { covered.add(p.pid); grew = true; }
  }

  const needle = norm(root);
  const names = (p) => norm(p.cmd).includes(needle) || norm(p.path).includes(needle);
  const unknown = procs.filter((p) => inRun(p) && !covered.has(p.pid) && names(p));

  const rows = [];
  for (const p of gate) {
    const done = close && kill(p.pid);
    rows.push({ pid: p.pid, name: p.name, started: p.started, owner: 'gate', action: done ? 'closed' : 'listed' });
  }
  for (const p of unknown) rows.push({ pid: p.pid, name: p.name, started: p.started, owner: 'unknown', action: 'listed' });
  const closed = rows.filter((r) => r.action === 'closed').length;
  return { rows, closed, listed: rows.length - closed };
}

/** The output lines: a row per process, then the JSON summary. */
export function render({ rows, closed, listed }) {
  return [...rows.map((r) => `${r.pid} | ${r.name} | ${r.started} | owner: ${r.owner} | action: ${r.action}`), JSON.stringify({ closed, listed })];
}

function parseArgs(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--close') a.close = true;
    else if (argv[i] === '--root' || argv[i] === '--since') a[argv[i].slice(2)] = argv[++i];
    else usage(`unknown argument ${argv[i]}`);
  }
  return a;
}

function usage(message) {
  console.error(`sweep: ${message}`);
  process.exit(2);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.root) usage('--root is required');
  if (!args.since || Number.isNaN(ms(args.since))) usage('--since takes an ISO time, e.g. 2026-01-01T10:00:00Z');
  const root = resolve(args.root);
  const gitDir = gitDirOf(root);
  if (!gitDir) usage(`no git repository at ${root}`);
  let recorded = [];
  try { recorded = JSON.parse(readFileSync(join(gitDir, 'deliver', 'gate.json'), 'utf8')).procs ?? []; } catch { /* the gate never ran */ }
  console.log(render(sweep({ root, since: args.since, close: !!args.close, recorded })).join('\n'));
}

const isMain = (() => {
  try { return realpathSync.native(process.argv[1]) === realpathSync.native(fileURLToPath(import.meta.url)); } catch { return false; }
})();

if (isMain) main();
