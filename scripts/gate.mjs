const HERE = dirname(fileURLToPath(import.meta.url));
const { gitDirOf } = createRequire(import.meta.url)('../hooks/lib/git-dir.js');
const WIN = process.platform === 'win32';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const FLAGS = ['--wait', '--supervise', '--force', '--no-scope', '--red'];
const VALUES = ['--root', '--head', '--test', '--dirty', '--unit', '--test-files', '--stuck-minutes', '--max-minutes', '--run', '--lane-add'];
const LISTS = ['--merge', '--lane-remove'];

function parseArgs(argv) {
  const a = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (FLAGS.includes(k)) a[k.slice(2)] = true;
    else if (VALUES.includes(k)) a[k.slice(2)] = argv[++i];
    else if (LISTS.includes(k)) {
      // every token up to the next known option is a ref, a dash-led one included: validated (and refused) later
      a[k.slice(2)] = [];
      while (i + 1 < argv.length && ![...FLAGS, ...VALUES, ...LISTS].includes(argv[i + 1])) a[k.slice(2)].push(argv[++i]);
    } else a._.push(k);
  }
  return a;
}

function usage(message) {
  console.error(`gate: ${message}`);
  process.exit(2);
}

/** A minutes option: a finite number >= 0, else usage. */
function minutes(args, name, fallback) {
  const v = args[name];
  if (v === undefined) return fallback;
  const n = Number(v);
  if (v.trim() === '' || !Number.isFinite(n) || n < 0) usage(`--${name} takes a number of minutes (0 or more), got "${v}"`);
  return n;
}

// What a good `--merge` could not remove, added to every last line this process prints.
let LEFTOVER = [];

function emit(gate, exit, extra = {}) {
  console.log(JSON.stringify({ gate, test: '', outside: [], formatOnly: [], tree: '', greenAt: '', seconds: 0, ...(LEFTOVER.length ? { leftover: LEFTOVER } : {}), ...extra }));
  process.exit(exit);
}

function readState(dir) {
  for (let i = 0; i < 5; i++) {
    try { return JSON.parse(readFileSync(join(dir, 'gate.json'), 'utf8')); } catch (e) {
      if (e.code === 'ENOENT') return {};
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 40);
    }
  }
  return {};
}

const writeState = (dir, state) => writeFileSync(join(dir, 'gate.json'), JSON.stringify(state, null, 2));

function killTree(pid) {
  try {
    if (WIN) execFileSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true });
    else process.kill(-pid, 'SIGKILL');
  } catch { /* already gone */ }
}

function pidAlive(pid) {
  try { process.kill(pid, 0); return true; } catch (e) { return e.code === 'EPERM'; }
}

/** Start time (epoch ms) of a live process, null when it can't be read. */
function startTimeOf(pid) {
  try {
    const res = WIN
      ? spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', `(Get-Process -Id ${pid}).StartTime.ToUniversalTime().ToString('o')`], { encoding: 'utf8', windowsHide: true })
      : spawnSync('ps', ['-o', 'lstart=', '-p', String(pid)], { encoding: 'utf8' });
    const t = Date.parse((res.stdout ?? '').trim());
    return res.status === 0 && !Number.isNaN(t) ? t : null;
  } catch { return null; }
}

const REUSE_CHECK_MS = 30000;

/**
 * The supervisor writes its pid and start time right after it starts; until then a recent run counts as alive. A live pid
 * whose start time differs from the stored one is a reused pid, so the supervisor is dead. The start time is read at most
 * every 30 s per `memo` (the read costs a process spawn); one that can't be read counts as alive.
 */
function supervisorAlive(run, memo = {}) {
  if (!run.pid) return Date.now() - run.startedAt < 30000;
  if (!pidAlive(run.pid)) return false;
  if (run.pidStarted && (!memo.at || Date.now() - memo.at >= REUSE_CHECK_MS)) {
    memo.at = Date.now();
    const actual = startTimeOf(run.pid);
    if (actual !== null && Math.abs(actual - run.pidStarted) > 2000) return false;
  }
  return true;
}

/** Notes a process the gate started in `gate.json` as `{ pid, started }` (the last 50), for `sweep.mjs` to match by pid and start time. */
function recordProcess(dir, pid) {
  const state = readState(dir);
  state.procs = [...(state.procs ?? []), { pid, started: new Date().toISOString() }].slice(-50);
  writeState(dir, state);
}

/** Runs the command once; resolves `{ code }` when it exits, `{ stalled: true }` after the stuck check killed it. */
function runOnce(command, root, logPath, stuckMs) {
  return new Promise((done) => {
    const fd = openSync(logPath, 'a');
    let last = statSync(logPath).size;
    let settled = false;
    let timer;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      clearInterval(timer);
      closeSync(fd);
      done(value);
    };
    const child = spawn(command, { shell: true, cwd: root, stdio: ['ignore', fd, fd], detached: !WIN, windowsHide: true });
    if (child.pid) recordProcess(dirname(logPath), child.pid);
    child.on('exit', (code) => finish({ code: code ?? 1 }));
    child.on('error', () => finish({ code: 1 }));
    if (stuckMs > 0) {
      timer = setInterval(() => {
        const size = statSync(logPath).size;
        if (size === last) { killTree(child.pid); finish({ stalled: true }); } else last = size;
      }, stuckMs);
    }
  });
}

/** The detached supervisor: runs the command (twice at most), then records how it ended, if its run is still the current one. */
async function supervise(dir, root, id) {
  const state = readState(dir);
  const run = state.run;
  if (!run || run.id !== id) return;
  run.pidStarted = startTimeOf(process.pid) ?? undefined;
  run.pid = process.pid;
  writeState(dir, state);
  const logPath = join(dir, 'gate.log');
  let outcome = { code: 1 };
  try {
    for (let attempt = 1; attempt <= 2; attempt++) {
      outcome = await runOnce(run.command, root, logPath, run.stuckMinutes * 60000);
      if (!outcome.stalled) break;
    }
  } catch {
    outcome = { code: 1 };
  }
  const fresh = readState(dir);
  if (fresh.run?.id !== id) return;
  fresh.run = { ...fresh.run, status: 'done', exitCode: outcome.code ?? 1, timedOut: !!outcome.stalled, endedAt: Date.now() };
  writeState(dir, fresh);
}

const tail = (text, n) => text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean).slice(-n);

/** The last test line the log shows (node `--test` marks), else its last non-empty line. */
function lastTestSeen(log) {
  const lines = tail(log, 400);
  for (let i = lines.length - 1; i >= 0; i--) {
    const m = /^(?:[▶✔✖]|# Subtest:)\s*(.+?)(?:\s+\(\d[\d.]*ms\))?$/.exec(lines[i]);
    if (m) return m[1];
  }
  return lines.at(-1) ?? '';
}

/** A name that is a test file (a file that failed to load), not a test. */
function isTestFile(name, testFiles) {
  const n = name.replace(/\\/g, '/');
  return /\.(test|spec)\.[cm]?[jt]sx?$/.test(n) || testFiles.some((f) => n.endsWith(f.replace(/\\/g, '/')));
}

/** Names of failed tests in a runner's output (node spec and TAP, dotnet, vitest, jest), up to 5; file-level failures are no test. */
export function failedTests(log, testFiles = []) {
  const names = [];
  for (const line of log.split(/\r?\n/)) {
    const m = /^\s*✖\s+(.+?)(?:\s+\(\d[\d.]*ms\))?\s*$/.exec(line) || /^\s*not ok \d+ - (.+)$/.exec(line)
      || /^\s*Failed\s+(\S+)/.exec(line) || /^\s*●\s+(.+? › .+)$/.exec(line)
      || /^\s*FAIL\s+\S+\s+>\s+(.+)$/.exec(line) || /^\s*×\s+(.+?)(?:\s+\d[\d.]*m?s)?\s*$/.exec(line);
    if (m && !/^failing tests:?$/.test(m[1]) && !isTestFile(m[1], testFiles) && !names.includes(m[1])) names.push(m[1]);
  }
  return names.slice(0, 5);
}

const GUARD = join(HERE, '..', 'hooks', 'scope-guard.js');

/** The scope check through `scope-guard.js --check`: `{ verdict: 'clean' | 'outside' | 'unchecked', outside }`. */
function scopeCheck(root, head, dirty) {
  const res = spawnSync(process.execPath, [GUARD, '--check', head, ...(dirty ? ['--dirty', dirty] : [])], { cwd: root, encoding: 'utf8', windowsHide: true });
  const outside = (res.stdout ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  if (res.status === 0) return { verdict: 'clean', outside: [] };
  if (res.status === 1 && outside.length) return { verdict: 'outside', outside };
  process.stderr.write(res.stderr || 'gate: the scope check did not complete\n');
  return { verdict: 'unchecked', outside };
}

const git = (root, args, env) => spawnSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, ...env }, windowsHide: true });
const out = (res) => (res.stdout ?? '').trim();

const LANE_PREFIX = 'deliver-lane/';
// A lane's own commits and the merge commits are scratch: the merge ends with the start branch back at its head.
const LANE_GIT = ['-c', 'user.name=deliver-lane', '-c', 'user.email=deliver-lane@localhost', '-c', 'commit.gpgsign=false'];
const laneGit = (root, args) => git(root, [...LANE_GIT, ...args]);

/** Adds `<root>-lane-<name>` (the next free name) as a worktree on a new branch `deliver-lane/<name>` from `head`; the last line is `{lane,path,branch}`. */
function laneAdd(root, dir0, name, head) {
  if (!/^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(name)) usage(`--lane-add takes a plain name, got "${name}"`);
  if (!head) usage('--head is required with --lane-add');
  if (head.startsWith('-')) usage(`--head takes a revision, got "${head}"`);
  let lane = name;
  for (let n = 2; n < 100; n++) {
    const taken = git(root, ['rev-parse', '--verify', '--quiet', `refs/heads/${LANE_PREFIX}${lane}`]).status === 0 || existsSync(`${root}-lane-${lane}`);
    if (!taken) break;
    lane = `${name}-${n}`;
  }
  const path = `${root}-lane-${lane}`;
  const branch = `${LANE_PREFIX}${lane}`;
  const res = git(root, ['worktree', 'add', '-b', branch, '--end-of-options', path, head]);
  if (res.status !== 0) usage(`git worktree add failed: ${(res.stderr ?? '').trim()}`);
  // The scope hook only lets a lane edit under an active perimeter of its own branch.
  const laneDir = gitDirOf(path);
  try {
    const text = readFileSync(join(dir0, 'deliver', 'perimeter.md'), 'utf8');
    mkdirSync(join(laneDir, 'deliver'), { recursive: true });
    writeFileSync(join(laneDir, 'deliver', 'perimeter.md'), text.replace(/^branch:.*$/im, `branch: ${branch}`));
  } catch { /* no perimeter at the start: the lane has none either */ }
  console.log(JSON.stringify({ lane, path, branch }));
  process.exit(0);
}

/** The worktree path of each branch, from `git worktree list --porcelain`. */
function worktreesByBranch(root) {
  const map = new Map();
  let path = '';
  for (const line of out(git(root, ['worktree', 'list', '--porcelain'])).split(/\r?\n/)) {
    if (line.startsWith('worktree ')) path = line.slice(9);
    else if (line.startsWith('branch refs/heads/')) map.set(line.slice(18), path);
  }
  return map;
}

/** Exits 2 unless every ref is an existing `deliver-lane/*` branch (a plain name, never an option or a revision range). */
function laneRefs(root, list, flag) {
  if (!list.length) usage(`${flag} takes at least one lane branch`);
  for (const ref of list) {
    if (!ref.startsWith(LANE_PREFIX) || !/^[A-Za-z0-9][A-Za-z0-9._/-]*$/.test(ref) || ref.includes('..')) usage(`${flag} takes ${LANE_PREFIX}* branch names, got "${ref}"`);
    if (git(root, ['rev-parse', '--verify', '--quiet', `refs/heads/${ref}`]).status !== 0) usage(`${flag}: no branch "${ref}"`);
  }
}

const nulList = (res) => (res.stdout ?? '').split('\0').filter(Boolean);
/** Files of the tree at `cwd` that differ from `rev` (tracked) or are untracked; `rev` null: only the unstaged and untracked ones. */
function dirtyFiles(cwd, rev) {
  return [
    ...nulList(git(cwd, ['-c', 'core.quotepath=false', 'diff', '--name-only', '-z', ...(rev ? ['--end-of-options', rev] : [])])),
    ...nulList(git(cwd, ['-c', 'core.quotepath=false', 'ls-files', '--others', '--exclude-standard', '-z'])),
  ];
}

/** Refuses (exit 2, nothing written) a start tree whose staged or uncommitted files the merge could take or overwrite. */
function checkStartTree(root, start, list, trees) {
  if (git(root, ['diff', '--cached', '--quiet']).status !== 0) usage('--merge: the start tree has staged changes; commit or unstage them first');
  const mine = new Set(dirtyFiles(root, null));
  if (!mine.size) return;
  for (const ref of list) {
    const lane = trees.get(ref);
    const changed = new Set([
      ...nulList(git(root, ['-c', 'core.quotepath=false', 'diff', '--name-only', '-z', '--end-of-options', start, ref])),
      ...(lane ? dirtyFiles(lane, start) : []),
    ]);
    const clash = [...mine].filter((f) => changed.has(f));
    if (clash.length) usage(`--merge: the start tree has uncommitted changes in files ${ref} changes: ${clash.join(', ')}; commit or stash them, or run the plan serially`);
  }
}

/**
 * Commits each lane's work, merges the lane branches into the current branch one by one and ends with the branch back at
 * `head` and the merged change uncommitted in the tree, like a serial run. A conflict (or a refused merge) is aborted, the
 * branch put back and `{ red: true, files, text }` returned; when that rollback fails `text` says so. The lane worktrees and
 * branches are removed after a good merge only; what could not be removed is in `leftover`.
 */
function mergeLanes(root, list) {
  laneRefs(root, list, '--merge');
  const start = out(git(root, ['rev-parse', 'HEAD']));
  const trees = worktreesByBranch(root);
  checkStartTree(root, start, list, trees);
  const lanePaths = list.filter((ref) => trees.has(ref)).map((ref) => trees.get(ref));
  for (const path of lanePaths) {
    const added = laneGit(path, ['add', '-A']);
    if (added.status !== 0) usage(`could not stage the lane at ${path}: ${(added.stderr ?? '').trim()}`);
    const staged = git(path, ['diff', '--cached', '--quiet']).status;
    if (staged > 1) usage(`could not read the staged changes of the lane at ${path}`);
    if (staged === 1) {
      const res = laneGit(path, ['commit', '--no-verify', '-q', '-m', 'deliver lane']);
      if (res.status !== 0) usage(`could not commit the lane at ${path}: ${(res.stderr ?? '').trim()}`);
    }
  }
  const result = { red: false, files: [], text: '', leftover: [] };
  for (const [i, ref] of list.entries()) {
    const res = laneGit(root, ['merge', '--no-ff', '--no-edit', '--no-verify', '--end-of-options', ref]);
    if (res.status === 0) continue;
    result.red = true;
    result.files = out(git(root, ['diff', '--name-only', '--diff-filter=U'])).split(/\r?\n/).filter(Boolean);
    result.text = result.files.length ? `merge conflict in ${ref}` : tail(`${res.stdout ?? ''}\n${res.stderr ?? ''}`, 3).join(' | ');
    // a refused merge has nothing to abort: only a merge still in progress after the abort, a failed reset or a moved head is a failed rollback
    git(root, ['merge', '--abort']);
    const inMerge = git(root, ['rev-parse', '-q', '--verify', 'MERGE_HEAD']).status === 0;
    const resetFailed = i > 0 && git(root, ['reset', '--keep', start]).status !== 0;
    const now = out(git(root, ['rev-parse', 'HEAD']));
    if (inMerge || resetFailed || now !== start) {
      result.text = `rollback failed: the start branch is at ${now || '(unknown)'}, not at ${start}; check git status in ${root} (${result.text})`;
    }
    break;
  }
  if (!result.red) {
    git(root, ['reset', '-q', start]);
    for (const path of lanePaths) {
      const res = git(root, ['worktree', 'remove', '--force', path]);
      if (res.status !== 0) result.leftover.push(`worktree ${path}: ${(res.stderr ?? '').trim()}`);
    }
    for (const ref of list) {
      const res = git(root, ['branch', '-D', ref]);
      if (res.status !== 0) result.leftover.push(`branch ${ref}: ${(res.stderr ?? '').trim()}`);
    }
  }
  return result;
}

/** Force-removes the worktree and the branch of each lane branch and prints what happened to each. */
function laneRemove(root, list) {
  laneRefs(root, list, '--lane-remove');
  const trees = worktreesByBranch(root);
  const removed = list.map((branch) => {
    const path = trees.get(branch) ?? '';
    const errors = [];
    // doubled: only a double force removes a locked worktree
    if (path) {
      const res = git(root, ['worktree', 'remove', '--force', '--force', path]);
      if (res.status !== 0) errors.push(`worktree: ${(res.stderr ?? '').trim()}`);
    }
    const res = git(root, ['branch', '-D', branch]);
    if (res.status !== 0) errors.push(`branch: ${(res.stderr ?? '').trim()}`);
    return { branch, path, ok: !errors.length, ...(errors.length ? { error: errors.join(' | ') } : {}) };
  });
  console.log(JSON.stringify({ removed }));
  process.exit(removed.every((x) => x.ok) ? 0 : 1);
}

/** The tree of the working directory, hashed through a temporary index so the real one stays untouched; '' when git failed. */
function treeHash(root, dir) {
  const env = { GIT_INDEX_FILE: join(dir, `index.${process.pid}`) };
  try {
    // Seeding the temporary index with the real one lets git reuse its stat data instead of rehashing every file.
    const real = out(git(root, ['rev-parse', '--git-path', 'index']));
    if (real) copyFileSync(resolve(root, real), env.GIT_INDEX_FILE);
  } catch { /* no index yet: git builds one */ }
  try {
    if (git(root, ['add', '-A'], env).status !== 0) return '';
    const res = git(root, ['write-tree'], env);
    return res.status === 0 ? out(res) : '';
  } finally {
    rmSync(env.GIT_INDEX_FILE, { force: true });
  }
}

/** Changed files whose diff against `head` is empty once whitespace and blank lines are ignored. */
function formatOnlyFiles(root, head) {
  const list = git(root, ['-c', 'core.quotepath=false', 'diff', '--name-only', '-z', '--end-of-options', head]);
  if (list.status !== 0) return [];
  return (list.stdout ?? '').split('\0').filter(Boolean).filter((f) => {
    const res = git(root, ['diff', '--ignore-all-space', '--ignore-blank-lines', '--end-of-options', head, '--', f]);
    return res.status === 0 && !out(res);
  });
}

/** The SHA-256 of each file (repo-relative path), empty for one that doesn't exist. */
function hashFiles(root, files) {
  const hashes = {};
  for (const f of files) {
    try { hashes[f] = createHash('sha256').update(readFileSync(join(root, f))).digest('hex'); } catch { hashes[f] = ''; }
  }
  return hashes;
}

/** A runner whose failed tests `failedTests` can read, from the command line; null when none matches. */
const readableRunner = (command) => /\bnode(\.exe)?\b.*--test\b|\bdotnet\s+test\b|\bvitest\b|\bjest\b/.exec(command)?.[0] ?? null;

function finalize(dir, state) {
  const run = state.run;
  const o = run.opts;
  if (o.leftover?.length) LEFTOVER = o.leftover;
  const seconds = Math.round(((run.endedAt ?? Date.now()) - run.startedAt) / 1000);
  const base = { tree: o.tree ?? '', seconds, ...(o.proofDropped ? { proof: 'dropped' } : {}) };
  let log = '';
  try { log = readFileSync(join(dir, 'gate.log'), 'utf8'); } catch { /* no output */ }
  state.run = null;
  writeState(dir, state);
  if (run.timedOut) emit('red: timeout', 1, { ...base, test: lastTestSeen(log) });
  if (o.red) {
    if (run.exitCode === 0) emit('red: no failing test', 1, base);
    const names = failedTests(log, o.testFiles);
    if (!names.length) emit('red', 1, { ...base, test: tail(log, 5).join(' | ') });
    state.proof = { names, files: hashFiles(o.root, o.testFiles) };
    writeState(dir, state);
    emit('red-proven', 0, { ...base, test: names.join('; ') });
  }
  if (run.exitCode !== 0) emit('red', 1, { ...base, test: failedTests(log).join('; ') || tail(log, 5).join(' | ') });
  if (!o.noScope) {
    const scope = scopeCheck(o.root, o.head, o.dirty);
    if (scope.verdict === 'unchecked') process.exit(2);
    if (scope.verdict === 'outside') emit('red: scope', 1, { ...base, outside: scope.outside });
  }
  const formatOnly = formatOnlyFiles(o.root, o.head);
  const greenAt = new Date().toISOString();
  state.green = { tree: o.tree, head: o.head, dirty: o.dirty, test: o.command, scope: !o.noScope, greenAt, formatOnly };
  delete state.proof;
  writeState(dir, state);
  emit('green', 0, { ...base, formatOnly, greenAt });
}

async function waitFor(dir, maxMinutes) {
  const deadline = Date.now() + maxMinutes * 60000;
  const memo = {};
  for (;;) {
    const state = readState(dir);
    if (!state.run) usage('no run to wait for');
    if (state.run.status === 'done') return finalize(dir, state);
    const seconds = Math.round((Date.now() - state.run.startedAt) / 1000);
    if (!supervisorAlive(state.run, memo)) {
      // It may have written its result between the read above and the liveness check.
      const fresh = readState(dir);
      if (fresh.run?.status === 'done') return finalize(dir, fresh);
      fresh.run = null;
      writeState(dir, fresh);
      emit('red', 1, { test: 'supervisor died', seconds });
    }
    if (Date.now() >= deadline) emit('running', 3, { seconds });
    await sleep(150);
  }
}

/** Records the run, starts the detached supervisor and waits for it. */
function startRun(dir, state, root, run, maxMinutes) {
  const id = randomUUID();
  writeFileSync(join(dir, 'gate.log'), '');
  state.run = { id, status: 'running', startedAt: Date.now(), ...run };
  writeState(dir, state);
  spawn(process.execPath, [fileURLToPath(import.meta.url), '--supervise', '--root', root, '--run', id], { detached: true, stdio: 'ignore', windowsHide: true }).unref();
  return waitFor(dir, maxMinutes);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.root) usage('--root is required');
  const root = resolve(args.root);
  const dir0 = gitDirOf(root);
  if (!dir0) usage(`no git repository at ${root}`);
  const dir = join(dir0, 'deliver');
  mkdirSync(dir, { recursive: true });

  if (args.supervise) return supervise(dir, root, args.run);
  if (args['lane-add'] !== undefined) return laneAdd(root, dir0, args['lane-add'], args.head);
  if (args['lane-remove'] !== undefined) return laneRemove(root, args['lane-remove']);
  const maxMinutes = minutes(args, 'max-minutes', 9);
  const stuckMinutes = minutes(args, 'stuck-minutes', 5);
  if (args.wait) return waitFor(dir, maxMinutes);

  const state = readState(dir);
  if (state.run?.status === 'running' && supervisorAlive(state.run)) usage('a gate is already running here: use --wait');
  if (args.red) {
    if (!args.unit) usage('--unit is required with --red');
    if (!readableRunner(args.unit)) usage("--unit runs a test runner the gate can't read (dotnet test, node --test, vitest, jest)");
    return startRun(dir, state, root, {
      command: args.unit, stuckMinutes,
      opts: { root, red: true, testFiles: (args['test-files'] ?? '').split(',').filter(Boolean) },
    }, maxMinutes);
  }
  if (!args.test) usage('--test is required');
  if (!args.head) usage('--head is required');
  if (args.head.startsWith('-')) usage(`--head takes a revision, got "${args.head}"`);
  if (args.merge) {
    const merged = mergeLanes(root, args.merge);
    LEFTOVER = merged.leftover;
    if (merged.red) emit('red: merge', 1, { test: merged.text, outside: merged.files });
  }
  const noScope = !!args['no-scope'];
  const dirty = args.dirty ?? '';
  const proofDropped = !!args.force && !!state.proof;
  if (proofDropped) { delete state.proof; writeState(dir, state); }
  const changed = state.proof ? Object.entries(state.proof.files).filter(([f, h]) => hashFiles(root, [f])[f] !== h).map(([f]) => f) : [];
  if (changed.length) emit('red: tests changed', 1, { test: changed.join('; ') });
  const tree = treeHash(root, dir);
  if (!tree) usage('git could not hash the working tree');
  if (!noScope) {
    const scope = scopeCheck(root, args.head, dirty);
    if (scope.verdict === 'unchecked') process.exit(2);
    if (scope.verdict === 'outside') emit('red: scope', 1, { tree, outside: scope.outside, ...(proofDropped ? { proof: 'dropped' } : {}) });
  }
  const g = state.green;
  if (!args.force && !state.proof && g && g.tree === tree && g.head === args.head && g.dirty === dirty && g.test === args.test && g.scope === !noScope) {
    emit('skipped: tree unchanged', 0, { tree, greenAt: g.greenAt, formatOnly: g.formatOnly ?? [] });
  }
  return startRun(dir, state, root, {
    command: args.test, stuckMinutes,
    opts: { root, head: args.head, dirty, noScope, tree, command: args.test, proofDropped, leftover: LEFTOVER },
  }, maxMinutes);
}

const isMain = (() => {
  try { return realpathSync.native(process.argv[1]) === realpathSync.native(fileURLToPath(import.meta.url)); } catch { return false; }
})();

if (isMain) {
  main().catch((e) => {
    console.error(`gate: ${e?.stack ?? e}`);
    process.exit(2);
  });
}
