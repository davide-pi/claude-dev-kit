#!/usr/bin/env node
/**
 * The `deliver` gate: runs a block's test command under a stuck check and answers with one JSON line.
 *
 *   node gate.mjs --root <repoRoot> --head <start head> --test "<command>"
 *        [--dirty a,b] [--stuck-minutes 5] [--max-minutes 9] [--force] [--no-scope]
 *   node gate.mjs --root <repoRoot> --red --unit "<command>" --test-files <a,b>
 *   node gate.mjs --root <repoRoot> --wait
 *
 * `--red` runs the unit command only, proves at least one test fails and stores the names with the SHA-256 of each
 * test file; the next plain run is green only while those files are unchanged. The tree hash (a temporary index,
 * the real one untouched) lets an unchanged tree skip the run; `hooks/scope-guard.js` checks the perimeter.
 *
 * The command runs under a detached supervisor (this script with the hidden `--supervise --run <id>` flags) that
 * writes its output to `<git dir>/deliver/gate.log`, compares the log size every `--stuck-minutes` (no growth: kill
 * the process tree, run once more; a second stall is `red: timeout`; 0 turns the check off) and stores the result in
 * `<git dir>/deliver/gate.json`, only while that file still holds its run id. A second run while the recorded
 * supervisor is alive exits 2; a dead supervisor is `red` ("supervisor died"). The foreground call polls the state
 * up to `--max-minutes`, then prints `running` and exits 3; `--wait` polls again. Minutes may be fractions.
 *
 * Last stdout line: `{gate,test,outside,formatOnly,tree,greenAt,seconds}`. Exit 0 green, 1 red, 2 not checked
 * (bad arguments, no git repository, a scope or git step that failed), 3 still running. git runs through argv,
 * never a shell.
 *
 * Generated by Claude Code at the user's request.
 */

import { spawn, spawnSync, execFileSync } from 'node:child_process';
import { createHash, randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync, openSync, closeSync, statSync, rmSync, realpathSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const { gitDirOf } = createRequire(import.meta.url)('../hooks/lib/git-dir.js');
const WIN = process.platform === 'win32';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function parseArgs(argv) {
  const a = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (['--wait', '--supervise', '--force', '--no-scope', '--red'].includes(k)) a[k.slice(2)] = true;
    else if (['--root', '--head', '--test', '--dirty', '--unit', '--test-files', '--stuck-minutes', '--max-minutes', '--run'].includes(k)) a[k.slice(2)] = argv[++i];
    else a._.push(k);
  }
  return a;
}

function usage(message) {
  console.error(`gate: ${message}`);
  process.exit(2);
}

/** A minutes option: a finite number >= 0, else usage. */
function minutes(args, name, fallback) {
  const v = args[name];
  if (v === undefined) return fallback;
  const n = Number(v);
  if (v.trim() === '' || !Number.isFinite(n) || n < 0) usage(`--${name} takes a number of minutes (0 or more), got "${v}"`);
  return n;
}

function emit(gate, exit, extra = {}) {
  console.log(JSON.stringify({ gate, test: '', outside: [], formatOnly: [], tree: '', greenAt: '', seconds: 0, ...extra }));
  process.exit(exit);
}

function readState(dir) {
  for (let i = 0; i < 5; i++) {
    try { return JSON.parse(readFileSync(join(dir, 'gate.json'), 'utf8')); } catch (e) {
      if (e.code === 'ENOENT') return {};
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 40);
    }
  }
  return {};
}

const writeState = (dir, state) => writeFileSync(join(dir, 'gate.json'), JSON.stringify(state, null, 2));

function killTree(pid) {
  try {
    if (WIN) execFileSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true });
    else process.kill(-pid, 'SIGKILL');
  } catch { /* already gone */ }
}

function pidAlive(pid) {
  try { process.kill(pid, 0); return true; } catch (e) { return e.code === 'EPERM'; }
}

/** The supervisor writes its pid right after it starts; until then a recent run counts as alive. */
const supervisorAlive = (run) => (run.pid ? pidAlive(run.pid) : Date.now() - run.startedAt < 30000);

/** Runs the command once; resolves `{ code }` when it exits, `{ stalled: true }` after the stuck check killed it. */
function runOnce(command, root, logPath, stuckMs) {
  return new Promise((done) => {
    const fd = openSync(logPath, 'a');
    let last = statSync(logPath).size;
    let settled = false;
    let timer;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      clearInterval(timer);
      closeSync(fd);
      done(value);
    };
    const child = spawn(command, { shell: true, cwd: root, stdio: ['ignore', fd, fd], detached: !WIN, windowsHide: true });
    child.on('exit', (code) => finish({ code: code ?? 1 }));
    child.on('error', () => finish({ code: 1 }));
    if (stuckMs > 0) {
      timer = setInterval(() => {
        const size = statSync(logPath).size;
        if (size === last) { killTree(child.pid); finish({ stalled: true }); } else last = size;
      }, stuckMs);
    }
  });
}

/** The detached supervisor: runs the command (twice at most), then records how it ended, if its run is still the current one. */
async function supervise(dir, root, id) {
  const state = readState(dir);
  const run = state.run;
  if (!run || run.id !== id) return;
  run.pid = process.pid;
  writeState(dir, state);
  const logPath = join(dir, 'gate.log');
  let outcome = { code: 1 };
  try {
    for (let attempt = 1; attempt <= 2; attempt++) {
      outcome = await runOnce(run.command, root, logPath, run.stuckMinutes * 60000);
      if (!outcome.stalled) break;
    }
  } catch {
    outcome = { code: 1 };
  }
  const fresh = readState(dir);
  if (fresh.run?.id !== id) return;
  fresh.run = { ...fresh.run, status: 'done', exitCode: outcome.code ?? 1, timedOut: !!outcome.stalled, endedAt: Date.now() };
  writeState(dir, fresh);
}

const tail = (text, n) => text.split(/\r?\n/).map((l) => l.trim()).filter(Boolean).slice(-n);

/** The last test line the log shows (node `--test` marks), else its last non-empty line. */
function lastTestSeen(log) {
  const lines = tail(log, 400);
  for (let i = lines.length - 1; i >= 0; i--) {
    const m = /^(?:[▶✔✖]|# Subtest:)\s*(.+?)(?:\s+\(\d[\d.]*ms\))?$/.exec(lines[i]);
    if (m) return m[1];
  }
  return lines.at(-1) ?? '';
}

/** A name that is a test file (a file that failed to load), not a test. */
function isTestFile(name, testFiles) {
  const n = name.replace(/\\/g, '/');
  return /\.(test|spec)\.[cm]?[jt]sx?$/.test(n) || testFiles.some((f) => n.endsWith(f.replace(/\\/g, '/')));
}

/** Names of failed tests in a runner's output (node spec and TAP, dotnet, vitest, jest), up to 5; file-level failures are no test. */
export function failedTests(log, testFiles = []) {
  const names = [];
  for (const line of log.split(/\r?\n/)) {
    const m = /^\s*✖\s+(.+?)(?:\s+\(\d[\d.]*ms\))?\s*$/.exec(line) || /^\s*not ok \d+ - (.+)$/.exec(line)
      || /^\s*Failed\s+(\S+)/.exec(line) || /^\s*●\s+(.+? › .+)$/.exec(line)
      || /^\s*FAIL\s+\S+\s+>\s+(.+)$/.exec(line) || /^\s*×\s+(.+?)(?:\s+\d[\d.]*m?s)?\s*$/.exec(line);
    if (m && !/^failing tests:?$/.test(m[1]) && !isTestFile(m[1], testFiles) && !names.includes(m[1])) names.push(m[1]);
  }
  return names.slice(0, 5);
}

const GUARD = join(HERE, '..', 'hooks', 'scope-guard.js');

/** The scope check through `scope-guard.js --check`: `{ verdict: 'clean' | 'outside' | 'unchecked', outside }`. */
function scopeCheck(root, head, dirty) {
  const res = spawnSync(process.execPath, [GUARD, '--check', head, ...(dirty ? ['--dirty', dirty] : [])], { cwd: root, encoding: 'utf8', windowsHide: true });
  const outside = (res.stdout ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  if (res.status === 0) return { verdict: 'clean', outside: [] };
  if (res.status === 1 && outside.length) return { verdict: 'outside', outside };
  process.stderr.write(res.stderr || 'gate: the scope check did not complete\n');
  return { verdict: 'unchecked', outside };
}

const git = (root, args, env) => spawnSync('git', args, { cwd: root, encoding: 'utf8', env: { ...process.env, ...env }, windowsHide: true });
const out = (res) => (res.stdout ?? '').trim();

/** The tree of the working directory, hashed through a temporary index so the real one stays untouched; '' when git failed. */
function treeHash(root, dir) {
  const env = { GIT_INDEX_FILE: join(dir, `index.${process.pid}`) };
  try {
    if (git(root, ['add', '-A'], env).status !== 0) return '';
    const res = git(root, ['write-tree'], env);
    return res.status === 0 ? out(res) : '';
  } finally {
    rmSync(env.GIT_INDEX_FILE, { force: true });
  }
}

/** Changed files whose diff against `head` is empty once whitespace and blank lines are ignored. */
function formatOnlyFiles(root, head) {
  const list = git(root, ['-c', 'core.quotepath=false', 'diff', '--name-only', '-z', head]);
  if (list.status !== 0) return [];
  return (list.stdout ?? '').split('\0').filter(Boolean).filter((f) => {
    const res = git(root, ['diff', '--ignore-all-space', '--ignore-blank-lines', head, '--', f]);
    return res.status === 0 && !out(res);
  });
}

/** The SHA-256 of each file (repo-relative path), empty for one that doesn't exist. */
function hashFiles(root, files) {
  const hashes = {};
  for (const f of files) {
    try { hashes[f] = createHash('sha256').update(readFileSync(join(root, f))).digest('hex'); } catch { hashes[f] = ''; }
  }
  return hashes;
}

/** A runner whose failed tests `failedTests` can read, from the command line; null when none matches. */
const readableRunner = (command) => /\bnode(\.exe)?\b.*--test\b|\bdotnet\s+test\b|\bvitest\b|\bjest\b/.exec(command)?.[0] ?? null;

function finalize(dir, state) {
  const run = state.run;
  const o = run.opts;
  const seconds = Math.round(((run.endedAt ?? Date.now()) - run.startedAt) / 1000);
  const base = { tree: o.tree ?? '', seconds };
  let log = '';
  try { log = readFileSync(join(dir, 'gate.log'), 'utf8'); } catch { /* no output */ }
  state.run = null;
  writeState(dir, state);
  if (run.timedOut) emit('red: timeout', 1, { ...base, test: lastTestSeen(log) });
  if (o.red) {
    if (run.exitCode === 0) emit('red: no failing test', 1, base);
    const names = failedTests(log, o.testFiles);
    if (!names.length) emit('red', 1, { ...base, test: tail(log, 5).join(' | ') });
    state.proof = { names, files: hashFiles(o.root, o.testFiles) };
    writeState(dir, state);
    emit('red-proven', 0, { ...base, test: names.join('; ') });
  }
  if (run.exitCode !== 0) emit('red', 1, { ...base, test: failedTests(log).join('; ') || tail(log, 5).join(' | ') });
  if (!o.noScope) {
    const scope = scopeCheck(o.root, o.head, o.dirty);
    if (scope.verdict === 'unchecked') process.exit(2);
    if (scope.verdict === 'outside') emit('red: scope', 1, { ...base, outside: scope.outside });
  }
  const formatOnly = formatOnlyFiles(o.root, o.head);
  const greenAt = new Date().toISOString();
  state.green = { tree: o.tree, head: o.head, dirty: o.dirty, test: o.command, scope: !o.noScope, greenAt, formatOnly };
  delete state.proof;
  writeState(dir, state);
  emit('green', 0, { ...base, formatOnly, greenAt });
}

async function waitFor(dir, maxMinutes) {
  const deadline = Date.now() + maxMinutes * 60000;
  for (;;) {
    const state = readState(dir);
    if (!state.run) usage('no run to wait for');
    if (state.run.status === 'done') return finalize(dir, state);
    const seconds = Math.round((Date.now() - state.run.startedAt) / 1000);
    if (!supervisorAlive(state.run)) {
      // It may have written its result between the read above and the liveness check.
      const fresh = readState(dir);
      if (fresh.run?.status === 'done') return finalize(dir, fresh);
      fresh.run = null;
      writeState(dir, fresh);
      emit('red', 1, { test: 'supervisor died', seconds });
    }
    if (Date.now() >= deadline) emit('running', 3, { seconds });
    await sleep(150);
  }
}

/** Records the run, starts the detached supervisor and waits for it. */
function startRun(dir, state, root, run, maxMinutes) {
  const id = randomUUID();
  writeFileSync(join(dir, 'gate.log'), '');
  state.run = { id, status: 'running', startedAt: Date.now(), ...run };
  writeState(dir, state);
  spawn(process.execPath, [fileURLToPath(import.meta.url), '--supervise', '--root', root, '--run', id], { detached: true, stdio: 'ignore', windowsHide: true }).unref();
  return waitFor(dir, maxMinutes);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.root) usage('--root is required');
  const root = resolve(args.root);
  const dir0 = gitDirOf(root);
  if (!dir0) usage(`no git repository at ${root}`);
  const dir = join(dir0, 'deliver');
  mkdirSync(dir, { recursive: true });

  if (args.supervise) return supervise(dir, root, args.run);
  const maxMinutes = minutes(args, 'max-minutes', 9);
  const stuckMinutes = minutes(args, 'stuck-minutes', 5);
  if (args.wait) return waitFor(dir, maxMinutes);

  const state = readState(dir);
  if (state.run?.status === 'running' && supervisorAlive(state.run)) usage('a gate is already running here: use --wait');
  if (args.red) {
    if (!args.unit) usage('--unit is required with --red');
    if (!readableRunner(args.unit)) usage("--unit runs a test runner the gate can't read (dotnet test, node --test, vitest, jest)");
    return startRun(dir, state, root, {
      command: args.unit, stuckMinutes,
      opts: { root, red: true, testFiles: (args['test-files'] ?? '').split(',').filter(Boolean) },
    }, maxMinutes);
  }
  if (!args.test) usage('--test is required');
  if (!args.head) usage('--head is required');
  const noScope = !!args['no-scope'];
  const dirty = args.dirty ?? '';
  const changed = state.proof ? Object.entries(state.proof.files).filter(([f, h]) => hashFiles(root, [f])[f] !== h).map(([f]) => f) : [];
  if (changed.length) emit('red: tests changed', 1, { test: changed.join('; ') });
  const tree = treeHash(root, dir);
  if (!tree) usage('git could not hash the working tree');
  if (!noScope) {
    const scope = scopeCheck(root, args.head, dirty);
    if (scope.verdict === 'unchecked') process.exit(2);
    if (scope.verdict === 'outside') emit('red: scope', 1, { tree, outside: scope.outside });
  }
  const g = state.green;
  if (!args.force && !state.proof && g && g.tree === tree && g.head === args.head && g.dirty === dirty && g.test === args.test && g.scope === !noScope) {
    emit('skipped: tree unchanged', 0, { tree, greenAt: g.greenAt, formatOnly: g.formatOnly ?? [] });
  }
  return startRun(dir, state, root, {
    command: args.test, stuckMinutes,
    opts: { root, head: args.head, dirty, noScope, tree, command: args.test },
  }, maxMinutes);
}

const isMain = (() => {
  try { return realpathSync.native(process.argv[1]) === realpathSync.native(fileURLToPath(import.meta.url)); } catch { return false; }
})();

if (isMain) {
  main().catch((e) => {
    console.error(`gate: ${e?.stack ?? e}`);
    process.exit(2);
  });
}
