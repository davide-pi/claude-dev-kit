#!/usr/bin/env node
/**
 * The `deliver` gate: runs a block's test command under a stuck check and answers with one JSON line.
 *
 *   node gate.mjs --root <repoRoot> --head <start head> --test "<command>"
 *        [--dirty a,b] [--stuck-minutes 5] [--max-minutes 9] [--force] [--no-scope]
 *   node gate.mjs --root <repoRoot> --red --unit "<command>" --test-files <a,b>
 *   node gate.mjs --root <repoRoot> --wait
 *   node gate.mjs --root <repoRoot> --head <start head> --lane-add <name>
 *   node gate.mjs --root <repoRoot> --head <start head> --test "<command>" --merge <lane branch> [<lane branch> ...]
 *   node gate.mjs --root <repoRoot> --lane-remove <lane branch> [<lane branch> ...]
 *
 * `--lane-add` makes the worktree `<root>-lane-<name>` (the next free name) on the new branch `deliver-lane/<name>` from
 * the head, gives it the start's perimeter for that branch and prints `{lane,path,branch}`. `--merge` commits each lane's
 * work, merges the branches in order, then runs the plain gate (tests, scope) on the start tree: a conflict is aborted
 * (`git merge --abort`, the branch put back at its head, checked: a failed rollback says so in `test`) and answered
 * `red: merge` with the files in `outside`. `--merge` refuses (exit 2, nothing written) a start tree with staged changes
 * or with a modified or untracked file that a lane changes. Lane worktrees and branches are removed only after a good merge
 * (what could not be removed is `leftover` in the last line); the merged change is left uncommitted. `--lane-remove`
 * force-removes the worktree and the branch of each `deliver-lane/*` branch and prints `{removed:[{branch,path,ok}]}`.
 *
 * `--red` runs the unit command only, proves at least one test fails and stores the names with the SHA-256 of each
 * test file; the next plain run is green only while those files are unchanged. The tree hash (a temporary index,
 * the real one untouched) lets an unchanged tree skip the run; `hooks/scope-guard.js` checks the perimeter.
 *
 * The command runs under a detached supervisor (this script with the hidden `--supervise --run <id>` flags) that
 * writes its output to `<git dir>/deliver/gate.log`, compares the log size every `--stuck-minutes` (no growth: kill
 * the process tree, run once more; a second stall is `red: timeout`; 0 turns the check off) and stores the result in
 * `<git dir>/deliver/gate.json`, only while that file still holds its run id. A second run while the recorded
 * supervisor is alive exits 2; a dead supervisor is `red` ("supervisor died"). The foreground call polls the state
 * up to `--max-minutes`, then prints `running` and exits 3; `--wait` polls again. Minutes may be fractions.
 *
 * A stored red proof makes every plain run `red: tests changed` while a proven test file differs; `--force` drops the
 * proof and adds `"proof":"dropped"` to the last line. A supervisor pid is stored with its start time: a live pid that
 * started at another time is a reused one, and the supervisor counts as dead (checked every 30 s while waiting).
 *
 * Last stdout line: `{gate,test,outside,formatOnly,tree,greenAt,seconds}` (plus `proof` when dropped). Exit 0 green, 1 red, 2 not checked
 * (bad arguments, no git repository, a scope or git step that failed), 3 still running. git runs through argv,
 * never a shell.
 *
 * Generated by Claude Code at the user's request.
 */

