#!/usr/bin/env node
/**
 * The hook fire log, as a table: which hooks fired, how often, with which decision, from the main session
 * or a subagent, over how many days. The log is `<config>/.cache/hook-fires.log` (hooks/lib/fire-log.js),
 * one `{ day, hook, event, decision, sub }` line per fire, closed by itself after six distinct days.
 *
 *   node scripts/hook-fires.mjs [--delete]
 *
 * Prints `hook | event | fires | by decision | main/sub | days`, one row per hook and event. `--delete`
 * removes the log (which ends the brief's reminder and starts a new count) and prints `deleted`. Torn
 * lines are skipped. Config directory: CLAUDE_CONFIG_DIR or ~/.claude. Zero dependencies.
 *
 * Generated by Claude Code at the user's request.
 */

import { existsSync, readFileSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';

const LOG = join(process.env.CLAUDE_CONFIG_DIR || join(homedir(), '.claude'), '.cache', 'hook-fires.log');

if (process.argv.includes('--delete')) {
  rmSync(LOG, { force: true });
  rmSync(join(dirname(LOG), 'hook-fires.closed'), { force: true });
  console.log('deleted');
  process.exit(0);
}

if (!existsSync(LOG)) {
  console.log('no hook fire log');
  process.exit(0);
}

const rows = new Map();
for (const line of readFileSync(LOG, 'utf8').split('\n')) {
  let fire;
  try { fire = JSON.parse(line); } catch { continue; }
  if (!fire || typeof fire !== 'object' || !fire.hook) continue;
  const key = `${fire.hook}\u0000${fire.event}`;
  const row = rows.get(key) ?? { hook: fire.hook, event: fire.event, fires: 0, decisions: new Map(), main: 0, sub: 0, days: new Set() };
  row.fires += 1;
  row.decisions.set(fire.decision, (row.decisions.get(fire.decision) ?? 0) + 1);
  if (fire.sub) row.sub += 1; else row.main += 1;
  row.days.add(fire.day);
  rows.set(key, row);
}

const table = [['hook', 'event', 'fires', 'by decision', 'main/sub', 'days']];
for (const r of [...rows.values()].sort((a, b) => a.hook.localeCompare(b.hook) || String(a.event).localeCompare(String(b.event)))) {
  table.push([r.hook, String(r.event), String(r.fires), [...r.decisions].map(([d, n]) => `${d} ${n}`).join(', '), `${r.main}/${r.sub}`, String(r.days.size)]);
}
const widths = table[0].map((_, i) => Math.max(...table.map((row) => row[i].length)));
for (const row of table) console.log(row.map((cell, i) => cell.padEnd(widths[i])).join(' | ').trimEnd());
