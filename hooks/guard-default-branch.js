/**
 * PreToolUse hook for Bash / PowerShell.
 *
 * The convention (skill `git-branching`) is: the default branch is protected, every change goes
 * through a `feature/*` or `fix/*` branch and a PR. This hook makes the rule visible exactly when
 * it is about to be broken: if the command is a `git commit` / `git push` and the current branch is
 * the repo's default, it asks the user to confirm.
 *
 * Two deliberate design choices, both because this runs before EVERY Bash/PowerShell tool call
 * (the PreToolUse matcher can only filter by tool name, not by command text):
 *
 *   1. Node, not PowerShell — process startup is ~50-70ms instead of ~300ms.
 *   2. No `git` subprocess at all: the current branch and the default branch are read straight out
 *      of the `.git` directory, so the common case (a command that is not a commit/push) costs one
 *      regex, and the worst case costs two or three small file reads.
 *
 * It never blocks on its own: at most it escalates to the user (permissionDecision "ask"), and any
 * error lets the command through. Always exits 0.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const path = require('path');

/** No output => the normal permission flow applies. */
function approve() {
  process.exit(0);
}

function requestConfirmation(reason) {
  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: 'ask',
      permissionDecisionReason: reason,
    },
  }));
  process.exit(0);
}

/** Blank out the values of message-carrying flags, including combined ones (-am, -sm). */
function scrubMessages(command) {
  return command.replace(
    /(--message|--reuse-message|--file|-F|-[a-zA-Z]*m)(\s*=?\s*)("[^"]*"|'[^']*'|\S+)/g,
    (_, flag, sep) => `${flag}${sep}MSG`,
  );
}

function hasGitVerb(text, verb) {
  return new RegExp(`(^|[;&|\`\\s])git\\b[^;&|]*\\b${verb}\\b`).test(text);
}

/** `git -C <path>` wins over the session cwd. Read from the scrubbed text, never the raw command. */
function extractDashC(scrubbed) {
  const m = scrubbed.match(/git\s+(?:-c\s+\S+\s+)*-C\s+(?:"([^"]+)"|'([^']+)'|(\S+))/);
  return m ? (m[1] || m[2] || m[3]) : null;
}

/** Walk up from `start` to the repo root and return its resolved .git directory. */
function findGitDir(start) {
  let dir = path.resolve(start);
  for (;;) {
    const candidate = path.join(dir, '.git');
    if (fs.existsSync(candidate)) {
      const stat = fs.statSync(candidate);
      if (stat.isDirectory()) return candidate;
      // A worktree or submodule: `.git` is a file containing `gitdir: <path>`.
      const pointer = fs.readFileSync(candidate, 'utf8').match(/^gitdir:\s*(.+)$/m);
      if (!pointer) return null;
      const resolved = path.resolve(dir, pointer[1].trim());
      return fs.existsSync(resolved) ? resolved : null;
    }
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function readRef(gitDir, relative) {
  try {
    return fs.readFileSync(path.join(gitDir, relative), 'utf8').trim();
  } catch {
    return null;
  }
}

/** The checked-out branch, or null when HEAD is detached. */
function currentBranch(gitDir) {
  const head = readRef(gitDir, 'HEAD');
  const m = head && head.match(/^ref:\s*refs\/heads\/(.+)$/);
  return m ? m[1] : null;
}

function packedRefs(gitDir) {
  return readRef(gitDir, 'packed-refs') ?? '';
}

/** The repo's default branch: origin/HEAD if it is set, else whichever of main/master exists. */
function defaultBranch(gitDir) {
  const originHead = readRef(gitDir, path.join('refs', 'remotes', 'origin', 'HEAD'));
  const symbolic = originHead && originHead.match(/^ref:\s*refs\/remotes\/origin\/(.+)$/);
  if (symbolic) return symbolic[1];

  // Some clones keep it in packed-refs / in the config-less form.
  const packed = packedRefs(gitDir);
  const packedOrigin = packed.match(/^ref:\s*refs\/remotes\/origin\/(.+)$/m);
  if (packedOrigin) return packedOrigin[1];

  for (const candidate of ['main', 'master']) {
    if (readRef(gitDir, path.join('refs', 'heads', candidate))) return candidate;
    if (new RegExp(`\\srefs/heads/${candidate}$`, 'm').test(packed)) return candidate;
  }
  return null;
}

try {
  const raw = fs.readFileSync(0, 'utf8');
  if (!raw.trim()) approve();

  const payload = JSON.parse(raw);
  const command = payload?.tool_input?.command;
  if (typeof command !== 'string' || !command.trim()) approve();

  const scan = scrubMessages(command);

  const isCommit = hasGitVerb(scan, 'commit');
  const isPush = hasGitVerb(scan, 'push');
  if (!isCommit && !isPush) approve();
  if (/--dry-run/.test(scan)) approve();

  const repo = extractDashC(scan) || payload.cwd;
  if (!repo || !fs.existsSync(repo)) approve();

  const gitDir = findGitDir(repo);
  if (!gitDir) approve();

  const current = currentBranch(gitDir);
  const fallback = defaultBranch(gitDir);
  if (!current || !fallback) approve();

  if (current !== fallback) {
    // On a working branch the remaining case is `git push origin <default>` from here.
    if (isPush && new RegExp(`\\b${fallback.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(scan)) {
      requestConfirmation(
        `Il comando spinge su '${fallback}', il branch protetto di questo repo. La convenzione ` +
        'git-branching vuole che ci arrivi solo una PR (squash, CI verde + 1 review). Confermi?',
      );
    }
    approve();
  }

  const action = isCommit && isPush ? 'committare e spingere' : isCommit ? 'committare' : 'spingere';
  requestConfirmation(
    `Sei su '${current}', il branch di default del repo. La convenzione git-branching vieta di ` +
    `${action} direttamente qui: la strada e' un branch feature/* o fix/* e una PR verso ` +
    `'${fallback}'. Confermi di voler procedere comunque?`,
  );
} catch {
  // A bug in the hook must never get in the way of the work.
  approve();
}
