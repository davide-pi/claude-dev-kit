/**
 * SessionStart hook: pin the Azure CLI identity to the workspace root the session runs in.
 *
 * `az account set` is machine-global, so two sessions on different roots (one per Azure DevOps org,
 * each with its own sign-in) flip each other's default mid-command. Each identity therefore owns a
 * private Azure CLI config dir (a copy of ~/.azure with its own default subscription), and this
 * hook points AZURE_CONFIG_DIR at the right one through CLAUDE_ENV_FILE.
 *
 * The root -> identity map is local-only data, `~/.claude/workspaces.json` (the kit ships
 * `workspaces.example.json`; no org, project or account name lives in this file):
 *
 *   { "roots": [ { "path": "C:\\workspaces\\product", "identity": "work" }, ... ] }
 *
 * `identity` is the short name of the config dir: `~/.azure-<identity>`. The longest matching
 * `path` wins; other keys of an entry (platform, org, project) are not read here.
 *
 * Two variables are written, plain `export NAME=value` lines only — anything else makes the
 * PowerShell tool ignore the whole file:
 *   - AZURE_CONFIG_DIR — the path; reaches the Bash tool (PowerShell drops values holding `\`).
 *   - AZ_IDENTITY      — the short name, no slash, so it reaches PowerShell as well.
 *
 * Unmapped roots, a missing or unreadable `workspaces.json`, and a missing config dir write
 * nothing: ~/.azure stays the default there. Always exits 0.
 *
 * Generated by Claude Code at the user's request.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');

/** `{ path, identity }` entries of the local map, normalised and longest path first. */
function readRoots() {
  const raw = fs.readFileSync(path.join(os.homedir(), '.claude', 'workspaces.json'), 'utf8');
  const roots = JSON.parse(raw)?.roots;
  if (!Array.isArray(roots)) return [];
  return roots
    .filter((r) => r && typeof r.path === 'string' && /^[\w.-]+$/.test(r.identity ?? ''))
    .map((r) => ({ root: path.resolve(r.path).toLowerCase(), identity: r.identity }))
    .sort((a, b) => b.root.length - a.root.length);
}

function identityFor(cwd) {
  const dir = path.resolve(cwd).toLowerCase();
  const hit = readRoots().find(({ root }) => dir === root || dir.startsWith(root + path.sep));
  return hit ? hit.identity : null;
}

try {
  const input = JSON.parse(fs.readFileSync(0, 'utf8') || '{}');
  const envFile = process.env.CLAUDE_ENV_FILE;
  const id = envFile && identityFor(input.cwd || process.cwd());
  if (id) {
    const dir = path.join(os.homedir(), `.azure-${id}`);
    if (fs.existsSync(dir)) {
      // Forward slashes: bash strips unquoted backslashes, and az accepts either separator.
      const value = dir.replace(/\\/g, '/');
      fs.appendFileSync(envFile, `export AZURE_CONFIG_DIR=${value}\nexport AZ_IDENTITY=${id}\n`);
    }
  }
} catch {
  // never block a session start
}
process.exit(0);
