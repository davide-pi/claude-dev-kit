/**
 * PreToolUse hook on every MCP tool: a read-only agent (`agent_type` in `lib/read-only-agents.js`) may call only
 * MCP tools that read.
 *
 * Connector servers have per-account names (UUIDs), so an agent's `tools:` allowlist cannot name them; this
 * hook judges the tool's own name instead. The part after the last `__` is split into words (`_`, `-`, spaces,
 * camelCase); the first word that is a known verb decides: a read verb (get, list, search, read, find, fetch,
 * query...) lets the call through, anything else is denied. So `outlook_create_reply_draft` is denied by
 * `create`, `get_draft` passes by `get`, and a name with no read verb (`batch`, `navigate`, `run_pipeline`,
 * `wit_work_item`) is denied by default: an open write vocabulary can't be listed, a read one can.
 *
 * A read-only agent reads untrusted text (mail, chat messages, web pages): this keeps injected text from making
 * it send or change anything. No `agent_type` (the main session) or an agent not in the list: no decision.
 * A bad payload lets the call through. Always exits 0.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const { deny, readPayload } = require('./lib/decision');
const { READ_ONLY_AGENTS } = require('./lib/read-only-agents');

const READ_VERBS = new Set(['get', 'list', 'search', 'read', 'find', 'fetch', 'query', 'describe', 'view',
  'lookup', 'count', 'show']);
const WRITE_VERBS = new Set(['send', 'reply', 'draft', 'create', 'update', 'delete', 'remove', 'post', 'react',
  'add', 'schedule', 'forward', 'move', 'rename', 'upload', 'copy', 'trash', 'untrash', 'modify', 'write', 'set',
  'complete', 'respond', 'archive', 'invite', 'share', 'edit', 'put', 'patch', 'insert', 'publish', 'cancel',
  'batch', 'replace', 'run', 'resolve', 'link', 'assign', 'accept', 'decline', 'flag', 'mark', 'join', 'checkout',
  'approve', 'reject', 'close', 'merge', 'execute', 'exec', 'trigger', 'invoke', 'start', 'stop', 'restore',
  'commit', 'push', 'deploy', 'grant', 'revoke', 'apply', 'save', 'submit', 'clear', 'reset', 'pin', 'tag']);

/** Words of a tool name: separators and camelCase boundaries, lower-cased. */
const wordsOf = (name) => name.split(/[_\-\s]+|(?<=[a-z0-9])(?=[A-Z])/).filter(Boolean).map((w) => w.toLowerCase());

try {
  const payload = readPayload('mcp-readonly-guard');
  const agent = payload?.agent_type;
  const tool = payload?.tool_name || '';
  if (agent && READ_ONLY_AGENTS.has(agent) && tool.startsWith('mcp__')) {
    const verb = wordsOf(tool.slice(tool.lastIndexOf('__') + 2)).find((w) => READ_VERBS.has(w) || WRITE_VERBS.has(w));
    if (!verb || !READ_VERBS.has(verb)) {
      const why = verb ? `'${verb}' may write` : 'its name holds no read verb';
      deny(`A read-only agent (${agent}) may not call '${tool}': ${why}. ` +
        'Only tools whose first verb reads (get, list, search, read, find, fetch, query) are allowed; return the rest to the caller.');
    }
  }
} catch {
  // a bad payload: the call goes on
}
process.exit(0);
