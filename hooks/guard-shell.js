/**
 * PreToolUse hook for Bash / PowerShell — the single entry point for every shell guard.
 *
 * Runs, on the same parsed payload:
 *
 *   - lib/default-branch.js — a `git commit` / `git push` landing on the repo's default branch;
 *   - lib/destructive.js    — an action with no undo, even buried in `docker exec`, `sqlcmd -Q` or a
 *                             pipeline, where a permission prefix cannot see it;
 *   - lib/sql-target.js     — a raw `sqlcmd` / `psql` / `redis-cli` (and kin) aimed at a host that
 *                             is not a dev host: non-dev databases go through
 *                             `~/.claude/scripts/db-ro.ps1`. This one and secret-read DENY;
 *   - lib/alm-contract.js   — an `az` write missing the house ALM flags (PR work item, squash +
 *                             delete, assignee), hours written (CompletedWork), global defaults;
 *   - lib/secret-read.js    — the second DENY: Get-Content / cat / grep / find -exec naming a secret file
 *                             (`.env`, keys, token caches), which the Read deny rules do not cover;
 *   - lib/guard.js          — a DENY too: a read-only agent (`agent_type` in `lib/read-only-agents.js`) running a
 *                             git write (checkout, switch, reset, stash, rebase, commit, push) or a tracker / pull request
 *                             write (`az boards|repos|wiki` writes, `gh pr|issue` writes, `gh api` POST); no `agent_type`, no deny;
 *   - lib/browser-use-cli.js — a DENY too: `browser-use` run from a shell while no such CLI is on the PATH;
 *                             the plugin is reached through its MCP tools;
 *   - lib/self-protect.js   — a shell write into ~/.claude hooks, settings*.json or CLAUDE.md;
 *   - lib/docker-cp.js      — a `docker cp` that overwrites a host file outside the cwd or under ~/.claude;
 *   - lib/script-args.js    — a DENY when an argument of the allowed `db-ro.ps1`
 *                             calls holds a construct a single-quote re-quote fixes (`$`, `(`, `@`, `<`… unquoted);
 *                             an ask for an unbalanced or typographic quote, a non-ASCII character,
 *                             `db-ro.ps1 -AcceptWriteGrant` (or an abbreviation);
 *   - lib/output-filter.js  — not a check: when nothing above fired, a plain `dotnet test` /
 *                             `dotnet build` / `npm test` / `npx vitest` / `docker compose logs` is
 *                             rewritten to pipe through a failure filter (opt-out `# raw`);
 *   - lib/batch-nudge.js    — not a check: on an allowed or rewritten call of the main session, the fifth
 *                             single shell call in a row adds one `additionalContext` line to batch; the same
 *                             lib also adds a one-time hint (per session and agent) on a call that starts `cd X &&`,
 *                             and DENIES that call to a subagent, which would otherwise prompt the user per directory;
 *   - lib/az-pin.js         — the other rewrite: an `az` command the allow list already covers, in a
 *                             directory the workspace map gives an identity, is pinned to that
 *                             identity's AZURE_CONFIG_DIR (opt-out `# raw`).
 *
 * One process instead of two because this runs before EVERY Bash/PowerShell tool call (the
 * PreToolUse matcher can only filter by tool name, not by command text): one Node start-up, one
 * stdin parse. Node, not PowerShell — the whole hook is ~150ms against ~370ms just to start `pwsh`.
 *
 * The denying checks all run first: when one denies, nothing else matters; the asks they return join
 * the others. The others always run. When several fire (`git push origin main && docker compose down -v`),
 * the user gets one prompt carrying every reason.
 *
 * Apart from those denials it never blocks on its own: at most it escalates to the user
 * (permissionDecision "ask"). A guard that fails (a crashed check, a module that does not load, a payload
 * that cannot be read) asks too, never approves: the ask is written by hand, without lib/decision, so it
 * survives a broken lib. Only the rewrites fail open. The rewrites come last, so a
 * command that asks is never rewritten (nor auto-allowed). Always exits 0.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

/** The ask a failing guard answers, built with nothing but `process`: it must work when every lib is broken. */
function askRaw(reason) {
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'ask', permissionDecisionReason: reason } }));
  process.exit(0);
}
const failed = (error) => {
  try { require('./lib/cache').logError('guard-shell', error); } catch { /* the log is as broken as the rest */ }
  askRaw('The command guard failed, so this command could not be checked. Confirm it yourself (details in hook-errors.log).');
};

let lib;
try {
  lib = { ...require('./lib/decision'), ...require('./lib/guard'), ...require('./lib/batch-nudge') };
} catch (error) {
  failed(error);
}

try {
  const { approve, requestConfirmation, deny, rewrite, readPayload, evaluate, nudge, cdHint, cdDeny } = lib;
  const payload = readPayload('guard-shell');
  // A subagent's cd X && ... would prompt the user per directory: deny it with the way round instead.
  const cdReason = cdDeny(payload);
  if (cdReason) deny(cdReason);
  const result = evaluate(payload);
  // Only a call that goes through counts toward the run: an ask or a deny gets no nudge.
  const context = () => [nudge(payload), cdHint(payload)].filter(Boolean).join('\n') || undefined;
  if (!result) approve(context());
  if (result.rewrite) rewrite(result.rewrite, context());
  if (result.decision === 'deny') deny(result.reason);
  requestConfirmation(result.reason);
} catch (error) {
  failed(error);
}
