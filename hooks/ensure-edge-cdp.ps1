#Requires -Version 5.1
<#
  Slow path of the PreToolUse hook hooks/edge-cdp.js (tool mcp__plugin_browser-use_browser-use__*):
  edge-cdp.js launches it only when no CDP port answers.

  browser-use (browser-harness) does not start a browser: it attaches to the CDP port
  written by the MAIN Edge profile in "User Data\DevToolsActivePort". The edge://inspect
  toggle ("Allow remote debugging") is persisted in Local State, so it is enough for Edge
  to be open for the port (9222) to come back up. On the first attach of each browser
  session Edge asks "Allow remote debugging?": it must be clicked by hand.
    1. CDP port reachable               -> exits at once;
    2. Edge not running                  -> starts it and waits for the port;
    3. Edge open but port closed         -> warns to re-enable the toggle.

  Never blocks the tool call: always exits with code 0.
  Generated by Claude Code at the user's request.
#>

$ErrorActionPreference = 'Stop'

$UserData     = Join-Path $env:LOCALAPPDATA 'Microsoft\Edge\User Data'
$DefaultPort  = 9222
$GraceSeconds = 20

function Write-HookMessage([string]$Text) {
    @{ systemMessage = $Text } | ConvertTo-Json -Compress
}

function Get-CdpPort {
    $file = Join-Path $UserData 'DevToolsActivePort'
    try {
        $first = (Get-Content $file -TotalCount 1 -ErrorAction Stop).Trim()
        return [int]$first
    } catch {
        return $DefaultPort
    }
}

function Test-Port([int]$Port) {
    $client = New-Object System.Net.Sockets.TcpClient
    try {
        $task = $client.ConnectAsync('127.0.0.1', $Port)
        return ($task.Wait(500) -and $client.Connected)
    } catch {
        return $false
    } finally {
        $client.Dispose()
    }
}

function Resolve-EdgeExe {
    foreach ($root in 'HKLM:', 'HKCU:') {
        $key = "$root\SOFTWARE\Microsoft\Windows\CurrentVersion\App Paths\msedge.exe"
        if (Test-Path $key) {
            $path = (Get-ItemProperty $key -ErrorAction SilentlyContinue).'(default)'
            if ($path -and (Test-Path $path)) { return $path }
        }
    }
    foreach ($p in "${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
                   "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe") {
        if (Test-Path $p) { return $p }
    }
    return $null
}

try {
    # --- 1. fast path: CDP port already up -----------------------------------
    if ((Test-Port (Get-CdpPort)) -or (Test-Port $DefaultPort)) { exit 0 }

    # --- 3. Edge open but port closed: the toggle is off ---------------------
    if (Get-Process -Name msedge -ErrorAction SilentlyContinue) {
        Write-HookMessage "Edge is running but the CDP port is closed: open edge://inspect/#remote-debugging and tick 'Allow remote debugging for this browser instance'."
        exit 0
    }

    # --- 2. Edge closed: start it and wait for the port ---------------------
    $exe = Resolve-EdgeExe
    if (-not $exe) {
        Write-HookMessage "msedge.exe not found: browser-use cannot attach to a browser."
        exit 0
    }
    Start-Process -FilePath $exe | Out-Null

    $deadline = (Get-Date).AddSeconds($GraceSeconds)
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 500
        # Edge rewrites DevToolsActivePort at startup: re-read the port every loop
        if ((Test-Port (Get-CdpPort)) -or (Test-Port $DefaultPort)) {
            Write-HookMessage "Edge was not running: started it for browser-use (CDP port up)."
            exit 0
        }
    }
    Write-HookMessage "Started Edge, but the CDP port did not open within ${GraceSeconds}s: check edge://inspect/#remote-debugging."
    exit 0
}
catch {
    Write-HookMessage ("ensure-edge-cdp hook failed: {0}" -f $_.Exception.Message)
    exit 0
}
