/**
 * Check: an action with no undo, wherever it sits in the command line.
 *
 * The permission allow/deny list can only match a command *prefix*, so it is blind to the shape
 * that actually loses data: the destructive verb buried inside a longer line —
 * `docker exec -i db sqlcmd -Q "DROP DATABASE Sales"`, `docker compose down -v`,
 * `az group delete --yes`. This check reads the whole line, per chained command.
 *
 * No subprocess and, but for one case, no file system access: it is text analysis, so the common case
 * (a line with none of the danger words) is one regex and nothing else. The one case: a recursive delete
 * whose every operand sits in Claude's own temp folder (`<tmp>/claude/<proj>/<session>/…`) passes, after an
 * lstat per path component to refuse a symbolic link or junction. Relative operands count after a `cd` /
 * `Set-Location` into that folder (a literal, or a variable assigned one earlier on the line), and
 * `Remove-Item` only when no link sits inside the tree it would recurse into.
 *
 * The interesting half of the problem is the false positives. Four of them are worth naming,
 * because each one would have trained the user to click through the prompt:
 *
 *   - a *searcher*: `grep -rn "DROP TABLE" .` hunts for the danger, it does not do it. A segment
 *     whose command is a search tool is skipped whole.
 *   - a *comment*: `# then DROP DATABASE Sales` — `#` comments outside quotes are blanked, and so
 *     are `--` / block comments inside a quoted SQL string.
 *   - a *path*: `psql -f scripts/drop-old-tables.sql` names a file. Path-shaped tokens outside
 *     quotes are blanked (which is also why this check cannot see inside a script — see below).
 *   - a *read-only query*: `sqlcmd -Q "SELECT 'DROP TABLE ' + name FROM sys.tables"` generates
 *     text. Inside a quoted string, SQL string literals and whole read-only statements are blanked.
 *
 * Plus `--dry-run` / `--what-if` / `--help`, per chained command, which change nothing.
 *
 * Deliberately NOT detected: what a script or a migration *contains*. `./teardown.ps1` and
 * `psql -f drop.sql` are one token here; reading the file would mean I/O on every tool call, and
 * the risk is the user's own script, which they wrote. `tools/guard-shell.test.mjs` pins every
 * rule and every false positive above.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const { splitSegments, expandTexts, hasSubstitution, SEARCHERS } = require('./shell-parse');

/**
 * Cheap gate. If none of these words is anywhere in the line, no rule below can fire, so the
 * overwhelming majority of tool calls cost exactly one regex.
 *
 * `purge_queue` / `delete_queue` are listed in full because `_` is a word character, so `\bpurge\b`
 * does not match inside them — the broker CLIs would have slipped straight through the gate.
 */
const DANGER_WORDS = /\b(?:drop|dropdb|dropuser|dropdatabase|truncate|flushall|flushdb|flush_all|prune|purge|purge_queue|delete|delete_queue|destroy|uninstall|remove|rm|ri|rd|rmdir|del|erase|down|nuke|clear|expire|push|switch|checkout|restore|clean|reset|branch|update-ref|filter-branch|gc|rmi)\b/i;
/** A flag cluster carrying `-D`: force-delete. Case-sensitive, because `-d` is the safe form. */
const DANGER_FLAG = /(?<![-\w])-[a-zA-Z]*D[a-zA-Z]*(?![\w-])/;

/** `az account set` loses no data, but the default it flips is machine-global (see skills/azdo-cli). */
const AZ_ACCOUNT_SET = /(?<![-\w])az\s+account\s+set\b/i;

const isDangerous = (text) => DANGER_WORDS.test(text) || DANGER_FLAG.test(text) || AZ_ACCOUNT_SET.test(text);

/** Commands that look for a string or a help page instead of acting on it: never destructive, whatever they find. */
const LOOKUPS = new Set([...SEARCHERS, 'get-help', 'man', 'help', 'which', 'where', 'get-command']);

/** Flags that make the whole chained command a no-op. */
const NOOP_FLAGS = /(?<![-\w])(?:--dry-run|--dryrun|--dry_run|--what-if|--whatif|-whatif|--noop|--no-op|--help|--usage|--version)\b/i;

/** Extensions common enough that a bare `drop-tables.sql` is obviously a file, not a statement. */
const PATHISH = /^[^\s]*(?:[\\/][^\s]*|\.(?:sql|ps1|psm1|sh|bash|cmd|bat|js|mjs|cjs|ts|cs|csproj|sln|json|ya?ml|xml|md|txt|log|bak|tf|dockerfile))$/i;

/** Walk a segment once, reporting every quoted span (content only, quotes excluded). */
function quotedSpans(segment) {
  const spans = [];
  let quote = null;
  let start = 0;
  for (let i = 0; i < segment.length; i += 1) {
    const c = segment[i];
    if (quote && c === quote) {
      spans.push({ start, end: i });
      quote = null;
    } else if (!quote && (c === '"' || c === "'")) {
      quote = c;
      start = i + 1;
    }
  }
  return spans;
}

/** Replace a slice with spaces, so every remaining match keeps its original offset. */
function blank(text, start, end) {
  return text.slice(0, start) + ' '.repeat(Math.max(0, end - start)) + text.slice(end);
}

/** The executable of a segment, lowercased and stripped of any directory and extension. */
function leadingCommand(segment) {
  const match = segment.trim().match(/^[^\s]+/);
  if (!match) return '';
  return match[0]
    .replace(/^["']|["']$/g, '')
    .replace(/^.*[\\/]/, '')
    .replace(/\.(?:exe|cmd|bat|ps1)$/i, '')
    .toLowerCase();
}

/**
 * `git grep` / `git log --grep=…` are searchers too, but the verb is the second token. A searcher
 * that carries a substitution (`grep foo $(rm -rf x)`) runs something else, so it is not skipped.
 */
function isSearcher(segment) {
  if (hasSubstitution(segment)) return false;
  const command = leadingCommand(segment);
  if (LOOKUPS.has(command)) return true;
  if (command === 'git') {
    const verb = segment.trim().split(/\s+/)[1];
    return ['grep', 'log', 'show', 'blame', 'diff'].includes(verb);
  }
  return false;
}

/**
 * SQL statements that only read. A quoted string is cut at `;` and each statement that starts with
 * one of these is blanked, so `SELECT … FROM sys.tables WHERE name = 'DropLog'` is inert while
 * `SELECT 1; DROP TABLE x` is not.
 */
const READ_ONLY_SQL = /^\s*(?:select|with|explain|show|describe|desc|print|use|set)\b/i;

/** A SQL client anywhere in the segment, also behind `docker exec` / `sudo`: only then does `--` start a comment. */
const SQL_CLIENT = /(?<![-\w])(?:sqlcmd|invoke-sqlcmd|osql|isql|bcp|sqlpackage|psql|pg_restore|mysql|mariadb|usql|sqlite3?|sqlplus|cqlsh|mongosh|duckdb|clickhouse-client)(?![-\w])/i;

/**
 * The value of a flag that carries prose: a title, a body, a commit message. Quoted (`"..."`, `'...'`,
 * the `"$(cat <<'EOF' ... EOF)"` commit heredoc) or one bare word. A value holding a substitution is
 * left alone: the shell runs it.
 */
const MESSAGE_FLAG = /(?<![-\w])(--title|--description|--discussion|--body|--message|(?:-[a-zA-Z]{0,3}m))(\s*=\s*|\s+)(?="|'|\S)/g;
const HEREDOC_VALUE = /^"\$\(cat\s+<<-?\s*'(\w+)'[\s\S]*?\n[ \t]*\1[ \t]*\r?\n?[ \t]*\)"/;
function messageValueLength(rest) {
  const heredoc = HEREDOC_VALUE.exec(rest);
  if (heredoc) return heredoc[0].length;
  const quoted = /^"(?:[^"\\]|\\.)*"|^'[^']*'/.exec(rest);
  const value = quoted ? quoted[0] : /^\S+/.exec(rest)?.[0] ?? '';
  return /\$\(|`/.test(value) ? 0 : value.length;
}

/** Blank the value of every message-like flag, so a danger word in a title or a commit message is inert. */
function blankMessages(segment) {
  let out = segment;
  for (const m of segment.matchAll(MESSAGE_FLAG)) {
    const start = m.index + m[0].length;
    out = blank(out, start, start + messageValueLength(segment.slice(start)));
  }
  return out;
}

/** The string arguments of a plain `echo` / `Write-Output` / `printf` that is not piped on: text, not a command. */
function blankEchoArgs(segment) {
  const m = /^(\s*(?:echo|write-output|write-host|printf)\s+)/i.exec(segment);
  return m ? blank(segment, m[1].length, segment.length) : segment;
}

/**
 * Blank everything inside a segment that cannot be an instruction to destroy something:
 * comments, file paths, SQL string literals and read-only SQL statements. Offsets are preserved so
 * the result can still be reported against the original text.
 */
function prepare(segment, blankPaths = true, echoIsData = false) {
  let scan = blankMessages(segment);
  if (echoIsData) scan = blankEchoArgs(scan);
  const sql = SQL_CLIENT.test(segment);

  // 1. `#` comments outside quotes (bash and PowerShell), from a token boundary to end of line.
  {
    let quote = null;
    for (let i = 0; i < scan.length; i += 1) {
      const c = scan[i];
      if (quote) {
        if (c === quote) quote = null;
      } else if (c === '"' || c === "'") {
        quote = c;
      } else if (c === '#' && (i === 0 || /\s/.test(scan[i - 1]))) {
        const end = scan.indexOf('\n', i);
        scan = blank(scan, i, end < 0 ? scan.length : end);
      }
    }
  }

  // 2. Inside each quoted span: SQL comments, then SQL string literals, then read-only statements.
  for (const span of quotedSpans(scan)) {
    let body = scan.slice(span.start, span.end);
    const offset = span.start;

    // SQL comments only exist for a SQL client: `--force` inside `bash -c "git push --force"` is a flag.
    if (sql) {
      body = body.replace(/--[^\n]*/g, (m) => ' '.repeat(m.length));
      body = body.replace(/\/\*[\s\S]*?\*\//g, (m) => ' '.repeat(m.length));
    }
    // A single-quoted literal inside a double-quoted argument is data, not a statement.
    body = body.replace(/'[^']*'/g, (m) => ' '.repeat(m.length));

    let at = 0;
    for (const statement of body.split(';')) {
      if (READ_ONLY_SQL.test(statement)) {
        body = blank(body, at, at + statement.length);
      }
      at += statement.length + 1;
    }
    scan = scan.slice(0, offset) + body + scan.slice(offset + body.length);
  }

  // 3. Path-shaped tokens *outside* quotes: `scripts/drop-old.sql`, `./teardown.ps1`, `C:\db\x.bak`.
  if (blankPaths) {
    const inQuote = new Array(scan.length).fill(false);
    for (const span of quotedSpans(scan)) {
      for (let i = span.start; i < span.end; i += 1) inQuote[i] = true;
    }
    for (const m of scan.matchAll(/[^\s"']+/g)) {
      if (inQuote[m.index]) continue;
      if (PATHISH.test(m[0])) scan = blank(scan, m.index, m.index + m[0].length);
    }
  }

  return scan;
}

/**
 * Every rule: a predicate and what the user is asked. It receives the prepared segment (`scan`, paths
 * blanked), the same text with its paths kept (`keep`: a refspec like `+feature/x` is a path to `scan`)
 * and the raw segment.
 */
const has = (re) => (scan) => re.test(scan);
const all = (...tests) => (...args) => tests.every((t) => t(...args));

/** The command a segment runs, after `sudo`, `xargs`, `env VAR=x` and their options. */
/** Shell keywords that open a condition or a body: the command is the word after them. */
const SHELL_KEYWORDS = new Set(['if', 'elif', 'then', 'else', 'while', 'until', 'do', '{', '!']);
function effectiveCommand(segment) {
  const tokens = segment.trim().split(/\s+/);
  const wrappers = ['sudo', 'xargs', 'env', 'command', 'nohup', 'time', 'exec'];
  let i = 0;
  while (i < tokens.length) {
    if (SHELL_KEYWORDS.has(tokens[i])) { i += 1; continue; }
    if (!(/^[A-Za-z_]\w*=/.test(tokens[i]) || wrappers.includes(tokens[i].toLowerCase()))) break;
    i += 1;
    while (i < tokens.length && tokens[i].startsWith('-')) i += 1;
  }
  return leadingCommand(tokens.slice(i).join(' '));
}

/** A pipeline stage that runs a script block per item: `ls | % { rm $_ }`. */
const PIPE_LOOPS = new Set(['%', 'foreach', 'foreach-object']);
const DELETER_WORD = /(?<![-\w])(?:remove-item|rm|ri|del|erase|rd|rmdir)(?![-\w])/i;
const DELETERS = new Set(['rm', 'ri', 'del', 'rd', 'rmdir', 'erase', 'remove-item']);
const RM_FLAG = /^(?:-[rRfv]+|--recursive|--force|--verbose)$/;
const CMD_SWITCH = /^\/[sqf]$/i;
const PATH_FLAG = /^-(?:path|literalpath|lp)$/i;
/** True when `flag` is `-name` or an abbreviation of it at least `min` letters long (PowerShell binds unique prefixes). */
const abbreviates = (flag, name, min) => {
  const f = flag.slice(1).toLowerCase();
  return f.length >= min && name.startsWith(f);
};
/** Anything a shell would expand, substitute or reinterpret: a path holding one is not a plain path. */
const NOT_PLAIN = /[$`%*?[\]{}()<>|;&'"!#^=]/;

/**
 * The path operands of a delete segment, or null when any token is not clearly a known flag of that
 * deleter or a plain path (null = the caller asks). Reads the raw segment, never the prepared one:
 * the preparation blanks quoted text, which could hide a substitution.
 */
function deleteOperands(text, command) {
  if (/[\r\n]/.test(text)) return null;
  const tokens = text.trim().split(/\s+/);
  if (leadingCommand(tokens[0]) !== command) return null; // a wrapper (`sudo`, `xargs`, `env`) or anything before the deleter
  const powershell = command === 'remove-item' || command === 'ri';
  const operands = [];
  let flagsEnded = false;
  const addOperand = (raw) => {
    const quoted = /^(["'])([^"'\s]*)\1$/.exec(raw);
    const operand = quoted ? quoted[2] : raw;
    if (!operand || operand.startsWith('~') || NOT_PLAIN.test(operand) || (command === 'rm' && operand.includes('\\'))) return false; // bash reads `\` as an escape, not a separator // a leading ~ expands to the home folder
    operands.push(operand);
    return true;
  };
  for (let i = 1; i < tokens.length; i += 1) {
    const token = tokens[i];
    if (!flagsEnded && command === 'rm' && token === '--') { flagsEnded = true; continue; }
    const flagLike = !flagsEnded && (token.startsWith('-') || (!powershell && command !== 'rm' && /^\/\w$/.test(token)));
    if (!flagLike) {
      for (const piece of token.split(',')) if (!addOperand(piece)) return null; // cmd and PowerShell split on `,`; bash fails closed here
    } else if (command === 'rm') {
      if (!RM_FLAG.test(token)) return null;
    } else if (powershell) {
      if (PATH_FLAG.test(token)) {
        const value = tokens[i += 1];
        if (value === undefined) return null;
        for (const piece of value.split(',')) if (!addOperand(piece)) return null;
      } else if (!(abbreviates(token, 'recurse', 1) || abbreviates(token, 'force', 2))) return null;
    } else if (!CMD_SWITCH.test(token)) return null;
  }
  return operands.length ? operands : null;
}

const normalizePath = (p) => (process.platform === 'win32' ? p.replace(/\\/g, '/').toLowerCase() : p.replace(/\\/g, '/'));
/** Anything on the line that could make or move a link or junction before the delete runs. */
const LINK_CREATOR = /(?<![-\w])(?:ln|mklink|new-item|ni|symlink|symboliclink|junction|mv|move|move-item|mi)(?![-\w])/i;
const SHORT_TEMP_CLAUDE = /^[a-z]:\/users\/[^/]+~\d+\/appdata\/local\/temp\/claude\//;

/**
 * True when the operand is a strict descendant of `<tmp>/claude/<proj>/<session>` (at least one segment
 * below the session folder): absolute, no `.`/`..`, no symbolic link or junction on the way. Any doubt is false.
 */
function isThrowawayPath(operand, sessionId) {
  try {
    const p = normalizePath(operand).replace(/\/$/, '');
    if (!(/^[a-z]:\//i.test(p) || (p.startsWith('/') && !p.startsWith('//')))) return false;
    const root = `${normalizePath(os.tmpdir()).replace(/\/+$/, '')}/claude/`;
    const rootLength = p.startsWith(root) ? root.length : process.platform === 'win32' ? SHORT_TEMP_CLAUDE.exec(p)?.[0].length : undefined;
    if (!rootLength) return false;
    const segments = p.slice(rootLength).split('/');
    if (segments.length < 3 || segments.some((s) => !s || /^\.+$/.test(s) || s.includes(':'))) return false;
    // With a session id in the payload, only this session's own folder; without one, any session's (a known limit).
    if (sessionId && segments[1] !== normalizePath(String(sessionId))) return false;
    for (let i = 0; i <= segments.length; i += 1) { // i = 0: the claude folder itself
      try {
        // No trailing slash: lstat on `link/` would follow the link.
        if (fs.lstatSync([p.slice(0, rootLength - 1), ...segments.slice(0, i)].join('/')).isSymbolicLink()) return false;
      } catch (error) {
        if (error?.code === 'ENOENT' || error?.code === 'ENOTDIR') break; // nothing deeper can exist
        return false;
      }
    }
    return true;
  } catch {
    return false;
  }
}

const CD_COMMANDS = new Set(['cd', 'chdir', 'pushd', 'set-location', 'sl']);
const BASH_CD = new Set(['cd', 'pushd']);
const PLAIN_CD = new Set(['cd']);
// Variables that change how the shell splits words, finds folders or commands, or where it is.
const RESERVED_VARS = /^(?:IFS|CDPATH|PATH|HOME|PWD|OLDPWD|SHELLOPTS|BASHOPTS|BASH_ENV|ENV|GLOBIGNORE)$/i;
const stripQuotes = (s) => /^(["'])(.*)\1$/.exec(s)?.[2] ?? s;
// The only forms each shell reads as an assignment of a literal: Bash `name=value`, PowerShell `$name = 'value'`.
const BASH_ASSIGNMENT = /^([A-Za-z_]\w*)=(?:"([^"$`\\\s]*)"|'([^'\s]*)'|([^"'$`\\\s]*))$/;
const PS_ASSIGNMENT = /^\$([A-Za-z_]\w*)\s*=\s*(?:"([^"$`\s]*)"|'([^'\s]*)')$/;

/** `[name, value]` when `text` is a plain literal assignment in `shell` (a PowerShell name is case-insensitive), else null. */
function parseAssignment(text, shell) {
  const m = shell === 'bash' ? BASH_ASSIGNMENT.exec(text) : shell === 'powershell' ? PS_ASSIGNMENT.exec(text) : null;
  return m ? [shell === 'powershell' ? m[1].toLowerCase() : m[1], m[2] ?? m[3] ?? m[4] ?? ''] : null;
}

/**
 * `text` with the variables it can resolve replaced: the literals this line assigned earlier, and on Windows
 * the temp folder as the shell spells it (Bash `$TEMP`, `${TEMP}`; PowerShell `$env:TEMP`; where the shell is
 * unknown, none). Others stay, and a path holding one is not a plain path.
 */
function expandVars(text, vars, shell) {
  const tmp = process.platform === 'win32' ? os.tmpdir().replace(/\\/g, '/').replace(/\/+$/, '') : null;
  return text.replace(/\$(?:\{(\w+)\}|(env:)?(\w+))/gi, (match, braced, env, bare) => {
    const name = braced ?? bare;
    if (shell === 'powershell') {
      if (env) return tmp && /^(?:temp|tmp)$/i.test(name) ? tmp : match;
      return vars.get(name.toLowerCase()) ?? match;
    }
    if (shell === 'bash' && !env) return vars.get(name) ?? (tmp && /^(?:TEMP|TMP)$/.test(name) ? tmp : match);
    return match;
  });
}

/** A plain literal path from one token, variables resolved and quotes removed, else null. */
function literalPath(raw, vars, shell) {
  if (/^'/.test(raw) && raw.includes('$')) return null; // single quotes: no expansion
  const value = stripQuotes(expandVars(raw, vars, shell));
  return value && !NOT_PLAIN.test(value) ? value : null;
}

/**
 * Where `cd` / `Set-Location` / `pushd` leaves the shell: an existing folder at or below a Claude temp
 * session folder, else null. A `cd` that fails changes nothing, and `;` runs the delete anyway, hence the stat.
 */
function changeDir(text, command, cwd, vars, shell, sessionId) {
  const tokens = text.trim().split(/\s+/);
  const pathFlag = shell === 'powershell' && tokens.length === 3 && PATH_FLAG.test(tokens[1]);
  if (tokens.length !== 2 && !pathFlag) return null;
  const raw = tokens[tokens.length - 1];
  const value = literalPath(raw, vars, shell);
  // Bash eats the backslashes of an unquoted path: only PowerShell and quotes keep them.
  if (value === null || (value.includes('\\') && !/^["']/.test(raw) && command !== 'set-location' && command !== 'sl')) return null;
  const path = value.replace(/\\/g, '/').replace(/\/+$/, '');
  const target = /^[a-z]:\//i.test(path) || path.startsWith('/') ? path : cwd && `${cwd}/${path.replace(/^(?:\.\/)+/, '')}`;
  if (!target || !isThrowawayPath(`${target}/x`, sessionId)) return null;
  try { return fs.statSync(target).isDirectory() ? target : null; } catch { return null; }
}

/**
 * The working folder and variables in force after the segments that precede a delete, or null when any of
 * them is not a delete, a `cd`, or an assignment of a plain value: it could make a link or run anything.
 */
function priorState(steps, finalSep, shell, sessionId) {
  const vars = new Map();
  let cwd = null;
  // `&`, `|` and `||` around a `cd` or an assignment: it runs in the background, in a pipe, or maybe not at all.
  const chained = (sep) => !/[&|]/.test(sep.replace(/&&/g, ''));
  const cdCommands = shell === 'powershell' ? CD_COMMANDS : shell === 'bash' ? BASH_CD : PLAIN_CD;
  const seps = [...steps.slice(1).map((s) => s.sep), finalSep];
  let deleted = false;
  for (let i = 0; i < steps.length; i += 1) {
    const text = steps[i].text.trim();
    const assignment = parseAssignment(text, shell);
    const command = assignment ? '' : effectiveCommand(text);
    if (assignment || CD_COMMANDS.has(command)) {
      if (!chained(steps[i].sep) || !chained(seps[i])) return null;
    }
    if (assignment) {
      if (RESERVED_VARS.test(assignment[0])) return null;
      const value = literalPath(assignment[1], vars, shell);
      if (value === null) return null;
      vars.set(assignment[0], value);
    } else if (CD_COMMANDS.has(command)) {
      // A spelling this shell does not know fails, and `;` runs the delete in the real folder.
      cwd = cdCommands.has(command) ? changeDir(text, command, cwd, vars, shell, sessionId) : null;
      // An earlier delete may remove the target (or fail and skip the `cd`): only an unbroken `&&` chain
      // from the `cd` to the final delete keeps that delete from running elsewhere.
      if (deleted && seps.slice(i).some((sep) => sep.trim() !== '&&')) cwd = null;
    } else if (DELETERS.has(command)) deleted = true;
    else return null;
  }
  return { vars, cwd };
}

/** The operand as an absolute path: relative ones resolve against the folder a `cd` set, else null. */
function absolutize(operand, cwd) {
  const path = operand.replace(/\\/g, '/');
  return /^[a-z]:\//i.test(path) || path.startsWith('/') ? path : cwd && `${cwd}/${path.replace(/^(?:\.\/)+/, '')}`;
}

/** True when a symbolic link or junction (or too much to look through) sits anywhere under `root`. */
function holdsLink(root, budget = { left: 20000 }) {
  let entries;
  try { entries = fs.readdirSync(root, { withFileTypes: true }); } catch (error) { return error?.code !== 'ENOENT' && error?.code !== 'ENOTDIR'; }
  for (const entry of entries) {
    budget.left -= 1;
    if (entry.isSymbolicLink() || budget.left < 0) return true;
    if (entry.isDirectory() && holdsLink(`${root}/${entry.name}`, budget)) return true;
  }
  return false;
}

/** A delete that recurses or forces: `rm -rf`, `rm -R`, `Remove-Item -Recurse`, `rd /s`. Not one aimed only at Claude's own temp folders. */
function deletesRecursively(scan, keep, segment, piped, line, sessionId = undefined) {
  const command = effectiveCommand(segment);
  if (!DELETERS.has(command)) return false;
  const recursive = command === 'rm'
    ? /(?<![-\w])(?:-[a-zA-Z]*[rRf][a-zA-Z]*|--recursive|--force)(?![\w-])/.test(keep)
    : /(?<![-\w])-(?:r|rec\w*|fo\w*)(?![\w-])/i.test(keep) || /(?<!\S)\/[sf](?!\w)/i.test(keep);
  if (!recursive) return false;
  // The hook reads every segment before any runs: a link made earlier on the same line (by any tool or
  // interpreter) is not on disk yet. So the exemption holds only when every segment before the delete is a
  // delete, a `cd` or an assignment (what comes after cannot touch it). A nested text (`bash -c "…"`) is not
  // one of the line's segments: its surroundings are unknown.
  if (!line || /'[^']*\$/.test(segment)) return true;
  const state = priorState(line.steps, line.sep, line.shell, sessionId);
  if (!state || LINK_CREATOR.test([...line.steps.map((s) => s.text), segment].join(' '))) return true;
  const operands = deleteOperands(expandVars(segment, state.vars, line.shell), command);
  if (!operands) return true;
  // Windows PowerShell 5.1 `Remove-Item -Recurse` can follow a junction inside the tree, and there `rm`, `del`,
  // `rd`, `rmdir` and `erase` are its aliases: on Windows look for one first.
  const mayFollowLinks = process.platform === 'win32' || command === 'remove-item' || command === 'ri';
  return !operands.every((operand) => {
    const target = absolutize(operand, state.cwd);
    return target && isThrowawayPath(target, sessionId) && !(mayFollowLinks && holdsLink(target));
  });
}

/** `git [-c k=v] <verb> …`: the verb is the first word after git and its options, never a word inside a message. */
const GIT_VERB = /\bgit\s+(?:(?:-[cC]\s+\S+|--(?:git-dir|work-tree|namespace|exec-path|config-env|super-prefix)\s+\S+|--[\w-]+(?:=\S+)?)\s+)*(checkout|restore|clean|reset|branch|update-ref|filter-branch|gc)(?![\w-])/i;
function gitCall(text) {
  const m = GIT_VERB.exec(text);
  return m ? { verb: m[1].toLowerCase(), rest: text.slice(m.index + m[0].length) } : null;
}
const flagCluster = (letter) => new RegExp(`(?<![-\\w])-[a-zA-Z]*${letter}[a-zA-Z]*(?![\\w-])`);

/** `git clean` that really deletes: forced and not a dry run (`-n` anywhere in a cluster). */
function cleanDeletes(scan, keep) {
  const call = gitCall(keep);
  if (call?.verb !== 'clean') return false;
  return (flagCluster('f').test(call.rest) || /(?<![-\w])--force(?![\w-])/.test(call.rest)) && !flagCluster('n').test(call.rest);
}

/** `git reset --hard` moves the branch and rewrites the working tree: uncommitted work is gone. */
function resetsHard(scan, keep) {
  const call = gitCall(keep);
  return call?.verb === 'reset' && /(?<![-\w])--hard(?![\w-])/.test(call.rest);
}

/**
 * `git branch` that moves, renames or copies over a branch. A local delete, forced or not, passes: the owner's
 * choice for unattended work, the reflog keeps its commits.
 */
function branchRewrites(scan, keep) {
  const call = gitCall(keep);
  if (call?.verb !== 'branch') return false;
  const moves = /(?<!\S)-[a-zA-Z]*[mMcC][a-zA-Z]*(?![\w-])/.test(call.rest) || /(?<!\S)--(?:move|copy)(?![\w-])/.test(call.rest);
  const deletes = /(?<!\S)-[a-zA-Z]*[dD][a-zA-Z]*(?![\w-])/.test(call.rest) || /(?<!\S)--delete(?![\w-])/.test(call.rest);
  return moves || (!deletes && (flagCluster('f').test(call.rest) || /(?<!\S)--force(?![\w-])/.test(call.rest)));
}

/** `git update-ref -d`, `git filter-branch`, `git gc --prune=now`: refs or objects with no way back. */
function rewritesHistory(scan, keep) {
  const call = gitCall(keep);
  if (!call) return false;
  if (call.verb === 'filter-branch') return true;
  if (call.verb === 'update-ref') return /(?<!\S)(?:-d|--delete)(?![\w-])/.test(call.rest);
  return call.verb === 'gc' && /(?<!\S)--prune=(?:now|all)(?!\S)/.test(call.rest);
}

/** `docker rm -f|-v`, `docker container rm -f`, `docker rmi -f`: a running container or image is removed, volumes with it. */
function dockerRemoves(scan, keep) {
  const m = /\b(?:docker|podman|nerdctl)(?:\.exe)?\s+(?:(?:container|image|compose)\s+)?(rm|rmi)(?![-\w])(.*)$/i.exec(keep);
  if (!m) return false;
  const forced = /(?<!\S)-[a-zA-Z]*f[a-zA-Z]*(?![\w-])|(?<!\S)--force(?![\w-])/.test(m[2]);
  const volumes = m[1].toLowerCase() === 'rm' && (/(?<!\S)-[a-zA-Z]*v[a-zA-Z]*(?![\w-])|(?<!\S)--volumes(?![\w-])/.test(m[2]));
  return forced || volumes;
}

/** `find … -delete`,`find … -exec rm …`: the walk itself deletes what it matches. */
function findDeletes(scan, keep, segment) {
  if (effectiveCommand(segment) !== 'find') return false;
  return /(?<![\w-])-delete(?![\w-])/.test(keep)
    || /(?<![\w-])-exec(?:dir)?\s+(?:\S*[\\/])?(?:rm|rmdir|del|unlink|shred)(?![\w-])/i.test(keep);
}

