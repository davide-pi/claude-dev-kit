/**
 * Check: the arguments of the kit's own allowed script (`db-ro.ps1`).
 *
 * settings.json allows `pwsh -NoProfile -File ~/.claude/scripts/db-ro.ps1 *` by
 * prefix, so whatever follows the prefix is approved without a prompt. The tail is read
 * with an allowlist grammar, not a blacklist: both shells run code in places a list of known
 * constructs misses (PowerShell argument mode evaluates `(…)`, `@(…)`, `$x.Method()`; Bash runs
 * `<(…)`, `>(…)`, `$(…)`, backticks). What may pass without a prompt is:
 *
 *   - single-quoted text, whatever it holds (literal in both shells);
 *   - double-quoted text without `$` or a backtick (both shells expand there);
 *   - unquoted text without any of `$ ( ) @ { } < > \ ; & |`, `%` or a backtick.
 *
 * An unquoted `$ ( ) @ { } \ ; & | %` or backtick, and a `$` or backtick inside double quotes, are
 * denied with a hint (wrap the value in single quotes): a re-quote fixes them. An unquoted `<` or `>` (a
 * redirection, which no re-quote fixes), an unbalanced quote, a typographic quote (PowerShell reads those as
 * quotes, the tokenizer here would not) and a non-ASCII character ask. Plus one rule on `db-ro.ps1`: its `-AcceptWriteGrant`
 * switch waives the read-only proof of a credential that holds write grants, so any argument that
 * starts with `-a` (the only db-ro parameter starting with `a`) asks, quoted or not: the shell strips
 * the quotes before pwsh binds it. A `-amount` inside a longer quoted query is data, not a token start.
 * A `"$VAR"` argument passes when the same line assigned VAR once to a plain literal just before (see `resolveCalls`):
 * it is read as that literal, so the grant check above still sees the real value.
 *
 * Text analysis only, no I/O.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const { splitSegments, RESERVED_VARS, parseAssignment } = require('./shell-parse');

const SCRIPT = /^pwsh\s+-NoProfile\s+-File\s+(["']?)~[\\/]\.claude[\\/]scripts[\\/](db-ro)\.ps1(?=$|[\s"'])/i;
/** PowerShell takes an en dash, an em dash or a horizontal bar as a parameter prefix too. */
const ABBREVIATED_GRANT_SWITCH = /^[-–—―]a/i;
const UNQUOTED_DANGER = /[$(){}<>@\\`%;&|]/;
/** A merge of streams or a null sink (`2>&1`, `2>/dev/null` in Bash, `2>$null`): it writes no file and runs no code. */
const SAFE_REDIRECT = /(?<=\s)(?:[12*]?>&[12]|[12*]?>\s*(?:\/dev\/null|\$null))(?=\s|$|[;|])/g;
const NON_ASCII_PRINTABLE = /[^\x21-\x7e]/;
/** PowerShell reads these as quote characters; the tokenizer below knows only ' and ". */
const TYPOGRAPHIC_QUOTE = /[‘’‚‛“”„]/;

/**
 * Walks the argument text with quotes honoured. Returns the tokens (split on unquoted whitespace,
 * quotes stripped), or the reason it must ask.
 */
function tokenize(text, posix) {
  // Every risk is remembered and the scan goes on, the risky character kept as data: a deny later in the
  // text wins over an ask, and the tokens still reach the -AcceptWriteGrant check.
  let risk = TYPOGRAPHIC_QUOTE.test(text) ? 'a typographic quote that PowerShell reads as a quote' : null;
  let denyRisk = null;
  const tokens = [];
  let token = null;
  let quote = null;
  for (const c of text) {
    if (quote) {
      if (c === quote) quote = null;
      else {
        if (quote === '"' && (c === '$' || c === '`')) denyRisk ??= `a ${c === '$' ? '$' : 'backtick'} inside double quotes`;
        // An escape in Bash this tokenizer does not follow: what comes after may sit outside the quotes there.
        else if (quote === '"' && c === '\\' && posix) risk ??= 'a backslash inside double quotes (an escape in Bash)';
        token += c;
      }
    } else if (c === '"' || c === "'") {
      quote = c;
      token ??= '';
    } else if (c === ' ' || c === '\t') {
      if (token) { tokens.push(token); token = null; }
    } else if (c === '<' || c === '>') {
      // A redirection (`2>&1`, `> out.txt`) is meant as one: a re-quote hint would not fix it, so it asks.
      risk ??= `an unquoted ${c} (a redirection)`;
      token = (token ?? '') + c;
    } else if (UNQUOTED_DANGER.test(c)) {
      denyRisk ??= `an unquoted ${c === '`' ? 'backtick' : c}`;
      token = (token ?? '') + c;
    } else if (NON_ASCII_PRINTABLE.test(c)) {
      // PowerShell also splits on Unicode spaces (U+00A0, U+2000-U+200A, ...): this tokenizer does not.
      risk ??= 'an unquoted character outside printable ASCII';
      token = (token ?? '') + c;
    } else {
      token = (token ?? '') + c;
    }
  }
  if (quote) risk ??= 'an unbalanced quote';
  if (token) tokens.push(token);
  return { tokens, risk, denyRisk };
}

const ask = (reason) => ({ decision: 'ask', reason });

/** What a variable may hold to be read as a plain literal: no space, glob, quote or substitution character. */
const SAFE_VALUE = { bash: /^[\w./:@+,~-]+$/, powershell: /^[\w./:@+,~\\-]+$/ };
/** A line that sets a variable changing how the shell splits words or finds commands: nothing resolves. */
const RESERVED_ASSIGNMENT = new RegExp(String.raw`(?<!\w)\$?${RESERVED_VARS.source.replace(/^\^|\$$/g, '')}\s*\+?=`, 'i');
/** Between two chained segments: `;`, `&&` or a newline, never a pipe, `&`, `||` or a group. */
const SEGMENT_GAP = /^\s*(?:;|&&)?\s*$/;
const CD_LITERAL = /^(?:cd|pushd|chdir|set-location|sl)\s+(?:"[^"$`]*"|'[^']*'|[\w./:@+,~\\-]+)$/i;
const DEFINES_COMMAND = /(?:^|[\s;&|(])(?:function|filter|set-alias|new-alias|sal|nal|alias)\s|(?<!\$)[\w.-]+\s*\(\s*\)/i;
/** `text` with the inside of every quoted string blanked: a `name()` in a commit message defines nothing. */
const unquoted = (text) => text.replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, '""');
const PLAIN_CALL =/^(?:git|node|dotnet|npm|npx)(?:\s|$)/i;

/** `text` with `$NAME` / `${NAME}` outside single quotes replaced by the literal in `vars`; what it cannot resolve stays. */
function resolveVars(text, vars, shell) {
  if (!vars.size) return text;
  let out = '';
  let quote = null;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote === "'") {
      if (c === "'") quote = null;
    } else if (c === '"') {
      quote = quote === '"' ? null : '"';
    } else if (c === "'" && !quote) {
      quote = "'";
    } else if (c === '$') {
      const m = /^\$(?:\{(\w+)\}|(\w+))/.exec(text.slice(i, i + 80));
      const name = m && (m[1] ?? m[2]);
      const value = name === null || name === undefined ? undefined : vars.get(shell === 'powershell' ? name.toLowerCase() : name);
      // PowerShell reads `$b:x`, `$b.Length` and `$b[0]` as scope, member and index access: not a plain value.
      const next = text[i + (m?.[0].length ?? 0)] ?? '';
      if (value !== undefined && !(shell === 'powershell' && /[:.[(]/.test(next))) {
        out += quote ? value : `'${value}'`;
        i += m[0].length - 1;
        continue;
      }
    }
    out += c;
  }
  return out;
}

/**
 * The segments of a line, with the variables a kit-script call uses resolved when this line assigned each one
 * exactly once to a plain literal and every segment between the assignment and the call is inert (another
 * assignment, a `cd` with a literal folder, a git / node / dotnet / npm / npx call without a group or substitution),
 * joined by `;`, `&&` or a newline. Anything else clears what was assigned before it.
 */
function resolveCalls(text, tool) {
  const segments = splitSegments(text);
  const shell = tool === 'Bash' ? 'bash' : tool === 'PowerShell' ? 'powershell' : null;
  // A function or alias may shadow `git` / `node`: no call is inert then.
  if (!shell || RESERVED_ASSIGNMENT.test(text) || DEFINES_COMMAND.test(/\b(?:eval|iex|invoke-expression)\b/i.test(text) ? text : unquoted(text))) return segments;
  const entries = [];
  let at = 0;
  for (const segment of segments) {
    const start = text.indexOf(segment, at);
    entries.push({ segment, sep: text.slice(at, start), assignment: parseAssignment(segment.trim(), shell) });
    at = start + segment.length;
  }
  const counts = new Map();
  for (const { assignment } of entries) if (assignment) counts.set(assignment[0], (counts.get(assignment[0]) ?? 0) + 1);
  const vars = new Map();
  return entries.map((entry, i) => {
    const trimmed = entry.segment.trim();
    if (i > 0 && !SEGMENT_GAP.test(entry.sep)) { vars.clear(); return entry.segment; }
    if (entry.assignment) {
      const [name, value] = entry.assignment;
      const mention = new RegExp(String.raw`(?<!\w)\$?${name}(?!\w)`, shell === 'powershell' ? 'i' : '');
      // A mention before the assignment (`readonly A`, `declare -n A`) may make it land elsewhere.
      if (counts.get(name) === 1 && SAFE_VALUE[shell].test(value) && !entries.slice(0, i).some((earlier) => mention.test(earlier.segment))) vars.set(name, value);
      return entry.segment;
    }
    if (SCRIPT.test(trimmed)) return resolveVars(entry.segment, vars, shell);
    if (!(CD_LITERAL.test(trimmed) || (PLAIN_CALL.test(trimmed) && !/[`{]|[$<>]\(/.test(trimmed) && !unquoted(trimmed).includes('(')))) vars.clear();
    return entry.segment;
  });
}

/**
 * The command with SAFE_REDIRECT dropped from its unquoted text only: inside quotes it is data the checks still read.
 * Matched on a copy with every quoted span masked, so a redirect glued to a quoted word (`>&1"out.txt"`) stays.
 */
function dropSafeRedirects(command, tool) {
  const masked = command.replace(/'[^']*'|"[^"]*"/g, (quoted) => 'q'.repeat(quoted.length));
  let kept = '';
  let from = 0;
  for (const match of masked.matchAll(SAFE_REDIRECT)) {
    // `/dev/null` is a null sink in Bash only: PowerShell writes a file at that path.
    if (tool !== 'Bash' && match[0].includes('/dev/null')) continue;
    kept += `${command.slice(from, match.index)} `;
    from = match.index + match[0].length;
  }
  return kept + command.slice(from);
}

/**
 * `{ decision, reason }` when an allowed script is called with a risky argument, else null. A quoting
 * risk that a re-quote fixes is a deny with the hint; every other risk asks.
 */
function checkScriptArgs(command, tool) {
  if (!/\.claude[\\/]scripts[\\/]db-ro\.ps1/i.test(command)) return null;
  // Every segment is read: every ask reason is kept, a deny anywhere wins (the ask reasons ride along).
  const asks = [];
  let denial = null;
  const note = (reason) => { if (!asks.includes(reason)) asks.push(reason); };
  // Dropped before the split, which would cut `2>&1` at its `&`.
  for (const segment of resolveCalls(dropSafeRedirects(command, tool), tool)) {
    const match = SCRIPT.exec(segment.trim());
    if (!match) continue;
    const script = `${match[2].toLowerCase()}.ps1`;
    let tail = segment.trim().slice(match[0].length);
    if (match[1]) { // the script path was itself quoted: the next character closes it
      // Still tokenized as it stands: a substitution or a grant switch in the tail must not hide behind this ask.
      if (tail[0] !== match[1]) note(`The path of ${script} is quoted in a way the check cannot follow. Confirm?`);
      else tail = tail.slice(1);
    }
    const { tokens, risk, denyRisk } = tokenize(tail, tool === 'Bash');
    if (denyRisk) {
      denial ??= `The arguments of ${script} hold ${denyRisk}: it could run code before the script starts, outside the allowed call. `
        + 'Wrap the value in single quotes, doubling any single quote inside it.';
    }
    if (risk) {
      note(`The arguments of ${script} hold ${risk}: it could run code before the script starts, `
        + 'outside the allowed call. Quote text in single quotes. Confirm?');
    }
    if (script === 'db-ro.ps1' && tokens.some((t) => ABBREVIATED_GRANT_SWITCH.test(t))) {
      note('This db-ro.ps1 call carries -AcceptWriteGrant (or an abbreviation that could): '
        + 'accepting a credential with write grants needs your explicit consent. Confirm?');
    }
  }
  if (denial) return { decision: 'deny', reason: [denial, ...asks].join('\n\n') };
  return asks.length ? ask(asks.join('\n\n')) : null;
}

module.exports = { checkScriptArgs };
