/**
 * The one shell-line parser every guard shares: a command line in, its chained commands out, with
 * whatever a shell wrapper or a substitution hides inside them.
 *
 *   - `parseSegments` tokenizes and STRIPS quotes (the git check reads tokens, and
 *     `-c credential.helper='!gh auth git-credential' push` must still yield `push`);
 *   - `splitSegments` KEEPS quotes and their contents (the destructive check looks for the danger
 *     *inside* a quoted argument: `sqlcmd -Q "DROP TABLE x"`);
 *   - `expandSegments` / `expandTexts` also walk into `bash -c "..."`, `pwsh -c`, `cmd /c`, `wsl`,
 *     `ssh host "..."`, `docker exec <c> sh -c "..."` and into `$(...)`, backticks and `<(...)`,
 *     as token lists / as raw command strings, so a check that reads either also sees what a
 *     wrapper runs;
 *   - `unquotedHas` answers "does this line carry one of these characters outside quotes".
 *
 * In all of them a separator inside quotes does not split. None is a shell parser: they only have to
 * keep separate commands apart. Whatever they get wrong costs an extra confirmation, never a silent
 * approval.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const isSeparator = (c) => c === ';' || c === '|' || c === '&' || c === '\n' || c === '\r';

/** One segment per chained command, each a list of tokens with quotes honoured and stripped. */
function parseSegments(command) {
  const segments = [];
  let tokens = [];
  let token = '';
  let quote = null;

  const endToken = () => { if (token) { tokens.push(token); token = ''; } };
  const endSegment = () => { endToken(); if (tokens.length) { segments.push(tokens); tokens = []; } };

  for (const c of command) {
    if (quote) {
      if (c === quote) quote = null;
      else token += c;
    } else if (c === '"' || c === "'") {
      quote = c;
    } else if (isSeparator(c)) {
      endSegment();
    } else if (c === ' ' || c === '\t' || c === '`') {
      // A backtick is PowerShell's escape and bash's command substitution: a token boundary, not a
      // command boundary — a `git push` inside backticks still pushes.
      endToken();
    } else {
      token += c;
    }
  }
  endSegment();
  return segments;
}

/** One segment per chained command, as raw text with quotes and their contents intact. */
function splitSegments(command) {
  const segments = [];
  let current = '';
  let quote = null;

  const push = () => { if (current.trim()) segments.push(current); current = ''; };

  for (const c of command) {
    if (quote) {
      current += c;
      if (c === quote) quote = null;
    } else if (c === '"' || c === "'") {
      quote = c;
      current += c;
    } else if (isSeparator(c)) {
      push();
    } else {
      current += c;
    }
  }
  push();
  return segments;
}

/**
 * The pipelines of a line, each as its stages (raw text): `a | b && c` gives `[[a, b], [c]]`.
 * A `||` and every other separator end the pipeline; only a single `|` chains stages.
 */
function splitPipelines(command) {
  const pipelines = [];
  let stages = [];
  let current = '';
  let quote = null;
  const endStage = () => { if (current.trim()) stages.push(current); current = ''; };
  const endPipeline = () => { endStage(); if (stages.length) pipelines.push(stages); stages = []; };

  for (let i = 0; i < command.length; i += 1) {
    const c = command[i];
    if (quote) {
      current += c;
      if (c === quote) quote = null;
    } else if (c === '"' || c === "'") {
      quote = c;
      current += c;
    } else if (c === '|' && command[i + 1] !== '|' && command[i - 1] !== '|') {
      endStage();
    } else if (isSeparator(c)) {
      endPipeline();
    } else {
      current += c;
    }
  }
  endPipeline();
  return pipelines;
}

/** True when one of `chars` sits outside quotes, or a quote is never closed. */
function unquotedHas(command, chars) {
  let quote = null;
  for (const c of command) {
    if (quote) { if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'") quote = c;
    else if (chars.has(c)) return true;
  }
  return quote !== null;
}

/** Commands that look for a string in text or files: what they are given is a pattern, not a target. */
const SEARCHERS = new Set(['grep', 'egrep', 'fgrep', 'rg', 'ripgrep', 'ack', 'ag', 'findstr', 'select-string', 'sls']);

// ── Wrappers ─────────────────────────────────────────────────────────────────────────────────

const CONTAINER_CLIS = new Set(['docker', 'podman', 'nerdctl']);
const SHELLS = new Set(['pwsh', 'powershell', 'bash', 'sh', 'zsh', 'dash', 'ash', 'ksh', 'cmd']);
const POWERSHELLS = new Set(['pwsh', 'powershell']);
/** Words that put a command in command position without being the command. */
const WRAPPERS = new Set(['sudo', 'call', 'command', 'env', 'time', 'nohup', 'start', 'start-process', 'exec']);
/** Wrapper options that take a value (`sudo -u postgres psql`). */
const WRAPPER_VALUE_OPTS = new Set(['-u', '-g', '-h', '-p', '-c', '-d', '--user', '--group']);
/** `wsl` options that take a value; `-e`, `--exec` and `--` end the options. */
const WSL_VALUE_OPTS = new Set(['-d', '--distribution', '-u', '--user', '--cd', '--shell-type', '--distribution-id']);
/** `ssh` options that take a value; the first other word is the host, the rest is the remote command. */
const SSH_VALUE_OPTS = new Set(['-p', '-i', '-l', '-o', '-F', '-J', '-L', '-R', '-D', '-b', '-c', '-E', '-e', '-I', '-m', '-O', '-Q', '-S', '-W', '-w']);
/**
 * The flag after which a shell takes its command, per family. POSIX shells accept it clustered with
 * other short options (`-ec`, `-xc`, `-lic`); PowerShell accepts any abbreviation of `-Command`
 * (`-c`, `-Comm`, `-CommandWithArgs`) but its other options (`-ExecutionPolicy`, `-NonInteractive`)
 * contain a `c` too, so it is matched by name; `cmd` takes `/c` and `/k`. A `--long` option is none.
 */
const POSIX_SHELL_FLAG = /^-[A-Za-z]*c[A-Za-z]*$/;
const POWERSHELL_FLAG = /^-(?:c|com\w*|cwa)$/i;
const CMD_FLAG = /^[/-][ck]$/i;
const shellFlag = (shell) => (POWERSHELLS.has(shell) ? POWERSHELL_FLAG : shell === 'cmd' ? CMD_FLAG : POSIX_SHELL_FLAG);
const ASSIGNMENT = /^[A-Za-z_]\w*=/;

/** A token as a command name: no directory, no extension, lowercase. */
function baseName(token) {
  return String(token)
    .replace(/^.*[\\/]/, '')
    .replace(/\.(?:exe|cmd|bat|ps1)$/i, '')
    .toLowerCase();
}

/** Skip `sudo [-u x]`, `env VAR=x`, `call`, ... until the real command. */
function stripWrappers(tokens) {
  let i = 0;
  while (i < tokens.length) {
    if (ASSIGNMENT.test(tokens[i])) { i += 1; continue; }
    if (!WRAPPERS.has(baseName(tokens[i]))) break;
    i += 1;
    while (i < tokens.length && tokens[i].startsWith('-')) i += WRAPPER_VALUE_OPTS.has(tokens[i]) ? 2 : 1;
  }
  return tokens.slice(i);
}

/** What follows `rest` as a nested command: its raw text, and its tokens when it was not one string. */
function nested(rest) {
  if (!rest.length) return [];
  if (rest.length === 1 && /\s/.test(rest[0])) return [{ text: rest[0] }];
  return [{ text: rest.join(' '), tokens: rest }];
}

/** The command that follows the shell's command flag: one quoted string, or the command itself. */
function shellInner(tokens, from, shell) {
  const isFlag = shellFlag(shell);
  const flag = tokens.findIndex((t, i) => i >= from && isFlag.test(t));
  return flag < 0 ? [] : nested(tokens.slice(flag + 1));
}

/** `wsl [-d distro] [-u user] [-e|--exec|--] cmd ...` -> `cmd ...`. */
function afterWsl(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) {
    const t = tokens[i];
    if (t === '-e' || t === '--exec' || t === '--') { i += 1; break; }
    i += WSL_VALUE_OPTS.has(t) ? 2 : 1;
  }
  return tokens.slice(i);
}

/** `ssh [opts] host cmd ...` -> `cmd ...` (ssh itself joins the words with spaces). */
function afterSsh(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) i += SSH_VALUE_OPTS.has(tokens[i]) ? 2 : 1;
  return tokens.slice(i + 1);
}

/** The commands one command runs on behalf of its wrapper: `bash -c "..."`, `docker exec c sh -c "..."`, `ssh h "..."`. */
function innerOf(cmd) {
  const name = baseName(cmd[0]);
  if (name === 'wsl') return nested(afterWsl(cmd));
  if (name === 'ssh') return nested(afterSsh(cmd));
  if (SHELLS.has(name)) return shellInner(cmd, 1, name);
  const launch = CONTAINER_CLIS.has(name) ? cmd.findIndex((t) => /^(?:exec|run)$/i.test(t)) : -1;
  if (launch < 0) return [];
  for (let i = launch + 1; i < cmd.length; i += 1) {
    const shell = baseName(cmd[i]);
    if (SHELLS.has(shell)) return shellInner(cmd, i + 1, shell);
  }
  return [];
}

/** `innerOf` as token lists: one per chained command of a nested string. */
const innerSegments = (cmd) => innerOf(cmd).flatMap((i) => (i.tokens ? [i.tokens] : parseSegments(i.text)));

const QUOTED_HEREDOC = /^\s*cat\s+<<-?\s*'\w+'/;

/** The inside of every `$(...)`, `<(...)`, `>(...)` and backtick pair outside single quotes. */
function substitutions(text) {
  const out = [];
  let quote = null;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quote === "'") { if (c === "'") quote = null; continue; }
    if (c === "'") { quote = "'"; continue; }
    if (c === '"') { quote = quote === '"' ? null : '"'; continue; }
    if (c === '`') {
      const end = text.indexOf('`', i + 1);
      if (end > i) { out.push(text.slice(i + 1, end)); i = end; }
    } else if (text[i + 1] === '(' && (c === '$' || c === '<' || c === '>')) {
      let depth = 0;
      let j = i + 1;
      for (; j < text.length; j += 1) {
        if (text[j] === '(') depth += 1;
        else if (text[j] === ')' && (depth -= 1) === 0) break;
      }
      const inner = text.slice(i + 2, j);
      // `$(cat <<'EOF' ... EOF)` is a commit message or a file body: quoted heredoc text is data.
      if (!QUOTED_HEREDOC.test(inner)) out.push(inner);
      i += 1;
    }
  }
  return out;
}

/** True when `text` carries a substitution or a process substitution outside single quotes. */
const hasSubstitution = (text) => substitutions(text).length > 0;

const MAX_DEPTH = 4;

/**
 * Every command of a line, the nested ones included, as `{ tokens, text }`: `text` is the raw
 * command string the tokens came from (the whole line for the top level).
 */
function walk(command) {
  const out = [];
  const visitText = (text, depth) => {
    out.push({ text, tokens: null });
    for (const tokens of parseSegments(text)) visitTokens(tokens, depth);
    if (depth < MAX_DEPTH) for (const inner of substitutions(text)) visitText(inner, depth + 1);
  };
  const visitTokens = (tokens, depth) => {
    out.push({ text: null, tokens });
    if (depth >= MAX_DEPTH) return;
    const cmd = stripWrappers(tokens);
    if (!cmd.length) return;
    for (const inner of innerOf(cmd)) {
      if (inner.tokens) { out.push({ text: inner.text, tokens: null }); visitTokens(inner.tokens, depth + 1); }
      else visitText(inner.text, depth + 1);
    }
  };
  visitText(command, 0);
  return out;
}

/** Every command of a line as a token list, wrapper and substitution contents included. */
const expandSegments = (command) => walk(command).filter((e) => e.tokens).map((e) => e.tokens);

/** The line itself and every command string nested in it (`bash -c "..."`, `$(...)`, `ssh h "..."`). */
const expandTexts = (command) => walk(command).filter((e) => e.text !== null).map((e) => e.text);

module.exports = {
  parseSegments, splitSegments, splitPipelines, unquotedHas, expandSegments, expandTexts, hasSubstitution,
  stripWrappers, baseName, SEARCHERS, SHELLS, CONTAINER_CLIS, innerOf, innerSegments,
};
