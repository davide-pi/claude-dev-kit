const SEARCHERS = new Set(['grep', 'egrep', 'fgrep', 'rg', 'ripgrep', 'ack', 'ag', 'findstr', 'select-string', 'sls']);

// ── Wrappers ─────────────────────────────────────────────────────────────────────────────────

const CONTAINER_CLIS = new Set(['docker', 'podman', 'nerdctl']);
const SHELLS = new Set(['pwsh', 'powershell', 'bash', 'sh', 'zsh', 'dash', 'ash', 'ksh', 'cmd']);
const POWERSHELLS = new Set(['pwsh', 'powershell']);
/** Words that put a command in command position without being the command. */
const WRAPPERS = new Set(['sudo', 'call', 'command', 'env', 'time', 'nohup', 'start', 'start-process', 'exec', 'timeout', 'nice']);
/** Wrapper options that take a value (`sudo -u postgres psql`). */
const WRAPPER_VALUE_OPTS = new Set(['-u', '-g', '-h', '-p', '-c', '-d', '--user', '--group']);
/** Options of one wrapper that take a value (`nice -n 10`; `-n` is a flag for sudo), and wrappers that then take a positional (`timeout 5`). */
const OWN_VALUE_OPTS = { timeout: new Set(['-s', '-k', '--signal', '--kill-after']), nice: new Set(['-n', '--adjustment']), command: new Set() };
const LEADING_POSITIONAL = new Set(['timeout']);
/** `wsl` options that take a value; `-e`, `--exec` and `--` end the options. */
const WSL_VALUE_OPTS = new Set(['-d', '--distribution', '-u', '--user', '--cd', '--shell-type', '--distribution-id']);
/** `ssh` options that take a value; the first other word is the host, the rest is the remote command. */
const SSH_VALUE_OPTS = new Set(['-p', '-i', '-l', '-o', '-F', '-J', '-L', '-R', '-D', '-b', '-c', '-E', '-e', '-I', '-m', '-O', '-Q', '-S', '-W', '-w']);
/**
 * The flag after which a shell takes its command, per family. POSIX shells accept it clustered with
 * other short options (`-ec`, `-xc`, `-lic`); PowerShell accepts any abbreviation of `-Command`
 * (`-c`, `-Comm`, `-CommandWithArgs`) but its other options (`-ExecutionPolicy`, `-NonInteractive`)
 * contain a `c` too, so it is matched by name; `cmd` takes `/c` and `/k`. A `--long` option is none.
 */
const POSIX_SHELL_FLAG = /^-[A-Za-z]*c[A-Za-z]*$/;
const POWERSHELL_FLAG = /^-(?:c|com\w*|cwa)$/i;
/** `-EncodedCommand` as PowerShell takes it: any prefix of the name, `-ec`, behind a dash, a slash or a Unicode dash. `-File` ends the options. */
const ENCODED_FLAG = /^[-/\u2010-\u2015\u2212]([A-Za-z]+)$/;
const isEncodedFlag = (t) => { const m = ENCODED_FLAG.exec(t); const name = m && m[1].toLowerCase(); return Boolean(name) && (name === 'ec' || 'encodedcommand'.startsWith(name)); };
const FILE_FLAG = /^[-/]f(?:i(?:l(?:e)?)?)?$/i;
const LONE_SURROGATE = /[\ud800-\udbff](?![\udc00-\udfff])|(?<![\ud800-\udbff])[\udc00-\udfff]/;

/** The text a PowerShell `-EncodedCommand` payload holds (base64 of UTF-16LE), as a nested command, or an opaque marker when it cannot be read. */
function decodeEncoded(payload) {
  const opaque = (why) => [{ text: '', opaque: `A PowerShell -EncodedCommand payload the guard could not read (${why}): it may hide anything.` }];
  if (payload === undefined) return opaque('no payload');
  if (!/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(payload)) return opaque('not base64');
  const bytes = Buffer.from(payload, 'base64');
  if (bytes.length % 2) return opaque('not UTF-16LE');
  const text = bytes.toString('utf16le');
  return LONE_SURROGATE.test(text) ? opaque('not UTF-16LE') : [{ text, encoded: true }];
}
const CMD_FLAG = /^[/-][ck]$/i;
const shellFlag = (shell) => (POWERSHELLS.has(shell) ? POWERSHELL_FLAG : shell === 'cmd' ? CMD_FLAG : POSIX_SHELL_FLAG);
const ASSIGNMENT = /^[A-Za-z_]\w*=/;

/** A token as a command name: no directory, no extension, lowercase. */
function baseName(token) {
  return String(token)
    .replace(/^.*[\\/]/, '')
    .replace(/\.(?:exe|cmd|bat|ps1)$/i, '')
    .toLowerCase();
}

/** Skip `sudo [-u x]`, `env VAR=x`, `call`, ... until the real command. */
function stripWrappers(tokens) {
  let i = 0;
  while (i < tokens.length) {
    if (ASSIGNMENT.test(tokens[i])) { i += 1; continue; }
    const wrapper = baseName(tokens[i]);
    if (!WRAPPERS.has(wrapper)) break;
    i += 1;
    const own = OWN_VALUE_OPTS[wrapper];
    while (i < tokens.length && tokens[i].startsWith('-')) i += (own ? own.has(tokens[i]) : WRAPPER_VALUE_OPTS.has(tokens[i])) ? 2 : 1;
    if (LEADING_POSITIONAL.has(wrapper)) i += 1;
  }
  return tokens.slice(i);
}

/** What follows `rest` as a nested command: its raw text, and its tokens when it was not one string. */
function nested(rest) {
  if (!rest.length) return [];
  if (rest.length === 1 && /\s/.test(rest[0])) return [{ text: rest[0] }];
  return [{ text: rest.join(' '), tokens: rest }];
}

/** The command that follows the shell's command flag: one quoted string, or the command itself. */
function shellInner(tokens, from, shell) {
  const isFlag = shellFlag(shell);
  const flag = tokens.findIndex((t, i) => i >= from && isFlag.test(t));
  if (POWERSHELLS.has(shell)) {
    const end = tokens.findIndex((t, i) => i >= from && FILE_FLAG.test(t));
    const encoded = tokens.findIndex((t, i) => i >= from && isEncodedFlag(t));
    if (encoded >= 0 && (end < 0 || encoded < end) && (flag < 0 || encoded < flag)) return decodeEncoded(tokens[encoded + 1]);
  }
  return flag < 0 ? [] : nested(tokens.slice(flag + 1));
}

/** `wsl [-d distro] [-u user] [-e|--exec|--] cmd ...` -> `cmd ...`. */
function afterWsl(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) {
    const t = tokens[i];
    if (t === '-e' || t === '--exec' || t === '--') { i += 1; break; }
    i += WSL_VALUE_OPTS.has(t) ? 2 : 1;
  }
  return tokens.slice(i);
}

/** `ssh [opts] host cmd ...` -> `cmd ...` (ssh itself joins the words with spaces). */
function afterSsh(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) i += SSH_VALUE_OPTS.has(tokens[i]) ? 2 : 1;
  return tokens.slice(i + 1);
}

// Package launchers that run the command after their options: `npx cmd`, `npm exec -- cmd`, `pnpm dlx cmd`, `npm exec -c "..."`.
const PACKAGE_RUNNERS = new Set(['npx', 'pnpx', 'bunx']);
const PACKAGE_MANAGERS = new Set(['npm', 'pnpm', 'yarn', 'bun']);
const LAUNCH_VERBS = new Set(['exec', 'x', 'dlx']);
const LAUNCH_VALUE_OPTS = new Set(['-p', '--package', '-w', '--workspace', '--prefix', '-C', '--dir', '--filter', '-F',
  '--registry', '--cache', '--userconfig', '--globalconfig', '--node-options', '--cwd']);

/** The command a package launcher runs, as tokens (`-c`/`--call` gives its one string), or null when `cmd` launches nothing. */
function afterLauncher(cmd) {
  const name = baseName(cmd[0]);
  let i = 1;
  if (!PACKAGE_RUNNERS.has(name)) {
    if (!PACKAGE_MANAGERS.has(name)) return null;
    // Global options (`pnpm -r`, `--filter web`, `npm -w a`, `yarn workspace a`) come before the verb.
    while (i < cmd.length && (cmd[i].startsWith('-') || (name === 'yarn' && cmd[i] === 'workspace'))) {
      i += LAUNCH_VALUE_OPTS.has(cmd[i]) || cmd[i] === 'workspace' ? 2 : 1;
    }
    if (!LAUNCH_VERBS.has(String(cmd[i]).toLowerCase())) return null;
    i += 1;
  }
  for (; i < cmd.length; i += 1) {
    const call = /^(?:-c|--call)(?:=([\s\S]*))?$/.exec(cmd[i]);
    if (call) return call[1] !== undefined ? [call[1]] : cmd.slice(i + 1, i + 2);
    if (cmd[i] === '--') return cmd.slice(i + 1);
    if (!cmd[i].startsWith('-')) return cmd.slice(i);
    if (LAUNCH_VALUE_OPTS.has(cmd[i])) i += 1;
  }
  return [];
}

/** The commands one command runs on behalf of its wrapper: `bash -c "..."`, `docker exec c sh -c "..."`, `ssh h "..."`, `npx sh -c "..."`. */
function innerOf(cmd) {
  const name = baseName(cmd[0]);
  if (name === 'wsl') return nested(afterWsl(cmd));
  if (name === 'ssh') return nested(afterSsh(cmd));
  const launched = afterLauncher(cmd);
  if (launched) return nested(launched);
  if (SHELLS.has(name)) return shellInner(cmd, 1, name);
  const launch = CONTAINER_CLIS.has(name) ? cmd.findIndex((t) => /^(?:exec|run)$/i.test(t)) : -1;
  if (launch < 0) return [];
  for (let i = launch + 1; i < cmd.length; i += 1) {
    const shell = baseName(cmd[i]);
    if (SHELLS.has(shell)) return shellInner(cmd, i + 1, shell);
  }
  return [];
}

/** `innerOf` as token lists: one per chained command of a nested string. */
const innerSegments = (cmd) => innerOf(cmd).flatMap((i) => (i.tokens ? [i.tokens] : parseSegments(i.text)));

const QUOTED_HEREDOC = /^\s*cat\s+<<-?\s*'\w+'/;

/** The inside of every `$(...)`, `<(...)`, `>(...)` and backtick pair outside single quotes. */
function substitutions(text) {
  const out = [];
  let quote = null;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quote === "'") { if (c === "'") quote = null; continue; }
    if (c === "'") { quote = "'"; continue; }
    if (c === '"') { quote = quote === '"' ? null : '"'; continue; }
    if (c === '`') {
      const end = text.indexOf('`', i + 1);
      if (end > i) { out.push(text.slice(i + 1, end)); i = end; }
    } else if (text[i + 1] === '(' && (c === '$' || c === '<' || c === '>')) {
      let depth = 0;
      let j = i + 1;
      for (; j < text.length; j += 1) {
        if (text[j] === '(') depth += 1;
        else if (text[j] === ')' && (depth -= 1) === 0) break;
      }
      const inner = text.slice(i + 2, j);
      // `$(cat <<'EOF' ... EOF)` is a commit message or a file body: quoted heredoc text is data.
      if (!QUOTED_HEREDOC.test(inner)) out.push(inner);
      i += 1;
    }
  }
  return out;
}

/** True when `text` carries a substitution or a process substitution outside single quotes. */
const hasSubstitution = (text) => substitutions(text).length > 0;

const MAX_DEPTH = 4;

/**
 * Every command of a line, the nested ones included, as `{ tokens, text }`: `text` is the raw
 * command string the tokens came from (the whole line for the top level).
 */
function walk(command) {
  const out = [];
  const visitText = (text, depth) => {
    out.push({ text, tokens: null });
    for (const tokens of parseSegments(text)) visitTokens(tokens, depth);
    if (depth < MAX_DEPTH) for (const inner of substitutions(text)) visitText(inner, depth + 1);
  };
  const visitTokens = (tokens, depth) => {
    out.push({ text: null, tokens });
    const cmd = stripWrappers(tokens);
    if (depth >= MAX_DEPTH) {
      if (cmd.some((t) => POWERSHELLS.has(baseName(t))) && cmd.some(isEncodedFlag)) out.push({ text: null, tokens: null, opaque: 'A PowerShell -EncodedCommand nested deeper than the guard reads: it may hide anything.' });
      return;
    }
    if (!cmd.length) return;
    for (const inner of innerOf(cmd)) {
      if (inner.opaque) { out.push({ text: null, tokens: null, opaque: inner.opaque }); continue; }
      if (inner.tokens) { out.push({ text: inner.text, tokens: null }); visitTokens(inner.tokens, depth + 1); }
      else {
        if (inner.encoded) out.push({ text: null, tokens: null, decoded: inner.text });
        visitText(inner.text, depth + 1);
      }
    }
  };
  visitText(command, 0);
  return out;
}

// `<<` opens a heredoc unless it is `<<<`; the delimiter is the whole word, quotes off (`quoted` tells which).
const HEREDOC = /(?<!<)<<(?!<)-?\s*(?:'([^']*)'|"([^"]*)"|([^\s;|&<>()'"]+))/;
const HERE_STRING_OPEN = /@(['"])\s*$/;
const UNQUOTED_DELIMITER = /(?<!<<-?\s*)(['"])[^'"]*\1/g;

/**
 * The command without heredoc and here-string bodies for which `dropBody(bareLine, open)` is true (all of
 * them by default). The opening line stays; a body is dropped only when its closer is found, so an
 * unclosed `<<` (`$((1 << n))`) never swallows the rest. A here-string closes only on a bare `'@` line: with a command after it (`'@ | iex`) the body stays.
 */
function stripBodies(command, { dropBody = () => true, hereStrings = true, dropped = null } = {}) {
  const lines = command.split(/\r?\n/);
  const kept = [];
  for (let i = 0; i < lines.length; i += 1) {
    kept.push(lines[i]);
    const bare = lines[i].replace(UNQUOTED_DELIMITER, '""');
    const here = HEREDOC.exec(bare);
    const str = hereStrings && !here && HERE_STRING_OPEN.exec(bare);
    if (!here && !str) continue;
    const delimiter = here && (here[1] ?? here[2] ?? here[3]);
    const open = here ? { heredoc: true, delimiter, quoted: here[3] === undefined } : { heredoc: false, quote: str[1] };
    if (!dropBody(bare, open, lines[i])) continue;
    const closes = here ? (l) => l.trim() === delimiter : (l) => l.trim() === `${open.quote}@`;
    const end = lines.findIndex((l, j) => j > i && closes(l));
    if (end < 0) continue;
    if (dropped && here) dropped.push(...lines.slice(i + 1, end));
    i = here ? end : end - 1;
  }
  return kept.join('\n');
}

/** The command without heredoc and here-string bodies: the line that opens one is kept, its body dropped. */
const withoutBodies = (command) => stripBodies(command);

// Receivers that read the body as data, never as commands. Anything else (a shell, ssh, docker, a DB client,
// a wrapper such as sudo or timeout) may run it, so its body stays checked.
const DATA_RECEIVERS = new Set([
  'cat', 'tee', 'node', 'python', 'python3', 'deno', 'ruby', 'perl', 'git', 'gh',
  'set-content', 'add-content', 'out-file', 'echo', 'printf',
]);
// Interpreters whose stdin body is a script in their own language, never shell lines.
const STDIN_INTERPRETERS = new Set(['node', 'python', 'python3', 'deno', 'ruby', 'perl']);
const SIMPLE_DELIMITER = /^[A-Za-z_][\w-]*$/;
// Commands that may run a body: shells, remote and container shells, eval-likes, DB clients.
const BODY_RUNNERS = new Set([
  'bash', 'sh', 'zsh', 'dash', 'ash', 'ksh', 'fish', 'csh', 'tcsh', 'busybox', 'pwsh', 'powershell', 'cmd', 'eval', 'source', '.', 'xargs', 'su', 'wsl', 'ssh',
  'iex', 'invoke-expression', 'psql', 'sqlcmd', 'mysql', 'sqlite3', 'redis-cli', 'mongosh', 'cqlsh',
]);
const EXEC_CLIS = new Set(['docker', 'podman', 'kubectl']);
// Files a tool runs on its own, each with its tools: a Makefile recipe at `make`, a git hook (`.husky/`, `.githooks/` via core.hooksPath) at `git commit`.
const AUTORUN_PAIRS = [
  [/(?:^|[\\/])(?:GNU)?[Mm]akefile$/, ['make', 'gmake']],
  [/(?:^|[\\/])(?:\.git[\\/]hooks|\.husky|\.githooks)[\\/][^\\/]+$/, ['git']],
];
/** The tools that run a file the line wrote: `make` for a Makefile, `git` for a hook. */
const autorunTools = (targets) => new Set(AUTORUN_PAIRS.filter(([file]) => [...targets].some((t) => file.test(t))).flatMap(([, tools]) => tools));
// A PowerShell here-string with its body: `@'` or `@"` ending its line, up to the closer at a line start.
const HERE_STRING_BODY = /@(['"])[ \t]*\r?\n([\s\S]*?)\r?\n\1@/g;

// Variables that change how the shell splits words, finds folders or commands, or where it is.
const RESERVED_VARS = /^(?:IFS|CDPATH|PATH|HOME|PWD|OLDPWD|SHELLOPTS|BASHOPTS|BASH_ENV|ENV|GLOBIGNORE|PS4|PROMPT_COMMAND)$/i;
// Commands that only move, list or make a folder: they run no text and no script a body wrote. A build is not
// one: MSBuild imports Directory.Build.targets and npm runs package.json scripts a body may have just written.
const INERT_COMMANDS = new Set(['cd', 'pushd', 'set-location', 'push-location', 'sl', 'mkdir', 'md', 'ls', 'dir']);

// The only forms each shell reads as an assignment of a literal: Bash `name=value`, PowerShell `$name = 'value'`.
const BASH_ASSIGNMENT = /^([A-Za-z_]\w*)=(?:"([^"$`\\\s]*)"|'([^'\s]*)'|([^"'$`\\\s]*))$/;
const PS_ASSIGNMENT = /^\$([A-Za-z_]\w*)\s*=\s*(?:"([^"$`\s]*)"|'([^'\s]*)')$/;

/** `[name, value]` when `text` is a plain literal assignment in `shell` (`any`: either form; a PowerShell name is case-insensitive), else null. */
function parseAssignment(text, shell) {
  if (shell === 'any') return parseAssignment(text, 'bash') ?? parseAssignment(text, 'powershell');
  const m = shell === 'bash' ? BASH_ASSIGNMENT.exec(text) : shell === 'powershell' ? PS_ASSIGNMENT.exec(text) : null;
  return m ? [shell === 'powershell' ? m[1].toLowerCase() : m[1], m[2] ?? m[3] ?? m[4] ?? ''] : null;
}

/** The assignment a token list spells (`P=x`, `$P = x`: the quotes are already gone), else null. */
const tokenAssignment = (tokens) => parseAssignment(tokens.length === 3 && tokens[1] === '=' ? `${tokens[0]} = '${tokens[2]}'` : tokens.length === 1 ? tokens[0] : '', 'any');

/** True for a segment that cannot run a body or a script: a literal non-reserved assignment, `cd`, `mkdir`, `ls`. */
function isInert(tokens) {
  if (!tokens.length || tokens.some((t) => /\$\(|[<>]\(/.test(t))) return false;
  const assigned = tokenAssignment(tokens);
  if (assigned) return !RESERVED_VARS.test(assigned[0]) && !/[$`(]/.test(assigned[1]);
  const command = baseName(tokens[0]);
  return INERT_COMMANDS.has(command);
}

/** True when the command, bodies off, has a segment that may run text as commands (or a script a body wrote). */
function hasBodyRunner(command) {
  const targets = redirectTargets(command);
  const autorun = autorunTools(targets);
  return expandSegments(stripBodies(command)).some((tokens) => !isInert(tokens) && [tokens, stripWrappers(tokens)].some((cmd) => {
    const name = cmd.length ? baseName(cmd[0]).toLowerCase() : '';
    if (BODY_RUNNERS.has(name) || (EXEC_CLIS.has(name) && cmd.some((t) => /^exec$/i.test(t)))) return true;
    if (autorun.has(name)) return true;
    if (cmd === tokens && cmd.length && RESERVED_VARS.test(/^\$?([A-Za-z_]\w*)=/.exec(cmd[0])?.[1] ?? '')) return true;
    // `S=$(printf x)` split at its spaces: the rest is the substitution's own words, read as their own segment.
    if (!cmd.length || DATA_RECEIVERS.has(name) || /^[A-Za-z_]\w*=\$\([^)]*$/.test(tokens[0])) return false;
    // `./s.sh`, `"$SHELL" s.sh`, `timeout 60 bash s.sh`, `nice sh s.sh`: a path, a variable or a runner after a prefix command.
    // `watch s.sh`, `stdbuf -o0 s.sh`: a script argument after a prefix command counts too.
    // A script named without a suffix (`timeout 60 ./s`, `watch s`): a path-like argument or a written file's name counts too.
    return /[\\/$]|\.(?:sh|ps1|bat|cmd)$/i.test(cmd[0])
      || cmd.slice(1).some((t) => BODY_RUNNERS.has(baseName(t)) || /\.(?:sh|ps1|bat|cmd)$/i.test(t) || /[\\/]/.test(t) || targets.has(t));
  }));
}

/** File names a command writes to: `> s`, `>> s`, `tee s`, `tee -a s`, `Set-Content [-Path] s` (quotes and a trailing `;` dropped). */
function redirectTargets(command) {
  const names = new Set();
  const writes = />>?\s*(\S+)|\btee\s+(?:-\S+\s+)*(\S+)|\b(?:set-content|add-content|out-file)\s+(?:-(?:path|filepath|literalpath)\s+)?([^\s;|@-][^\s;|]*)/gi;
  for (const m of command.matchAll(writes)) names.add((m[1] ?? m[2] ?? m[3]).replace(/[;|&)]+$/, '').replace(/^['"]|['"]$/g, ''));
  return names;
}

/** True when a command, bodies off, runs a script or text: a shell or eval-like, a script path, or a file the line wrote. */
function runsScript(command) {
  const targets = redirectTargets(command);
  const autorun = autorunTools(targets);
  // `.` and `source` run a script only in command position: as an argument (`dotnet build .`) they are a path or a word.
  const argRunner = (t) => BODY_RUNNERS.has(t) && t !== '.' && t !== 'source';
  // The writer itself (`Set-Content s.ps1`) and node/python (owner decision: their scripts stay unread) run nothing here.
  return expandSegments(stripBodies(command.replace(HERE_STRING_BODY, "''"))).some((tokens) => [tokens, stripWrappers(tokens)].some((cmd) => cmd.length
    && (autorun.has(baseName(cmd[0]).toLowerCase())
      || (!DATA_RECEIVERS.has(baseName(cmd[0]))
        && (BODY_RUNNERS.has(baseName(cmd[0])) || /^\.{0,2}[\\/]|\.(?:sh|ps1|bat|cmd)$/i.test(cmd[0])
          || cmd.slice(1).some((t) => targets.has(t) || argRunner(t)))))));
}

/**
 * Each line of the PowerShell here-string bodies when a script runner follows: otherwise a body is one quoted token no
 * check reads. Read one at a time, a stray quote in one line cannot hide the next.
 */
function runnableBodyLines(command) {
  const heredocs = [];
  // Heredoc bodies stay in the checked text when a command may run them; read line by line too, an apostrophe in one line (`# don't`) opens a quote that hides the lines after it.
  // A body fed on its own line to node/python stays unread (owner decision), whatever else the line runs.
  const stdinScript = (bare) => {
    const names = parseSegments(bare).filter((t) => t.length).map((t) => baseName(t[0]).toLowerCase());
    return names.some((n) => STDIN_INTERPRETERS.has(n)) && !names.some((n) => BODY_RUNNERS.has(n));
  };
  if (hasBodyRunner(command)) stripBodies(command, { hereStrings: false, dropped: heredocs, dropBody: (bare) => !stdinScript(bare) });
  const hereStrings = runsScript(command) ? [...command.matchAll(HERE_STRING_BODY)].flatMap((m) => m[2].split(/\r?\n/)) : [];
  return [...heredocs, ...hereStrings].filter((line) => line.trim());
}

/** True when the heredoc body opened on `line` is plain data: quoted delimiter, only data receivers, nothing that expands or pipes on. */
function isDataBody(bare, open, line) {
  if (!open.heredoc || !open.quoted || !SIMPLE_DELIMITER.test(open.delimiter)) return false;
  if (/<\(|>\(|\$\(|`/.test(line) || /(?:\||&&|\\)\s*$/.test(line)) return false;
  return parseSegments(bare).every((tokens) => DATA_RECEIVERS.has(baseName(tokens[0]).toLowerCase()) || isInert(tokens));
}

/**
 * The command without the heredoc bodies whose receiver is data (`cat > f`, `node -`, `tee`), unless some
 * command outside the bodies may run text (`bash s.sh` after `cat > s.sh <<'EOF'`): then every body stays.
 */
function withoutDataBodies(command) {
  return hasBodyRunner(command) ? command : stripBodies(command, { dropBody: isDataBody, hereStrings: false });
}

/** Every command of a line as a token list, wrapper and substitution contents included. */
const expandSegments = (command) => walk(command).filter((e) => e.tokens).map((e) => e.tokens);

/** The line itself and every command string nested in it (`bash -c "..."`, `$(...)`, `ssh h "..."`). */
const expandTexts = (command) => walk(command).filter((e) => e.text !== null).map((e) => e.text);

/** The text of every -EncodedCommand payload of a line, decoded. */
const decodedCommands = (command) => walk(command).filter((e) => e.decoded !== undefined).map((e) => e.decoded);

/** The reasons a line hides a PowerShell -EncodedCommand the guard cannot read (see above). */
const opaqueCommands = (command) => walk(command).filter((e) => e.opaque).map((e) => e.opaque);

const HEAD_KEYWORDS = new Set(['!', 'if', 'then', 'else', 'elif', 'do', 'while', 'until', 'time']);

/** The commands one token list starts: past `(`, `{`, `!`, `then`/`do`..., `$r =`, assignments and wrappers, plus those in `{ ... }` blocks further on. */
function headsOfTokens(tokens) {
  const out = [];
  // Drop the first `n` characters of the head token (the whole token when nothing is left).
  const trimHead = (rest, n) => (n < rest[0].length ? [rest[0].slice(n), ...rest.slice(1)] : rest.slice(1));
  const visit = (list, inBlock = false) => {
    let rest = list;
    let paren = false;
    let brace = inBlock;
    for (;;) {
      const first = rest[0];
      if (first === undefined) return;
      const open = /^(?:@(?=\())?[({]+/.exec(first);
      const glued = /^\$[\w:]+\+?=/.exec(first) ?? /^\[[^\]\s]+\]/.exec(first);
      if (open) {
        paren = paren || open[0].includes('(');
        brace = brace || open[0].includes('{');
        rest = trimHead(rest, open[0].length);
      } else if (HEAD_KEYWORDS.has(first.toLowerCase())) rest = rest.slice(1);
      else if (glued) rest = trimHead(rest, glued[0].length); // `$r=sqlcmd`, `$r=(sqlcmd`, `[void](sqlcmd`
      else if (first.startsWith('$') && /^\+?=/.test(rest[1] ?? '')) rest = trimHead(rest.slice(1), /^\+?=/.exec(rest[1])[0].length);
      else break;
    }
    let cmd = stripWrappers(rest);
    const start = tokens.length - cmd.length; // the lists are always suffixes of `tokens`; the trims below only cut the tail
    if (brace && cmd.length) cmd = [...cmd.slice(0, -1), cmd[cmd.length - 1].replace(/\}+$/, '')].filter(Boolean);
    if (paren && cmd.length) {
      // The group ends at the first `)` that is not a `$(...)` of its own: what follows (`.Length`, `[0]`, `-join`) is not an argument.
      const blanked = cmd.map((t) => t.replace(/\$?\([^()]*\)/g, (m) => ' '.repeat(m.length)));
      const close = blanked.findIndex((t) => t.includes(')'));
      if (close >= 0) cmd = [...cmd.slice(0, close), cmd[close].slice(0, blanked[close].indexOf(')'))].filter(Boolean);
    }
    if (cmd.length) out.push(Object.assign(cmd, { start }));
    // A block opens after `{`, glued or not: `if($a){sqlcmd`, `1){sqlcmd`; `${var}` does not.
    // Only the first brace recurses: the tail still holds the later ones, so each is reached once (a visit per brace was 2^N).
    const i = rest.findIndex((t) => /(?<!\$)\{/.test(t));
    if (i >= 0) visit([rest[i].slice(rest[i].search(/(?<!\$)\{/) + 1), ...rest.slice(i + 1)].filter(Boolean), true);
  };
  visit(tokens);
  return out;
}

/** Every command head of a line as the token list that starts at it, nested ones included (wrappers, `$(...)`, blocks, `if`/`do`). */
const commandPositions = (command) => walk(command).filter((e) => e.tokens).flatMap((e) => headsOfTokens(e.tokens));

