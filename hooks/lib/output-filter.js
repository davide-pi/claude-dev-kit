/**
 * Output filter for noisy test and log commands: the rewrite (used by guard-shell.js) and the
 * filter itself (this same file, run as `node output-filter.js --filter <mode>`).
 *
 * A green `dotnet test` prints the restore, the build and every assembly path before the one line
 * that matters; a red one buries the three failing assertions in the same noise. All of it lands in
 * the context and is re-read on every later turn. The official cost pattern is a PreToolUse
 * rewrite: pipe the command through a filter that keeps the failures, the errors and the summary.
 *
 * What gets rewritten — a SINGLE command, nothing chained, piped or redirected, starting with:
 *
 *   dotnet test · npm test · npm run test · npx vitest      → mode `test`
 *   docker compose logs (not `-f` / `--follow`)             → mode `logs`
 *
 * Single command only, because the rewrite is returned with `permissionDecision: "allow"` (the
 * rewritten input is used only with a decision): allowing `cd x && dotnet test` would also allow
 * whatever precedes the test. These commands are in the template's allow list already, so the
 * allow grants nothing new. Opt-out: `# raw` anywhere in the command; help, version, test listing,
 * watch modes and a log follow are never rewritten (a follow would never reach the filter's end).
 *
 * The rewrite. Bash prefixes `set -o pipefail;` so the command's own exit code survives the pipe:
 *
 *   set -o pipefail; dotnet test 2>&1 | node "<this file>" --filter test
 *
 * PowerShell's pipeline status is the last command's, the filter's, so the command runs in a script
 * block that records its own `$LASTEXITCODE` first, and the line ends by exiting with it (else with the
 * filter's):
 *
 *   $global:__rc = 0; & { dotnet test 2>&1; $global:__rc = $LASTEXITCODE } | node "<this file>" --filter test; ...
 *
 * The filter passes short output through untouched. Longer output keeps every line matching a
 * failure or error marker with a few lines of context, every summary line and the last lines, and
 * says on its first line how much it dropped. In `test` mode it exits 1 when it saw a failure, a
 * second line of defence for a run whose own status was lost.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');

const RAW_OPT_OUT = /#\s*raw\b/i;
/** Any of these outside quotes makes the line more than one plain command. */
const COMPOUND = new Set(['|', '&', ';', '>', '<', '\n', '\r', '`', '(', ')', '{', '}']);
/** `-t` lists dotnet tests but filters vitest tests, and `-f` is a framework or a follow: per tool. */
const flag = (names) => new RegExp(`(?:^|\\s)(?:${names})(?=\\s|=|$)`, 'i');
const MODES = [
  { re: /^dotnet(?:\.exe)?\s+test\b/i, mode: 'test', never: flag('--help|-h|-\\?|--version|--list-tests|-t') },
  { re: /^npm(?:\.cmd)?\s+(?:run\s+)?test\b/i, mode: 'test', never: flag('--help|-h|--version|--watch|--watchAll') },
  { re: /^npx(?:\.cmd)?\s+vitest\b/i, mode: 'test', never: flag('--help|-h|--version|--watch|-w|watch|dev|--ui') },
  { re: /^docker(?:\.exe)?\s+compose\s+logs\b/i, mode: 'logs', never: flag('--help|-f|--follow') },
];

/** True when the line has a shell operator outside quotes. */
function isCompound(command) {
  let quote = null;
  for (const c of command) {
    if (quote) { if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'") quote = c;
    else if (COMPOUND.has(c)) return true;
  }
  return quote !== null;
}

/** The rewritten command line, or null when this command is left alone. */
function planFilter(command, toolName) {
  if (typeof command !== 'string') return null;
  const line = command.trim();
  if (!line || RAW_OPT_OUT.test(line) || isCompound(line)) return null;
  const match = MODES.find(({ re }) => re.test(line));
  if (!match || match.never.test(line)) return null;
  const { mode } = match;
  const self = __filename.replace(/\\/g, '/');
  const filter = `node "${self}" --filter ${mode}`;
  if (toolName !== 'PowerShell') return `set -o pipefail; ${line} 2>&1 | ${filter}`;
  return `$global:__rc = 0; & { ${line} 2>&1; $global:__rc = $LASTEXITCODE } | ${filter}; `
    + 'if ($global:__rc) { exit $global:__rc } elseif ($LASTEXITCODE) { exit $LASTEXITCODE }';
}

// ── The filter ───────────────────────────────────────────────────────────────

const PASS_THROUGH_LINES = 60;
const MAX_KEPT = 300;

const RULES = {
  test: {
    marker: /\b(?:fail(?:ed|ure|ures|ing)?|errors?|exception|assert\w*|expected|actual|timed? ?out|panic)\b|^\s*(?:FAIL|✗|×|✕|●)\s|\bat .+:line \d+/i,
    summary: /^\s*(?:Passed!|Failed!|Skipped!|Total tests|Test Run (?:Successful|Failed|Aborted)|Tests?\s*:|Test Files|Test Suites:|Duration|Build (?:succeeded|FAILED)|\d+ (?:passing|failing|pending)\b)/i,
    failed: /^\s*Failed!|Test Run (?:Failed|Aborted)|Build FAILED|\berror (?:CS|MSB|NU|NETSDK)\d+|^\s*Tests?\s*:?.*\b[1-9]\d* failed|^\s*Test Files\s.*\b[1-9]\d* failed|^\s*FAIL\s|\b[1-9]\d* failing\b|^npm (?:ERR!|error)/im,
    after: 10,
    tail: 10,
  },
  logs: {
    marker: /\b(?:error|err|fatal|panic|exception|fail(?:ed|ure)?|crit(?:ical)?|unhandled|traceback|warn(?:ing)?)\b|^\S*\s*\|?\s+at\s/i,
    summary: null,
    failed: null,
    after: 5,
    tail: 20,
  },
};

/** The filtered text and whether the run failed. */
function filterOutput(text, mode) {
  const rule = RULES[mode] ?? RULES.test;
  const failed = rule.failed ? rule.failed.test(text) : false;
  const lines = text.replace(/\r\n/g, '\n').replace(/\n$/, '').split('\n');
  if (lines.length <= PASS_THROUGH_LINES) return { text, failed };

  const keep = new Uint8Array(lines.length);
  lines.forEach((l, i) => {
    if (rule.summary?.test(l)) keep[i] = 1;
    if (rule.marker.test(l)) {
      for (let j = Math.max(0, i - 1); j <= Math.min(lines.length - 1, i + rule.after); j += 1) keep[j] = 1;
    }
  });
  for (let i = Math.max(0, lines.length - rule.tail); i < lines.length; i += 1) keep[i] = 1;

  const out = [];
  let kept = 0;
  let gap = 0;
  for (let i = 0; i < lines.length; i += 1) {
    if (!keep[i]) { gap += 1; continue; }
    if (gap) { out.push(`[… ${gap} lines omitted]`); gap = 0; }
    out.push(lines[i]);
    kept += 1;
    if (kept >= MAX_KEPT && i < lines.length - rule.tail) {
      // Too many markers to be a signal: jump to the tail, which carries the summary.
      gap = lines.length - rule.tail - i - 1;
      i = lines.length - rule.tail - 1;
    }
  }
  if (gap) out.push(`[… ${gap} lines omitted]`);
  const header = `[output-filter] ${kept} of ${lines.length} lines (failures, errors, summary); add "# raw" to the command for all of it.`;
  return { text: `${header}\n${out.join('\n')}\n`, failed };
}

if (require.main === module) {
  const mode = process.argv[process.argv.indexOf('--filter') + 1];
  let input = '';
  try {
    input = fs.readFileSync(0, 'utf8');
  } catch {
    /* nothing piped in */
  }
  const { text, failed } = filterOutput(input, mode);
  process.stdout.write(text);
  process.exitCode = failed ? 1 : 0;
}

module.exports = { planFilter, filterOutput };
