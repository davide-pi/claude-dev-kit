/**
 * The hook fire log: one JSON line per hook fire, `{ day, hook, event, decision, sub }`, appended to
 * `<cache>/hook-fires.log`. Nothing else goes in a line (no command, path, prompt or project): the log
 * only answers whether a hook earns its place. It stops by itself once it holds six distinct days, so a
 * fire on a seventh day appends nothing; `scripts/hook-fires.mjs` reads it, `--delete` ends it.
 *
 * Every hook runs on every tool call, so the cost is kept flat: the common fire (same day as the last
 * line) reads the last 256 bytes only, the whole file is read once per new day. Never throws, never
 * touches a hook's output. `CLAUDE_HOOK_FIRE_LOG=0` turns it off; so does `node --test`
 * (NODE_TEST_CONTEXT), so the suites' hook runs do not write the real log.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const { CACHE_DIR } = require('./cache');

const LOG = path.join(CACHE_DIR, 'hook-fires.log');
/** Written when a seventh day is first refused: from then on a fire costs one `existsSync`. `--delete` removes it with the log. */
const CLOSED = path.join(CACHE_DIR, 'hook-fires.closed');
const DAYS_MAX = 6;
const TAIL_BYTES = 256;
const DECISIONS = new Set(['silent', 'context', 'allow', 'ask', 'deny', 'rewrite', 'block']);
const DAY = /"day":"(\d{4}-\d{2}-\d{2})"/g;

/** Local calendar day, yyyy-MM-dd. */
function localDay() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** True when the hook payload comes from a subagent. */
function isSub(payload) {
  return Boolean(payload && typeof payload === 'object' && (payload.agent_id || payload.agent_type));
}

/** The day of the last line, from the file's tail, or null. */
function lastDay() {
  let fd;
  try {
    fd = fs.openSync(LOG, 'r');
    const { size } = fs.fstatSync(fd);
    const length = Math.min(size, TAIL_BYTES);
    const buffer = Buffer.alloc(length);
    fs.readSync(fd, buffer, 0, length, size - length);
    const days = [...buffer.toString('utf8').matchAll(DAY)];
    return days.length ? days[days.length - 1][1] : null;
  } catch {
    return null;
  } finally {
    if (fd !== undefined) fs.closeSync(fd);
  }
}

/** The distinct days the log holds (empty when it is missing or unreadable). */
function distinctDays() {
  try {
    return new Set([...fs.readFileSync(LOG, 'utf8').matchAll(DAY)].map((m) => m[1]));
  } catch {
    return new Set();
  }
}

/** Append one line for this fire, unless the log is closed. `decision`: silent | context | allow | ask | deny | rewrite | block. */
function logFire({ hook, event, decision, sub }) {
  try {
    if (process.env.CLAUDE_HOOK_FIRE_LOG === '0' || process.env.NODE_TEST_CONTEXT || !DECISIONS.has(decision)) return;
    if (fs.existsSync(CLOSED)) return;
    const day = localDay();
    if (lastDay() !== day) {
      const seen = distinctDays();
      if (seen.size >= DAYS_MAX && !seen.has(day)) {
        fs.writeFileSync(CLOSED, '');
        return;
      }
    }
    fs.mkdirSync(CACHE_DIR, { recursive: true });
    fs.appendFileSync(LOG, `${JSON.stringify({ day, hook, event, decision, sub: Boolean(sub) })}\n`);
  } catch {
    /* the log must never be what fails */
  }
}

/**
 * Arm exactly one line for this process, written when it exits: whatever `decision`, `event` and `sub`
 * of the returned record hold by then (default `silent`). A hook sets them as it learns them.
 */
function armFire(hook, event) {
  const fire = { hook, event, decision: 'silent', sub: false };
  process.on('exit', () => logFire(fire));
  return fire;
}

module.exports = { logFire, armFire, isSub, distinctDays, DAYS_MAX };
