/**
 * Check: a shell command that reads a secret-bearing file.
 *
 * The `Read(...)` deny rules in settings.json cover the Read tool; a shell reads the same file with
 * `Get-Content .env`, `cat id_rsa` or `find . -name .env -exec cat {} +`, and the allow list lets
 * `Get-Content *` through. This check closes that gap by looking at the tokens of every command
 * (shell wrappers unwrapped) whose job is to print, transform or copy a file, and DENIES when one of
 * them names a file of the secret list:
 *
 *   - a reader (`cat`, `Get-Content`, `grep`, `sed`, `awk`, `cut`, `sort`, `base64`, `jq` …);
 *   - a copy whose SOURCE is a secret (`cp .env backup/`; `cp .env.example .env` writes it, not reads);
 *   - `git show HEAD:.env`, `git log -p -- .env`, `git diff -- .env` (a `rev:` prefix is stripped);
 *   - a pipeline whose earlier stage names the file and a later one reads what it is given
 *     (`Get-ChildItem -Filter .env | Get-Content`, `ls .env | xargs cat`);
 *   - a glob that selects one (`cat .e?v`).
 *
 * `.env.example` / `.env.template` / `.env.sample` (with or without a further suffix) are
 * documentation and stay readable. A search tool's own pattern (`grep "\.pem" src`), or the program
 * of `sed` / `awk` / `jq`, is not a file: the first positional argument is skipped.
 *
 * Pure text analysis, no I/O.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const {
  expandSegments, expandTexts, splitPipelines, parseSegments, stripWrappers, baseName, SEARCHERS,
} = require('./shell-parse');

/** Cheap gate: without one of these substrings (or a glob character) no secret file is named. */
const HINT = /\.env|\.pem|\.key|\.pfx|\.p12|\.jks|id_rsa|id_ed25519|id_ecdsa|id_dsa|msal_token_cache|service_principal_entries|hosts\.yml|config\.json|\.claude\.json|\.credentials\.json|\.git-credentials|\.npmrc|\.pgpass|netrc|\.aws|\.kube|kubeconfig|secrets\.json|[?*[]/i;

/** Commands that print, search or transform the content of the files they are given. */
/** Tools whose first positional argument is a program, not a file. */
const PROGRAM_FIRST = new Set(['sed', 'awk', 'gawk', 'jq']);
const READERS = new Set([
  'get-content', 'gc', 'type', 'cat', 'bat', 'head', 'tail', 'less', 'more', 'xxd', 'od', 'strings',
  'sed', 'awk', 'gawk', 'cut', 'sort', 'uniq', 'tac', 'nl', 'base64', 'jq',
  ...SEARCHERS,
]);
/** Commands that copy their sources somewhere else. */
const COPIERS = new Set(['cp', 'copy', 'copy-item', 'cpi', 'xcopy', 'robocopy']);
/** Stages of a pipeline that open the files they are handed. */
const PIPE_READERS = new Set(['get-content', 'gc', 'type', 'cat', 'select-string', 'sls']);
const GIT_READERS = new Set(['show', 'log', 'diff', 'blame', 'annotate', 'cat-file']);
/** Git's own options that swallow the next token, so it is never the subcommand. */
const GIT_VALUE_FLAGS = new Set(['-C', '-c', '--git-dir', '--work-tree', '--namespace']);

/** Flags whose value is a search pattern, not a file. */
const PATTERN_FLAGS = /^-(?:e|pattern|regexp)$/i;
/** Flags whose value is a file. */
const FILE_FLAGS = /^-(?:path|literalpath|filepath)$/i;
/** Flags whose value is where a copy goes. */
const DEST_FLAGS = /^-(?:destination|dest)$/i;

const SAMPLE = /^\.env\.(?:example|template|sample)(?:\..*)?$/i;
const SECRET_BASENAME = [
  /^\.env(?:[.*].*)?$/i, /\.(?:pem|key|pfx|p12|jks)$/i, /^id_(?:rsa|ed25519|ecdsa|dsa)/i, /^msal_token_cache/i,
  /^service_principal_entries/i, /^\.claude\.json$/i, /^\.credentials\.json$/i, /^\.git-credentials$/i,
  /^\.npmrc$/i, /^\.pgpass$/i, /^_?\.?netrc$/i, /^kubeconfig$/i, /^secrets\.json$/i,
];
const SECRET_PATH = [
  /[\\/]gh[\\/]hosts\.yml$/i, /[\\/]\.docker[\\/]config\.json$/i, /[\\/]\.aws[\\/]credentials$/i, /[\\/]\.kube[\\/]config$/i,
];
/** Names a glob is tried against: a pattern that can select one of them counts as naming it. */
const CANONICAL = [
  '.env', '.env.local', '.env.production', 'id_rsa', 'id_ed25519', 'id_ecdsa', 'id_dsa', '.npmrc', '.pgpass',
  '.netrc', 'secrets.json', 'kubeconfig', '.git-credentials', '.credentials.json', '.claude.json',
  'server.pem', 'server.key', 'cert.pfx', 'cert.p12', 'store.jks',
];

/** A glob over a file name as a regular expression, or null when it has none or too little to be specific. */
function globToRegExp(name) {
  if (!/[*?[]/.test(name) || name.replace(/[*?[\]]/g, '').length < 3) return null;
  if (/^\*\.\w+$/.test(name)) return null; // `*.json`: an extension is not a name, and `*.pem` is a literal rule
  try {
    const body = name.replace(/[.+^${}()|\\]/g, '\\$&').replace(/\*/g, '.*').replace(/\?/g, '.');
    return new RegExp(`^${body}$`, 'i');
  } catch {
    return null;
  }
}

/** The secret-list file `token` names, else null. A glob such as `*.pem` or `.e?v` counts: it selects them. */
function secretIn(token) {
  const bare = token.replace(/^\d?<+/, '');
  const name = bare.replace(/^.*[\\/]/, '').replace(/^[^:\s]*:(?=\S)/, '');
  if (SAMPLE.test(name)) return null;
  if (SECRET_BASENAME.some((re) => re.test(name)) || SECRET_PATH.some((re) => re.test(bare))) return token;
  const glob = globToRegExp(name);
  if (glob && CANONICAL.some((c) => glob.test(c))) return token;
  return null;
}

/** The first secret among `tokens`, else null. */
function firstSecret(tokens) {
  for (const t of tokens) {
    const hit = secretIn(t);
    if (hit) return hit;
  }
  return null;
}

/** The first secret file one command reads or copies out, else null. */
function secretRead(tokens) {
  const cmd = stripWrappers(tokens);
  if (!cmd.length) return null;
  const name = baseName(cmd[0]);

  if (name === 'git') {
    let i = 1;
    while (i < cmd.length && cmd[i].startsWith('-')) i += GIT_VALUE_FLAGS.has(cmd[i]) ? 2 : 1;
    return GIT_READERS.has(cmd[i]) ? firstSecret(cmd.slice(i + 1).filter((t) => !t.startsWith('-'))) : null;
  }
  if (COPIERS.has(name)) return copiedSecret(cmd);

  const findExec = name === 'find' && cmd.some((t) => /^-(?:exec|execdir|ok|okdir)$/.test(t));
  if (!READERS.has(name) && !findExec) return null;

  const skipsFirst = SEARCHERS.has(name) || PROGRAM_FIRST.has(name);
  let patternSeen = false;
  for (let i = 1; i < cmd.length; i += 1) {
    const t = cmd[i];
    if (skipsFirst && PATTERN_FLAGS.test(t)) { patternSeen = true; i += 1; continue; }
    if (FILE_FLAGS.test(t)) { const hit = secretIn(cmd[i + 1] ?? ''); if (hit) return hit; i += 1; continue; }
    if (t.startsWith('-') && !t.includes('/') && !t.includes('\\')) continue;
    if (skipsFirst && !patternSeen) { patternSeen = true; continue; }
    const hit = secretIn(t);
    if (hit) return hit;
  }
  return null;
}

/** `cp SRC… DEST`, `Copy-Item -Path SRC -Destination DEST`: only a secret SOURCE is a read. */
function copiedSecret(cmd) {
  const sources = [];
  const positional = [];
  let hasDestFlag = false;
  for (let i = 1; i < cmd.length; i += 1) {
    const t = cmd[i];
    if (FILE_FLAGS.test(t)) { sources.push(cmd[i + 1] ?? ''); i += 1; continue; }
    if (DEST_FLAGS.test(t)) { hasDestFlag = true; i += 1; continue; }
    if (t.startsWith('-') || /^\/[a-z]$/i.test(t)) continue;
    positional.push(t);
  }
  const fromPositional = hasDestFlag || positional.length < 2 ? positional : positional.slice(0, -1);
  return firstSecret([...sources, ...fromPositional]);
}

/** A pipeline stage that opens whatever files the previous stage lists. */
function readsItsInput(tokens) {
  const cmd = stripWrappers(tokens);
  if (!cmd.length) return false;
  const name = baseName(cmd[0]);
  if (name === 'xargs') {
    const target = cmd.slice(1).find((t) => !t.startsWith('-'));
    return target !== undefined && (READERS.has(baseName(target)) || COPIERS.has(baseName(target)));
  }
  return PIPE_READERS.has(name);
}

/** `Get-ChildItem -Filter .env | Get-Content`: the earlier stage names the file, a later one reads it. */
function pipedSecret(text) {
  for (const stages of splitPipelines(text)) {
    if (stages.length < 2) continue;
    const parsed = stages.map((stage) => parseSegments(stage)[0] ?? []);
    for (let i = 1; i < parsed.length; i += 1) {
      if (!readsItsInput(parsed[i])) continue;
      for (let j = 0; j < i; j += 1) {
        const hit = firstSecret(parsed[j].slice(1));
        if (hit) return hit;
      }
    }
  }
  return null;
}

/** `{ reason }` when the command reads a secret file through the shell, else null. */
function checkSecretRead(command) {
  if (!HINT.test(command)) return null;
  let hit = null;
  for (const tokens of expandSegments(command)) {
    hit = secretRead(tokens);
    if (hit) break;
  }
  if (!hit) for (const text of expandTexts(command)) { hit = pipedSecret(text); if (hit) break; }
  if (!hit) return null;
  return {
    reason: `This reads a secret-bearing file through the shell (${hit}); the Read deny rules do not apply to `
      + 'shell reads, so the guard does. Ask the owner to pass the value another way; do not retry with another command.',
  };
}

module.exports = { checkSecretRead };
