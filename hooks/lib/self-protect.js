/**
 * Check: a shell command that writes into the user's own Claude configuration.
 *
 * `Edit` / `Write` on `~/.claude/hooks/`, `~/.claude/settings*.json` and `~/.claude/CLAUDE.md` have
 * their own permission rules, but a shell reaches the same files with `>`, `tee`, `Set-Content`,
 * `sed -i`, `cp` ... and the allow list cannot tell. An agent that rewrites its own hooks or
 * permissions has switched its guards off, so the write asks.
 *
 * It ASKS, never denies: the owner edits these files too, through the shell.
 *
 * Paths are resolved first: `~`, `$HOME`, `${HOME}`, `$env:USERPROFILE`, `%USERPROFILE%`, `$CLAUDE_CONFIG_DIR`,
 * a path relative to the cwd, the msys `/c/Users/<me>/.claude`, an 8.3 short name and a junction (through
 * `fs.realpathSync.native`) all name the same place. `CLAUDE_CONFIG_DIR`, when set, is protected like `~/.claude`.
 *
 * An inline `cd` (`cd`, `Set-Location`, `pushd`, `chdir`) moves the cwd the later commands are read from, but only when
 * it surely ran: alone in its `;` / `&&` chain, to an existing directory, outside a subshell. Any doubt (a pipe, `&`,
 * `||`, a subshell, `popd`, `cd -`, `..`, a missing directory) checks every cwd seen so far; an unresolved target adds
 * the protected roots. A cd nested in `bash -c "..."` is not adopted.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { expandSegments, parseSegments, stripWrappers, baseName } = require('./shell-parse');

/** Commands that write every file they are given. */
const WRITERS = new Set(['tee', 'set-content', 'sc', 'add-content', 'ac', 'out-file', 'clear-content', 'new-item', 'ni']);
/** Commands that move or rename: the SOURCE is changed too, so any path they name counts. */
const MOVERS = new Set(['mv', 'move', 'move-item', 'mi', 'rename-item', 'rni', 'ren']);
/** Commands whose last positional argument (or `-Destination`) is where they write. */
const COPIERS = new Set(['cp', 'copy', 'copy-item', 'cpi', 'install', 'ln', ...MOVERS]);
/** Commands that delete every path they are given. */
const DELETERS = new Set(['rm', 'del', 'erase', 'rd', 'rmdir', 'ri', 'remove-item']);
/** A .NET `[IO.File]::Method(` call that writes, deletes, moves or copies. */
const DOTNET_WRITE = /\]::(?:write|append|delete|move|copy|replace|create|open)\w*\(/i;
const PATH_FLAGS = /^-(?:path|literalpath|filepath)$/i;
const DEST_FLAGS = /^-(?:destination|dest|value)$/i;
const REDIRECT = /^(?:\d|\*|&)?>>?(.*)$/;

const norm = (p) => p.replace(/\\/g, '/').replace(/\/+$/, '').toLowerCase();

/** `~`, `$HOME`, `$env:USERPROFILE`, `%USERPROFILE%`, `$CLAUDE_CONFIG_DIR` at the start of a token, as their real value. */
function expandHome(token) {
  const home = os.homedir();
  const config = process.env.CLAUDE_CONFIG_DIR;
  let out = token
    .replace(/^["']|["']$/g, '')
    .replace(/^(?:~|\$\{?HOME\}?|\$env:(?:USERPROFILE|HOME)|%USERPROFILE%|%HOME%)(?=$|[\\/])/i, () => home);
  if (config) out = out.replace(/^(?:\$\{?CLAUDE_CONFIG_DIR\}?|\$env:CLAUDE_CONFIG_DIR|%CLAUDE_CONFIG_DIR%)(?=$|[\\/])/i, () => config);
  // Git Bash's drive form: `/c/x` is drive C, `x`.
  return process.platform === 'win32' ? out.replace(/^\/([a-z])(?=\/|$)/i, (_, drive) => `${drive.toUpperCase()}:`) : out;
}

/** The path with its longest existing prefix resolved by the file system: 8.3 names, junctions and symlinks expanded. */
function canonical(full) {
  const tail = [];
  for (let head = full; ;) {
    try { return path.join(fs.realpathSync.native(head), ...tail); } catch { /* not there yet: try the parent */ }
    const parent = path.dirname(head);
    if (parent === head) return full;
    tail.unshift(path.basename(head));
    head = parent;
  }
}

/** The protected configuration roots, as they are written and canonical. */
function protectedRoots() {
  const roots = [path.join(os.homedir(), '.claude')];
  if (process.env.CLAUDE_CONFIG_DIR) roots.push(path.resolve(process.env.CLAUDE_CONFIG_DIR));
  return roots;
}

/** Whether the absolute `full` is a protected file (or, `withRoot`, a protected root itself). */
function underRoot(full, withRoot) {
  return protectedRoots().some((written) => [norm(written), norm(canonical(written))].some((root) => {
    if (withRoot && full === root) return true; // moving or deleting the directory takes every file in it
    if (full === `${root}/hooks` || full.startsWith(`${root}/hooks/`)) return true;
    if (full === `${root}/claude.md`) return true;
    const rel = full.startsWith(`${root}/`) ? full.slice(root.length + 1) : null;
    return rel !== null && /^settings[^/]*\.json$/.test(rel);
  }));
}

/** True when `token`, resolved against `cwd`, is a file the user's Claude configuration lives in. */
function isProtected(token, cwd, withRoot = false) {
  if (!token || /^-/.test(token)) return false;
  const expanded = expandHome(token);
  if (/[$%]/.test(expanded)) return false; // an unresolved variable cannot be placed
  const full = path.resolve(cwd || process.cwd(), expanded);
  return underRoot(norm(full), withRoot) || underRoot(norm(canonical(full)), withRoot);
}

/** The write target of one command that names it, else null. */
function writeTarget(tokens, cwd) {
  const cmd = stripWrappers(tokens);

  // A redirection works on any command, so it is read before the command name.
  for (let i = 0; i < tokens.length; i += 1) {
    const m = REDIRECT.exec(tokens[i]);
    if (!m) continue;
    const target = m[1] || tokens[i + 1] || '';
    if (isProtected(target.replace(/^&/, ''), cwd)) return target;
  }

  const dotnet = cmd.findIndex((t) => DOTNET_WRITE.test(t));
  if (dotnet >= 0) {
    // `[IO.File]::Copy('a', 'b')` is split at its spaces: every comma- or paren-separated piece after the call is an argument.
    const pieces = cmd.slice(dotnet).flatMap((t) => t.split(/[(,]/)).map((t) => t.replace(/[)'"]+$|^['"]+/g, ''));
    const hit = pieces.find((p) => isProtected(p, cwd));
    if (hit) return hit;
  }

  if (!cmd.length) return null;
  const name = baseName(cmd[0]);
  const args = cmd.slice(1);

  if (DELETERS.has(name)) {
    for (let i = 0; i < args.length; i += 1) {
      if (PATH_FLAGS.test(args[i])) { if (isProtected(args[i + 1], cwd, true)) return args[i + 1]; i += 1; continue; }
      if (isProtected(args[i], cwd, true)) return args[i];
    }
    return null;
  }

  if (WRITERS.has(name)) {
    for (let i = 0; i < args.length; i += 1) {
      if (PATH_FLAGS.test(args[i])) { if (isProtected(args[i + 1], cwd)) return args[i + 1]; i += 1; continue; }
      if (isProtected(args[i], cwd)) return args[i];
    }
    return null;
  }

  if (name === 'sed' && args.some((a) => /^-[A-Za-z]*i|^--in-place/.test(a))) {
    return args.find((a) => isProtected(a, cwd)) ?? null;
  }

  if (COPIERS.has(name)) {
    const positional = [];
    for (let i = 0; i < args.length; i += 1) {
      if (DEST_FLAGS.test(args[i])) { if (isProtected(args[i + 1], cwd)) return args[i + 1]; i += 1; continue; }
      if (PATH_FLAGS.test(args[i])) {
        if (MOVERS.has(name) && isProtected(args[i + 1], cwd, true)) return args[i + 1];
        i += 1;
        continue;
      }
      if (!args[i].startsWith('-')) positional.push(args[i]);
    }
    if (MOVERS.has(name)) { const source = positional.find((p) => isProtected(p, cwd, true)); if (source) return source; }
    const last = positional.at(-1);
    return positional.length >= 1 && isProtected(last, cwd) ? last : null;
  }
  return null;
}

const CD = new Set(['cd', 'chdir', 'set-location', 'sl', 'pushd', 'push-location']);
const POP = new Set(['popd', 'pop-location']);
/** The separators around a cd that let it hold for the next command: the cd ran, in this shell. */
const SURE = new Set(['', ';', '\n', '\r', '&&']);

/** The top-level commands of a line as `{ text, before, after }`, the separators around each; parentheses and quotes are kept whole. */
function topLevel(command) {
  const pieces = [];
  let current = '';
  let before = '';
  let quote = null;
  let depth = 0;
  const push = (sep) => { pieces.push({ text: current, before, after: sep }); current = ''; before = sep; };
  for (let i = 0; i < command.length; i += 1) {
    const c = command[i];
    if (quote) { if (c === quote) quote = null; current += c; continue; }
    if (c === '"' || c === "'") { quote = c; current += c; continue; }
    if (c === '(') depth += 1;
    if (c === ')') depth = Math.max(0, depth - 1);
    const redirectAmp = c === '&' && (command[i + 1] === '>' || command[i - 1] === '>');
    if (depth || redirectAmp || !(c === ';' || c === '|' || c === '&' || c === '\n' || c === '\r')) { current += c; continue; }
    const sep = (c === '&' || c === '|') && command[i + 1] === c ? c + command[(i += 1)] : c;
    push(sep);
  }
  push('');
  return pieces.filter((piece) => piece.text.trim());
}

/** Where a cd goes: `{ dir }`, `{ unknown }` (an unresolved variable), `{ previous }` (`cd -`). */
function cdTarget(args, cwd, vars) {
  const positional = [];
  for (let i = 0; i < args.length; i += 1) {
    if (/^-(?:path|literalpath)$/i.test(args[i])) { positional.unshift(args[i + 1] ?? ''); i += 1; } else if (args[i] === '-') return { previous: true };
    else if (!/^-/.test(args[i]) && !/^\/d$/i.test(args[i])) positional.push(args[i]);
  }
  const raw = (positional[0] ?? '~').replace(/\$\{?([A-Za-z_]\w*)\}?/g, (m, name) => vars.get(name) ?? m);
  const expanded = expandHome(raw);
  if (/[$%]/.test(expanded)) return { unknown: true };
  return { dir: path.resolve(cwd, expanded), dotted: /(?:^|[\\/])\.\.(?:$|[\\/])/.test(expanded) };
}

const isDir = (dir) => { try { return fs.statSync(dir).isDirectory(); } catch { return false; } };

/** `NAME=value` (bash) or `$NAME = value` (PowerShell) alone on its command: the variable and its value, else null. */
function assignment(tokens) {
  const bash = tokens.length === 1 && /^([A-Za-z_]\w*)=(.*)$/.exec(tokens[0]);
  if (bash) return [bash[1], bash[2]];
  const ps = /^\$([A-Za-z_]\w*)(?:=(.*))?$/.exec(tokens[0] ?? '');
  if (ps && ps[2] !== undefined && tokens.length === 1) return [ps[1], ps[2]];
  return ps && tokens[1] === '=' && tokens.length === 3 ? [ps[1], tokens[2]] : null;
}

/** The first protected write target of `text`, read from every cwd the commands before it may have left. */
function scan(text, state) {
  for (const piece of topLevel(text)) {
    if (piece.before === '||') state.cwds = new Set([...state.seen, ...state.cwds]);
    const trimmed = piece.text.trim();
    if (/^\(.*\)$/s.test(trimmed)) {
      // A subshell's cd ends with it: what follows may run in either cwd.
      const inner = { cwds: new Set(state.cwds), seen: state.seen, vars: state.vars };
      const hit = scan(trimmed.slice(1, -1), inner);
      if (hit) return hit;
      state.cwds = new Set([...state.seen, ...state.cwds, ...inner.cwds]);
      continue;
    }
    for (const tokens of expandSegments(piece.text)) {
      for (const cwd of state.cwds) { const target = writeTarget(tokens, cwd); if (target) return target; }
    }
    const tokens = parseSegments(piece.text)[0] ?? [];
    const set = assignment(tokens);
    if (set) { state.vars.set(set[0], set[1]); continue; }
    const name = tokens.length ? baseName(tokens[0]) : '';
    if (!CD.has(name) && !POP.has(name)) continue;
    const moved = POP.has(name) ? [{ previous: true }] : [...state.cwds].map((cwd) => cdTarget(tokens.slice(1), cwd, state.vars));
    const dirs = moved.filter((m) => m.dir).map((m) => m.dir);
    const sure = SURE.has(piece.before) && SURE.has(piece.after) && piece.before !== '&&' && moved.every((m) => m.dir && !m.dotted && isDir(m.dir));
    for (const dir of dirs) state.seen.add(dir);
    if (sure) { state.cwds = new Set(dirs); continue; }
    state.cwds = new Set([...state.seen, ...state.cwds, ...dirs]);
    if (moved.some((m) => m.unknown)) for (const root of protectedRoots()) state.cwds.add(root);
  }
  return null;
}

/** The confirmation reason when the command writes into ~/.claude hooks, settings or CLAUDE.md, else null. */
function checkSelfWrite(command, cwd) {
  // No text gate: a junction (`linked/x.js`) or a cd chain reaches the configuration without naming it.
  const start = cwd || process.cwd();
  const target = scan(command, { cwds: new Set([start]), seen: new Set([start]), vars: new Map() });
  if (!target) return null;
  return `This shell command writes to ${target}, part of the Claude configuration (hooks, settings or CLAUDE.md). `
    + 'A change there switches guards and permissions off for every later session. Confirm?';
}

module.exports = { checkSelfWrite };
