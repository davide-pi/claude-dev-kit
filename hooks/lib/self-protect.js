/**
 * Check: a shell command that writes into the user's own Claude configuration.
 *
 * `Edit` / `Write` on `~/.claude/hooks/`, `~/.claude/settings*.json` and `~/.claude/CLAUDE.md` have
 * their own permission rules, but a shell reaches the same files with `>`, `tee`, `Set-Content`,
 * `sed -i`, `cp` ... and the allow list cannot tell. An agent that rewrites its own hooks or
 * permissions has switched its guards off, so the write asks.
 *
 * It ASKS, never denies: the owner edits these files too, through the shell.
 *
 * Paths are resolved first: `~`, `$HOME`, `${HOME}`, `$env:USERPROFILE`, `%USERPROFILE%`, a path
 * relative to the cwd, and the absolute `C:/Users/<me>/.claude` all name the same place. Pure text
 * analysis plus `os.homedir()`; no file system access.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const os = require('os');
const path = require('path');
const { expandSegments, stripWrappers, baseName } = require('./shell-parse');

/** Cheap gate: every protected path contains `.claude`, or `$HOME` / `~` forms that lead to it from the cwd. */
const HINT = /claude|hooks|settings|CLAUDE\.md/i;

/** Commands that write every file they are given. */
const WRITERS = new Set(['tee', 'set-content', 'sc', 'add-content', 'ac', 'out-file', 'clear-content', 'new-item', 'ni']);
/** Commands whose last positional argument (or `-Destination`) is where they write. */
const COPIERS = new Set(['cp', 'copy', 'copy-item', 'cpi', 'mv', 'move', 'move-item', 'mi', 'install', 'ln', 'rename-item']);
const PATH_FLAGS = /^-(?:path|literalpath|filepath)$/i;
const DEST_FLAGS = /^-(?:destination|dest|value)$/i;
const REDIRECT = /^(?:\d|\*|&)?>>?(.*)$/;

const norm = (p) => p.replace(/\\/g, '/').replace(/\/+$/, '').toLowerCase();

/** `~`, `$HOME`, `$env:USERPROFILE`, `%USERPROFILE%` at the start of a token, as the real home. */
function expandHome(token) {
  const home = os.homedir();
  return token
    .replace(/^["']|["']$/g, '')
    .replace(/^(?:~|\$\{?HOME\}?|\$env:(?:USERPROFILE|HOME)|%USERPROFILE%|%HOME%)(?=$|[\\/])/i, () => home);
}

/** True when `token`, resolved against `cwd`, is a file the user's Claude configuration lives in. */
function isProtected(token, cwd) {
  if (!token || /^-/.test(token)) return false;
  const expanded = expandHome(token);
  if (/[$%]/.test(expanded)) return false; // an unresolved variable cannot be placed
  const full = norm(path.resolve(cwd || process.cwd(), expanded));
  const root = `${norm(os.homedir())}/.claude`;
  if (full === `${root}/hooks` || full.startsWith(`${root}/hooks/`)) return true;
  if (full === `${root}/claude.md`) return true;
  const rel = full.startsWith(`${root}/`) ? full.slice(root.length + 1) : null;
  return rel !== null && /^settings[^/]*\.json$/.test(rel);
}

/** The write target of one command that names it, else null. */
function writeTarget(tokens, cwd) {
  const cmd = stripWrappers(tokens);

  // A redirection works on any command, so it is read before the command name.
  for (let i = 0; i < tokens.length; i += 1) {
    const m = REDIRECT.exec(tokens[i]);
    if (!m) continue;
    const target = m[1] || tokens[i + 1] || '';
    if (isProtected(target.replace(/^&/, ''), cwd)) return target;
  }

  if (!cmd.length) return null;
  const name = baseName(cmd[0]);
  const args = cmd.slice(1);

  if (WRITERS.has(name)) {
    for (let i = 0; i < args.length; i += 1) {
      if (PATH_FLAGS.test(args[i])) { if (isProtected(args[i + 1], cwd)) return args[i + 1]; i += 1; continue; }
      if (isProtected(args[i], cwd)) return args[i];
    }
    return null;
  }

  if (name === 'sed' && args.some((a) => /^-[A-Za-z]*i|^--in-place/.test(a))) {
    return args.find((a) => isProtected(a, cwd)) ?? null;
  }

  if (COPIERS.has(name)) {
    const positional = [];
    for (let i = 0; i < args.length; i += 1) {
      if (DEST_FLAGS.test(args[i])) { if (isProtected(args[i + 1], cwd)) return args[i + 1]; i += 1; continue; }
      if (PATH_FLAGS.test(args[i])) { i += 1; continue; }
      if (!args[i].startsWith('-')) positional.push(args[i]);
    }
    const last = positional.at(-1);
    return positional.length >= 1 && isProtected(last, cwd) ? last : null;
  }
  return null;
}

/** The confirmation reason when the command writes into ~/.claude hooks, settings or CLAUDE.md, else null. */
function checkSelfWrite(command, cwd) {
  if (!HINT.test(command)) return null;
  for (const tokens of expandSegments(command)) {
    const target = writeTarget(tokens, cwd);
    if (target) {
      return `This shell command writes to ${target}, part of the Claude configuration (hooks, settings or CLAUDE.md). `
        + 'A change there switches guards and permissions off for every later session. Confirm?';
    }
  }
  return null;
}

module.exports = { checkSelfWrite };
