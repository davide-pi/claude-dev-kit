/**
 * Check: an Azure DevOps write that breaks the house ALM contract.
 *
 * These rules used to be prose in CLAUDE.md and were the ones most often forgotten, because each is
 * one missing flag on a long `az` line. As a check they surface exactly when they are about to be
 * broken, and cost nothing otherwise:
 *
 *   - `az repos pr create` without `--work-items` (every PR links its parent backlog item) or
 *     without `--squash true` and `--delete-source-branch true` (squash + delete, set at creation);
 *   - `az repos pr update --status completed` without the same two flags (and at completion);
 *   - `az boards work-item create` without `--assigned-to` (every item is assigned to the user);
 *   - `az boards work-item create|update` writing `CompletedWork` outside `worklog-push.ps1`
 *     (hours are written only by /worklog, through that script);
 *   - `az devops configure --defaults` (machine-global: other sessions pick it up — pass `--org`
 *     and `--project` on each call instead).
 *
 * All of them ASK, never deny: each has a legitimate exception the user can confirm.
 *
 * Multi-line commands are re-joined first: a PR create written over several lines with `\` (bash)
 * or a backtick (PowerShell) continuation would otherwise be split at each newline by the
 * segmenter, and the flags on the later lines would vanish — a false prompt on every long create.
 *
 * Pure text analysis, no I/O; a line without `az` in it costs one regex.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const { parseSegments } = require('./segments');

/** Cheap gate: nothing below can fire without one of these. */
const HINT = /\baz(?:\.cmd|\.exe)?\s[\s\S]*\b(?:repos|boards|devops)\b/i;
const CONTINUATION = /[\\`][ \t]*\r?\n/g;
const AZ = /^(?:.*[\\/])?az(?:\.cmd|\.exe)?$/i;
const FALSY = /^(?:false|no|off|0)$/i;
const HOURS_SCRIPT = /worklog-push\.ps1/i;

/** `--name value`, `--name=value`, `--name` alone (az reads a bare boolean flag as true). */
function flagsOf(tokens) {
  const flags = new Map();
  for (let i = 0; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (!t.startsWith('-')) continue;
    const eq = t.indexOf('=');
    if (eq > 0) { flags.set(t.slice(0, eq).toLowerCase(), t.slice(eq + 1)); continue; }
    const next = tokens[i + 1];
    flags.set(t.toLowerCase(), next !== undefined && !next.startsWith('-') ? next : '');
  }
  return flags;
}

/** The az call in one segment: its command words (`repos pr create`) and its flags. */
function parseAzCall(tokens) {
  const start = tokens.findIndex((t) => AZ.test(t));
  if (start < 0) return null;
  const args = tokens.slice(start + 1);
  const firstFlag = args.findIndex((t) => t.startsWith('-'));
  const words = (firstFlag < 0 ? args : args.slice(0, firstFlag)).map((w) => w.toLowerCase());
  return { verb: words.join(' '), flags: flagsOf(args), text: tokens.join(' ') };
}

const isOn = (flags, name) => flags.has(name) && !FALSY.test(flags.get(name));
const hasValue = (flags, name) => Boolean(flags.get(name)?.trim());

function mergeFlagsMissing(flags) {
  const missing = [];
  if (!isOn(flags, '--squash')) missing.push('`--squash true`');
  if (!isOn(flags, '--delete-source-branch')) missing.push('`--delete-source-branch true`');
  return missing;
}

/** Every contract this one az call breaks, as reason lines. */
function violations({ verb, flags, text }, command) {
  const out = [];
  if (verb === 'repos pr create') {
    if (!hasValue(flags, '--work-items')) {
      out.push('The PR links no work item: add `--work-items <id>` with the parent backlog item (never a Task).');
    }
    const missing = mergeFlagsMissing(flags);
    if (missing.length) out.push(`The PR is not set to squash and delete its source branch: add ${missing.join(' and ')}.`);
  } else if (verb === 'repos pr update' && /^completed$/i.test(flags.get('--status') ?? '')) {
    const missing = mergeFlagsMissing(flags);
    if (missing.length) out.push(`Completing the PR without squash + source-branch delete: add ${missing.join(' and ')}.`);
  } else if (verb === 'boards work-item create' || verb === 'boards work-item update') {
    if (verb.endsWith('create') && !hasValue(flags, '--assigned-to')) {
      out.push('The new work item has no assignee: add `--assigned-to <user>` (the identity resolved against the org).');
    }
    if (/CompletedWork/i.test(text) && !HOURS_SCRIPT.test(command)) {
      out.push('This writes CompletedWork outside /worklog: hours are logged only through `worklog-push.ps1`.');
    }
  } else if (verb === 'devops configure' && (flags.has('--defaults') || flags.has('-d'))) {
    out.push('`az devops configure --defaults` is machine-global and leaks into other sessions: pass `--org` and `--project` on each call instead.');
  }
  return out;
}

/** The confirmation reason when the command breaks an ALM contract, else null. */
function checkAlmContract(command) {
  if (!HINT.test(command)) return null;
  const joined = command.replace(CONTINUATION, ' ');
  const reasons = [];
  for (const tokens of parseSegments(joined)) {
    const call = parseAzCall(tokens);
    if (call) reasons.push(...violations(call, joined));
  }
  return reasons.length ? `${reasons.join('\n')}\nConfirm only if this exception is intended.` : null;
}

module.exports = { checkAlmContract };
