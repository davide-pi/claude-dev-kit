/**
 * Check: an Azure DevOps write that breaks the house ALM contract.
 *
 * These rules used to be prose in CLAUDE.md and were the ones most often forgotten, because each is
 * one missing flag on a long `az` line. As a check they surface exactly when they are about to be
 * broken, and cost nothing otherwise:
 *
 *   - `az repos pr create` without `--work-items` unless `--draft true` (a PR links its parent backlog item
 *     before it leaves draft) or
 *     without `--squash true` and `--delete-source-branch true` (squash + delete, set at creation);
 *   - `az repos pr update` with any `--status` other than `active`/`abandoned`, `--auto-complete`,
 *     `--bypass-policy` (az accepts unique flag prefixes: `--stat`), and `gh pr merge`: ALWAYS, because
 *     completing a PR is the write that lands on the shared branch, and the allow list, which lets the
 *     other `pr update` forms through, cannot tell it apart by prefix. The reason adds the squash and
 *     delete-source-branch flags when they are missing too. The one exception: `gh pr merge` whose single
 *     `-R`/`--repo` is a literal github.com repo (or a variable the same line assigns it literally) listed in
 *     `env.CLAUDE_PERSONAL_REPOS` of the user-level settings.json (never project settings, never process.env),
 *     with no GH_REPO/GH_HOST in sight: a personal repo has no shared branch to protect;
 *   - `az boards work-item create` without `--assigned-to` (every item is assigned to the user);
 *   - `az boards work-item create|update` writing `CompletedWork` (logged hours);
 *   - `az devops configure --defaults` (machine-global: other sessions pick it up — pass `--org`
 *     and `--project` on each call instead).
 *
 * All of them ASK, never deny: each has a legitimate exception the user can confirm.
 *
 * A command nested in `pwsh -c "..."`, `bash -c` or `wsl` is read too (`expandSegments`).
 *
 * Multi-line commands are re-joined first: a PR create written over several lines with `\` (bash)
 * or a backtick (PowerShell) continuation would otherwise be split at each newline by the
 * segmenter, and the flags on the later lines would vanish — a false prompt on every long create.
 *
 * Text analysis; the only I/O is the user settings read for a `gh pr merge` that names a literal repo.
 * A line without `az` in it costs one regex.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const { expandSegments, splitSegments, parseSegments, parseAssignment } = require('./shell-parse');
const { readUserSettings } = require('./az-pin');

/** Cheap gates: nothing below can fire without one of these. */
const HINT = /\baz(?:\.cmd|\.exe)?\s[\s\S]*\b(?:repos|boards|devops)\b/i;
const GH_HINT = /\bgh(?:\.exe)?\s[\s\S]*\bmerge\b/i;
const CONTINUATION = /[\\`][ \t]*\r?\n/g;
const AZ = /^(?:.*[\\/])?az(?:\.cmd|\.exe)?$/i;
const GH = /^(?:.*[\\/])?gh(?:\.exe)?$/i;
const FALSY = /^(?:false|no|off|0)$/i;

/** The flags that complete a PR. az accepts any unique prefix of a long flag, so `--stat` is `--status`. */
const COMPLETION_FLAGS = ['--status', '--auto-complete', '--bypass-policy'];
const canonicalFlag = (name) => {
  if (!name.startsWith('--') || name.length < 3) return name;
  const hits = COMPLETION_FLAGS.filter((full) => full.startsWith(name));
  return hits.length === 1 ? hits[0] : name;
};

/** `--name value`, `--name=value`, `--name` alone (az reads a bare boolean flag as true). */
function flagsOf(tokens) {
  const flags = new Map();
  for (let i = 0; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (!t.startsWith('-')) continue;
    const eq = t.indexOf('=');
    if (eq > 0) { flags.set(canonicalFlag(t.slice(0, eq).toLowerCase()), t.slice(eq + 1)); continue; }
    const next = tokens[i + 1];
    flags.set(canonicalFlag(t.toLowerCase()), next !== undefined && !next.startsWith('-') ? next : '');
  }
  return flags;
}

/** The az call in one segment: its command words (`repos pr create`) and its flags. */
function parseAzCall(tokens) {
  const start = tokens.findIndex((t) => AZ.test(t));
  if (start < 0) return null;
  const args = tokens.slice(start + 1);
  const firstFlag = args.findIndex((t) => t.startsWith('-'));
  const words = (firstFlag < 0 ? args : args.slice(0, firstFlag)).map((w) => w.toLowerCase());
  return { verb: words.join(' '), flags: flagsOf(args), text: tokens.join(' ') };
}

const isOn = (flags, name) => flags.has(name) && !FALSY.test(flags.get(name));
const hasValue = (flags, name) => Boolean(flags.get(name)?.trim());
/** `--auto-complete` and `--bypass-policy` finish the PR as surely as `--status completed`. */
const completesOnItsOwn = (flags) => isOn(flags, '--auto-complete') || isOn(flags, '--bypass-policy');

function mergeFlagsMissing(flags) {
  const missing = [];
  if (!isOn(flags, '--squash')) missing.push('`--squash true`');
  if (!isOn(flags, '--delete-source-branch')) missing.push('`--delete-source-branch true`');
  return missing;
}

/** Every contract this one az call breaks, as reason lines. */
function violations({ verb, flags, text }) {
  const out = [];
  if (verb === 'repos pr create') {
    // A draft may open before its item exists (pr-create §2): the item is linked before it leaves draft.
    const draft = flags.has('--draft') && /^(?:true|yes|on|1)?$/i.test((flags.get('--draft') ?? '').trim());
    if (!hasValue(flags, '--work-items') && !draft) {
      out.push('The PR links no work item: add `--work-items <id>` with the parent backlog item (never a Task), or open it with `--draft true` and link the item before it leaves draft.');
    }
    const missing = mergeFlagsMissing(flags);
    if (missing.length) out.push(`The PR is not set to squash and delete its source branch: add ${missing.join(' and ')}.`);
    if (completesOnItsOwn(flags)) out.push('This sets the new PR to complete on its own, which lands on the shared branch.');
  } else if (verb === 'repos pr update') {
    // Only `active` and `abandoned` are literal and reversible: `completed`, an unreadable value
    // (`--status $s`) and a bare flag all ask, because the allow list cannot tell them apart.
    const status = flags.get('--status');
    const unreadable = status !== undefined && !/^(?:active|abandoned)$/i.test(status);
    if (unreadable || completesOnItsOwn(flags)) {
      const missing = mergeFlagsMissing(flags);
      out.push('This completes the PR, or sets a status the guard cannot read: either lands on the shared branch.'
        + (missing.length ? ` It also lacks ${missing.join(' and ')} (squash + source-branch delete).` : ''));
    }
  } else if (verb === 'boards work-item create' || verb === 'boards work-item update') {
    if (verb.endsWith('create') && !hasValue(flags, '--assigned-to')) {
      out.push('The new work item has no assignee: add `--assigned-to <user>` (the identity resolved against the org).');
    }
    if (/CompletedWork/i.test(text)) {
      out.push('This writes CompletedWork: logged hours on a work item.');
    }
  } else if (verb === 'devops configure' && (flags.has('--defaults') || flags.has('-d'))) {
    out.push('`az devops configure --defaults` is machine-global and leaks into other sessions: pass `--org` and `--project` on each call instead.');
  }
  return out;
}

/** `gh pr merge` in one segment: the merge itself is the shared-branch write. */
function isGhPrMerge(tokens) {
  const start = tokens.findIndex((t) => GH.test(t));
  return start >= 0 && tokens[start + 1]?.toLowerCase() === 'pr' && tokens[start + 2]?.toLowerCase() === 'merge';
}

/** The `gh pr merge` flags, split by whether they take a value: any other flag keeps the ask. */
const MERGE_VALUE_FLAGS = new Set(['-R', '--repo', '-b', '--body', '-F', '--body-file', '-t', '--subject', '--match-head-commit', '-A', '--author-email']);
const MERGE_BOOL_FLAGS = new Set(['--admin', '--auto', '-d', '--delete-branch', '--disable-auto', '-m', '--merge', '-r', '--rebase', '-s', '--squash']);
const OWNER_REPO = /^(?:github\.com\/)?([A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+)$/i;
const VARIABLE = /^\$\{?([A-Za-z_]\w*)\}?$/;
const PULL_URL = /^https:\/\/github\.com\/([A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+)\/pull\/\d+\/?$/i;
const STREAM_REDIRECT = /(?<=\s)(?:[12]?>&[12]|2>\s*(?:\/dev\/null|\$null))(?=\s|$|[|;])/gi;
// Any gh variable but GH_TOKEN (which only picks the account), a GH_/_HOST/_REPO piece of a built name,
// an environment write by API or Env: path, or an export/env whose name is not a plain literal.
const GH_TARGET_ENV = /GH_(?!TOKEN\b)|_(?:HOST|REPO)\b|SetEnvironmentVariable|(?<!\$)\bEnv:|\$env:\s*[({]|\b(?:export|env|declare|typeset|readonly)\s+(?:-\w+\s+)*[^\s=;|&]*[$`'"{]/i;

/** The tokens without stderr merged into stdout or sent to null (`2>&1`, `2>/dev/null`, `2>$null`): neither changes the target. */
function dropStreamRedirects(tokens) {
  const kept = [];
  for (let i = 0; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (/^[12]?>&[12]$/.test(t) || /^2>(?:\/dev\/null|\$null)$/i.test(t)) continue;
    if (/^[12]?>&$/.test(t) && /^[12]$/.test(tokens[i + 1] ?? '')) { i += 1; continue; }
    if (t === '2>' && /^(?:\/dev\/null|\$null)$/i.test(tokens[i + 1] ?? '')) { i += 1; continue; }
    kept.push(t);
  }
  return kept;
}

/** The one `-R`/`--repo` value of the merge, or null: no repo, two, a PR that is not a number, an unknown flag. */
function mergeRepoArg(allTokens) {
  const tokens = dropStreamRedirects(allTokens);
  const start = tokens.findIndex((t) => GH.test(t));
  const repos = [];
  const urls = [];
  for (let i = start + 3; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (!t.startsWith('-')) {
      const url = PULL_URL.exec(t); // a pull URL wins over -R in gh, so it must name the same repo
      if (url) urls.push(url[1]);
      else if (!/^\d+$/.test(t)) return null; // a branch or a variable may name another repo
      continue;
    }
    const eq = t.indexOf('=');
    const name = eq > 0 ? t.slice(0, eq) : t;
    if (eq < 0 && MERGE_BOOL_FLAGS.has(name)) continue;
    if (!MERGE_VALUE_FLAGS.has(name)) return null;
    const value = eq > 0 ? t.slice(eq + 1) : tokens[(i += 1)];
    if (value === undefined) return null;
    // an unquoted $A or glob may split into more words, `-R other/x` among them, and gh keeps the last -R
    if (name !== '-R' && name !== '--repo' && /[$`*?~{\[]/.test(value)) return null;
    if (name === '-R' || name === '--repo') repos.push(value);
  }
  if (urls.length > 1 || repos.length > 1) return null;
  if (urls.length === 0) return repos[0] ?? null;
  return repos.length === 0 || repos[0].toLowerCase() === urls[0].toLowerCase() ? urls[0] : null;
}

/**
 * The literal value of `$name` when the line, up to this merge, is only literal assignments of it, else null.
 * A pipe, a background `&`, a prefix assignment or any other use of the name before the merge would leave gh
 * an empty repo, and an empty `-R ""` falls back to the repository of the working directory. What follows the
 * merge (a pipe to a reader, a later `gh pr view`) runs after gh has read its arguments, so it is not checked.
 */
function assignedValue(name, joined, ghTokens, shell) {
  const line = joined.replace(STREAM_REDIRECT, '');
  const segments = splitSegments(line).map((s) => s.trim());
  const wanted = dropStreamRedirects(ghTokens).join('\u0000');
  const matches = segments.map((s, i) => ((parseSegments(s)[0] ?? []).join('\u0000') === wanted ? i : -1)).filter((i) => i >= 0);
  if (matches.length !== 1) return null; // the same merge text twice could read another assignment of the name
  const k = matches[0];
  let end = 0;
  for (const segment of segments.slice(0, k + 1)) end = line.indexOf(segment, end) + segment.length; // in order: an earlier quote may hold the same text
  const head = line.slice(0, end);
  if (/(?<![|&])[|&](?![|&])/.test(head.replace(/'[^']*'|"[^"]*"/g, '')) || /\|\|/.test(head)) return null;
  const key = shell === 'powershell' ? name.toLowerCase() : name;
  const values = new Set();
  for (const segment of segments.slice(0, k)) {
    const assigned = parseAssignment(segment, shell);
    if (!assigned) return null;
    if (assigned[0] === key) values.add(assigned[1]);
  }
  const uses = head.match(new RegExp(`(?<![\\w-])${name}(?!\\w)`, shell === 'powershell' ? 'gi' : 'g'))?.length ?? 0;
  const assignments = segments.slice(0, k).filter((s) => parseAssignment(s, shell)?.[0] === key).length;
  return values.size === 1 && uses === assignments + 1 ? [...values][0] : null;
}

/** True when this merge targets, beyond doubt, a repo the user-level settings list in CLAUDE_PERSONAL_REPOS. */
function isPersonalRepoMerge(tokens, joined, toolName) {
  try {
    if (GH_TARGET_ENV.test(joined) || process.env.GH_HOST) return false;
    let repo = mergeRepoArg(tokens);
    if (repo === null) return false;
    const variable = VARIABLE.exec(repo);
    if (variable) repo = assignedValue(variable[1], joined, tokens, toolName === 'PowerShell' ? 'powershell' : 'bash');
    const match = repo === null ? null : OWNER_REPO.exec(repo);
    if (!match) return false;
    const listed = readUserSettings()?.env?.CLAUDE_PERSONAL_REPOS;
    if (typeof listed !== 'string') return false;
    return listed.split(/[\s,;]+/).some((entry) => entry && entry.toLowerCase() === match[1].toLowerCase());
  } catch {
    return false; // an unreadable config or a parse failure keeps the ask
  }
}

/** The confirmation reason when the command breaks an ALM contract, else null. */
function checkAlmContract(command, toolName = undefined) {
  const az = HINT.test(command);
  if (!az && !GH_HINT.test(command)) return null;
  const joined = command.replace(CONTINUATION, ' ');
  const reasons = [];
  for (const tokens of expandSegments(joined)) {
    const call = az ? parseAzCall(tokens) : null;
    if (call) reasons.push(...violations(call));
    else if (isGhPrMerge(tokens) && !isPersonalRepoMerge(tokens, joined, toolName)) reasons.push('This merges the PR, which lands on the shared branch.');
  }
  const unique = [...new Set(reasons)]; // a nested command is also visible in its wrapper's tokens
  return unique.length ? `${unique.join('\n')}\nConfirm only if this exception is intended.` : null;
}

module.exports = { checkAlmContract, parseAzCall };
