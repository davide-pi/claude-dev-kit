/**
 * Check: a raw SQL client pointed at a host that is not a known dev host.
 *
 * Non-dev databases are read through `~/.claude/scripts/sql-ro.ps1`, which checks the login is
 * read-only before it runs anything. A bare `sqlcmd -S prod-host ...` skips that gate, so this check
 * denies it. Unlike the other guards this one does not ask: the safe route exists and is cheap.
 *
 * It fires on `sqlcmd`, `Invoke-Sqlcmd`, `bcp` and `SqlPackage` in command position — also behind
 * `docker exec`, `sudo`, `env VAR=x`, or inside `pwsh -c "..."` / `bash -c "..."` / `cmd /c`. A tool
 * *named* in an argument (`which sqlcmd`, `git add sqlcmd.ps1`) is not an invocation.
 *
 * The server is read from `-S` / `--server` (sqlcmd, bcp), `-ServerInstance` / `-ConnectionString`
 * (Invoke-Sqlcmd) and `/SourceServerName:` / `/TargetServerName:` (SqlPackage). Its host (the part
 * before `,` or `\`) must be in `devHosts` of `~/.claude/db-targets.json`. A variable or expression
 * is never a known host, so it is denied too: the guard cannot see where it points. No server at all
 * is ambiguous (SQLCMDSERVER, a default instance) and is denied, except inside `docker exec`, where
 * the default is the container itself.
 *
 * Reads the registry only once a SQL client is actually found, and never throws.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseSegments } = require('./segments');

const FALLBACK_DEV_HOSTS = ['localhost', '127.0.0.1', '(local)', '.', 'host.docker.internal'];

/** Cheap gate: without one of these substrings no tool below can be present. */
const TOOL_HINT = /sqlcmd|bcp|sqlpackage/i;

const TOOLS = new Set(['sqlcmd', 'invoke-sqlcmd', 'bcp', 'sqlpackage']);
const CONTAINER_CLIS = new Set(['docker', 'podman', 'nerdctl']);
const SHELLS = new Set(['pwsh', 'powershell', 'bash', 'sh', 'zsh', 'cmd', 'wsl']);
/** Words that put a command in command position without being the command. */
const WRAPPERS = new Set(['sudo', 'call', 'command', 'env', 'time', 'nohup', 'start', 'start-process', 'exec']);
/** Commands that name a tool in order to look at it, not to run it. */
const NOT_LAUNCHERS = new Set([
  'which', 'where', 'whereis', 'type', 'ls', 'dir', 'cat', 'stat', 'file', 'test', 'get-command',
  'gcm', 'get-help', 'man', 'help', 'get-item', 'gi', 'get-childitem', 'gci',
]);
const SHELL_FLAG = /^(?:-c|-lc|-ic|-command|\/c|\/k)$/i;
const ASSIGNMENT = /^[A-Za-z_]\w*=/;

const REASON_PREFIX = 'Raw SQL client against a non-dev or unverifiable host';
const REASON_SUFFIX = 'Read non-dev databases through ~/.claude/scripts/sql-ro.ps1.';
const deny = (host) => ({ decision: 'deny', reason: `${REASON_PREFIX} (${host}). ${REASON_SUFFIX}` });

/** `devHosts` from the registry, lowercased; the fallback when the file is missing or unusable. */
function readDevHosts() {
  try {
    const raw = fs.readFileSync(path.join(os.homedir(), '.claude', 'db-targets.json'), 'utf8');
    const hosts = JSON.parse(raw)?.devHosts;
    if (Array.isArray(hosts) && hosts.length) return hosts.map((h) => String(h).toLowerCase());
  } catch {
    // Missing or unreadable: fall through.
  }
  return FALLBACK_DEV_HOSTS;
}

/** A token as a command name: no directory, no extension, lowercase. */
function baseName(token) {
  return String(token)
    .replace(/^.*[\\/]/, '')
    .replace(/\.(?:exe|cmd|bat|ps1)$/i, '')
    .toLowerCase();
}

/** `tcp:host\inst,1433` -> `host`. */
function hostOf(server) {
  const bare = server.trim().replace(/^(?:tcp|np|lpc):/i, '');
  return bare.split(/[,\\]/)[0].trim().toLowerCase();
}

/** `Server=x;Database=y` -> `x`, or null. */
function serverFromConnectionString(text) {
  const match = text.match(/(?:^|;)\s*(?:server|data source|address|addr|network address)\s*=\s*([^;]*)/i);
  return match ? match[1] : null;
}

/** Every server a SQL client invocation names. */
function extractServers(tool, tokens) {
  const servers = [];
  const next = (i) => (i + 1 < tokens.length ? tokens[i + 1] : '');

  for (let i = 1; i < tokens.length; i += 1) {
    const t = tokens[i];
    let value = null;

    if (tool === 'sqlcmd' || tool === 'bcp') {
      if (t === '-S' || t === '--server') value = next(i);
      else if (t.startsWith('--server=')) value = t.slice('--server='.length);
      else if (t.startsWith('-S') && !t.startsWith('--')) value = t.slice(2);
    } else if (tool === 'invoke-sqlcmd') {
      const m = t.match(/^-(?:server|serverinstance)(?:[:=](.*))?$/i);
      if (m) value = m[1] !== undefined ? m[1] : next(i);
      else if (/^-connectionstring$/i.test(t)) value = serverFromConnectionString(next(i));
    } else if (tool === 'sqlpackage') {
      const m = t.match(/^[/-]{1,2}(sourceservername|targetservername|ssn|tsn)[:=](.*)$/i);
      const cs = t.match(/^[/-]{1,2}(sourceconnectionstring|targetconnectionstring|scs|tcs)[:=](.*)$/i);
      if (m) value = m[2];
      else if (cs) value = serverFromConnectionString(cs[2]);
    }

    if (value !== null && value !== undefined) servers.push(value);
  }
  return servers;
}

/** The denial for one SQL client invocation (`tokens[0]` is the tool), else null. */
function evaluate(tool, tokens, inContainer) {
  const servers = extractServers(tool, tokens).map((s) => s.trim());
  const devHosts = readDevHosts();

  // `-S` with no value counts as missing; `-S ''` likewise.
  const named = servers.filter(Boolean);
  if (!named.length) return inContainer ? null : deny('no server given');

  for (const server of named) {
    const host = hostOf(server);
    if (!devHosts.includes(host)) return deny(host || server);
  }
  return null;
}

/** Skip `sudo`, `env VAR=x`, `call`, ... until the real command. */
function stripWrappers(tokens) {
  let i = 0;
  while (i < tokens.length && (WRAPPERS.has(baseName(tokens[i])) || ASSIGNMENT.test(tokens[i]))) i += 1;
  return tokens.slice(i);
}

/** Tokens that follow a shell flag: either one quoted command string, or the command itself. */
function innerCommands(tokens, from) {
  const flag = tokens.findIndex((t, i) => i >= from && SHELL_FLAG.test(t));
  if (flag < 0) return [];
  const rest = tokens.slice(flag + 1);
  if (rest.length === 1 && /\s/.test(rest[0])) return parseSegments(rest[0]);
  return rest.length ? [rest] : [];
}

/** The denial for one chained command, else null. `depth` bounds `bash -c "bash -c ..."` chains. */
function scan(tokens, inContainer, depth) {
  if (depth > 3) return null;
  const cmd = stripWrappers(tokens);
  if (!cmd.length) return null;

  const name = baseName(cmd[0]);
  if (TOOLS.has(name)) return evaluate(name, cmd, inContainer);

  if (SHELLS.has(name)) {
    for (const inner of innerCommands(cmd, 1)) {
      const found = scan(inner, inContainer, depth + 1);
      if (found) return found;
    }
    return null;
  }

  const exec = CONTAINER_CLIS.has(name) ? cmd.findIndex((t) => t.toLowerCase() === 'exec') : -1;
  if (exec < 0) return null;

  // Inside the container the default server is the container itself.
  for (let i = exec + 1; i < cmd.length; i += 1) {
    const tool = baseName(cmd[i]);
    if (TOOLS.has(tool) && !NOT_LAUNCHERS.has(baseName(cmd[i - 1]))) {
      return evaluate(tool, cmd.slice(i), true);
    }
    if (SHELL_FLAG.test(cmd[i])) {
      for (const inner of innerCommands(cmd, i)) {
        const found = scan(inner, true, depth + 1);
        if (found) return found;
      }
      return null;
    }
  }
  return null;
}

/** `{ decision: 'deny', reason }` for a raw SQL client aimed at a non-dev host, else null. */
function checkSqlTarget(command) {
  try {
    if (typeof command !== 'string' || !TOOL_HINT.test(command)) return null;
    for (const tokens of parseSegments(command)) {
      const found = scan(tokens, false, 0);
      if (found) return found;
    }
    return null;
  } catch {
    return null;
  }
}

module.exports = { checkSqlTarget };
