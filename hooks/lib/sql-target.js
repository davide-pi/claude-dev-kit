/**
 * Check: a raw database client pointed at a host that is not a known dev host.
 *
 * Non-dev databases are read through `~/.claude/scripts/db-ro.ps1` (the `/db` skill), which proves
 * the credential is read-only server-side before it runs anything. A bare `sqlcmd -S prod-host`,
 * `psql -h prod-host` or `redis-cli -h prod-host` skips that gate, so this check denies it. Unlike
 * the other guards it does not ask: the safe route exists and is cheap.
 *
 * Clients: `sqlcmd`, `Invoke-Sqlcmd`, `bcp`, `SqlPackage`; `psql`, `pg_dump`, `pg_dumpall`,
 * `pg_restore`; `redis-cli`. Found in command position — also behind `sudo`, `env VAR=x`, inside
 * `pwsh -c "..."` / `bash -c "..."` / `cmd /c`, after `docker|podman|nerdctl [compose] run|exec`
 * and after `wsl [-d distro] [-e|--]`. A tool *named* in an argument (`which psql`,
 * `git add sqlcmd.ps1`) is not an invocation. `--version` / `--help` always pass.
 *
 * Where the host comes from:
 *
 *   - SQL Server: `-S` / `--server` (sqlcmd, bcp), `-ServerInstance` / `-ConnectionString`
 *     (Invoke-Sqlcmd), `/SourceServerName:` / `/TargetServerName:` (SqlPackage).
 *   - Postgres: `-h` / `--host`, a `postgres://` URI or a `host=` conninfo in `-d` / `--dbname` or
 *     positional, else `PGHOST=` / `PGHOSTADDR=` assigned anywhere on the line (`env`, `$env:`,
 *     `export`, `docker run -e`). `PGSERVICE`, `--env-file` or a `PGHOST` passed without a value
 *     cannot be read, so they count as unverifiable.
 *   - Redis: `-h`, a `redis://` / `rediss://` URI in `-u`, `-s` (a socket is local); none at all is
 *     redis-cli's own default, 127.0.0.1.
 *
 * A host must be in `devHosts` of `~/.claude/db-targets.json` (compose service names belong there
 * too). A variable or expression is never a known host, so it is denied: the guard cannot see
 * where it points. No host at all is ambiguous for SQL Server (SQLCMDSERVER) and Postgres (PGHOST
 * set elsewhere) and is denied, except inside `docker run|exec`, where the default is the
 * container itself.
 *
 * On a dev host `redis-cli` runs read commands only (`REDIS_READ_COMMANDS`, kept identical to the
 * list in `scripts/db-ro.ps1` — `tools/sql-target.test.mjs` pins the parity): `KEYS`, `MONITOR`,
 * `DEBUG`, `CONFIG` ask; any other command, a command read from stdin (none on the line, `-x`,
 * `--pipe`) or a script (`--eval`) is denied.
 *
 * Returns `{ decision: 'deny' | 'ask', reason }` or null. A deny anywhere on the line wins over an
 * ask. Reads the registry only once a client is actually found, and never throws.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { parseSegments } = require('./segments');

const FALLBACK_DEV_HOSTS = ['localhost', '127.0.0.1', '(local)', '.', 'host.docker.internal'];

/** Cheap gate: without one of these substrings no tool below can be present. */
const TOOL_HINT = /sqlcmd|bcp|sqlpackage|psql|pg_dump|pg_restore|redis-cli/i;

const SQLSERVER_TOOLS = new Set(['sqlcmd', 'invoke-sqlcmd', 'bcp', 'sqlpackage']);
const POSTGRES_TOOLS = new Set(['psql', 'pg_dump', 'pg_dumpall', 'pg_restore']);
const REDIS_TOOLS = new Set(['redis-cli']);
const isTool = (name) => SQLSERVER_TOOLS.has(name) || POSTGRES_TOOLS.has(name) || REDIS_TOOLS.has(name);

const CONTAINER_CLIS = new Set(['docker', 'podman', 'nerdctl']);
const SHELLS = new Set(['pwsh', 'powershell', 'bash', 'sh', 'zsh', 'cmd']);
/** Words that put a command in command position without being the command. */
const WRAPPERS = new Set(['sudo', 'call', 'command', 'env', 'time', 'nohup', 'start', 'start-process', 'exec']);
/** Wrapper options that take a value (`sudo -u postgres psql`). */
const WRAPPER_VALUE_OPTS = new Set(['-u', '-g', '-h', '-p', '-c', '-d', '--user', '--group']);
/** Commands that name a tool in order to look at it, not to run it. */
const NOT_LAUNCHERS = new Set([
  'which', 'where', 'whereis', 'type', 'ls', 'dir', 'cat', 'stat', 'file', 'test', 'get-command',
  'gcm', 'get-help', 'man', 'help', 'get-item', 'gi', 'get-childitem', 'gci',
]);
/** `docker run|exec` options whose value could look like a tool name (`--name psql`). */
const CONTAINER_VALUE_OPTS = new Set([
  '--name', '-e', '--env', '--env-file', '--network', '--net', '-w', '--workdir', '-v', '--volume',
  '-u', '--user', '-h', '--hostname', '-l', '--label', '--mount', '--platform',
]);
/** `wsl` options that take a value; `-e`, `--exec` and `--` end the options. */
const WSL_VALUE_OPTS = new Set(['-d', '--distribution', '-u', '--user', '--cd', '--shell-type', '--distribution-id']);
const SHELL_FLAG = /^(?:-c|-lc|-ic|-command|\/c|\/k)$/i;
const ASSIGNMENT = /^[A-Za-z_]\w*=/;
const INFO_FLAGS = new Set(['--version', '--help']);

/**
 * Redis commands a dev-host `redis-cli` may run, uppercase; a two-word entry names a subcommand.
 * Explicit on purpose: HGETDEL, HGETEX, GETDEL, GETEX, ZRANGESTORE and SORT look like reads and
 * write. Keep identical to `$RedisReadCommands` in scripts/db-ro.ps1.
 */
const REDIS_READ_COMMANDS = [
  'GET', 'MGET', 'GETRANGE', 'STRLEN', 'EXISTS', 'TYPE', 'TTL', 'PTTL', 'DBSIZE', 'PING', 'INFO',
  'SCAN', 'HGET', 'HMGET', 'HGETALL', 'HKEYS', 'HVALS', 'HLEN', 'HEXISTS', 'HSCAN',
  'LRANGE', 'LLEN', 'LINDEX', 'SMEMBERS', 'SCARD', 'SISMEMBER', 'SSCAN',
  'ZRANGE', 'ZRANGEBYSCORE', 'ZRANGEBYLEX', 'ZREVRANGE', 'ZREVRANGEBYSCORE', 'ZCARD', 'ZSCORE',
  'ZRANK', 'ZCOUNT', 'ZSCAN', 'XLEN', 'XRANGE', 'XREVRANGE', 'XPENDING',
  'XINFO STREAM', 'XINFO GROUPS', 'XINFO CONSUMERS', 'CLIENT LIST', 'MEMORY USAGE', 'OBJECT ENCODING',
  'SLOWLOG GET',
];
const REDIS_READ = new Set(REDIS_READ_COMMANDS);
const REDIS_SUBCOMMAND_HOSTS = new Set(REDIS_READ_COMMANDS.filter((c) => c.includes(' ')).map((c) => c.split(' ')[0]));
/** Allowed, but heavy or revealing enough that the user decides. */
const REDIS_ASK = new Set(['KEYS', 'MONITOR', 'DEBUG', 'CONFIG']);
/** redis-cli options that take a value. */
const REDIS_VALUE_OPTS = new Set([
  '-h', '-p', '-s', '-a', '-u', '-r', '-i', '-n', '-d', '-D', '-t', '--user', '--pass', '--sni',
  '--cacert', '--cacertdir', '--cert', '--key', '--tls-ciphers', '--tls-ciphersuites', '--pattern',
  '--quoted-pattern', '--count', '--memkeys-samples', '--keystats-samples', '--cursor', '--top',
  '--show-pushes', '--pipe-timeout', '--intrinsic-latency', '--lru-test',
]);
/** redis-cli modes that only read. */
const REDIS_READ_MODES = new Set([
  '--scan', '--bigkeys', '--memkeys', '--keystats', '--hotkeys', '--stat', '--latency',
  '--latency-history', '--latency-dist', '--intrinsic-latency',
]);
/** redis-cli modes that write, replay, or read the commands from somewhere the guard cannot see. */
const REDIS_OPAQUE_MODES = new Set([
  '-x', '--pipe', '--eval', '--rdb', '--functions-rdb', '--replica', '--slave', '--cluster', '--ldb',
  '--ldb-sync-mode', '--lru-test',
]);

/** psql / pg_dump / pg_restore / pg_dumpall short options that take a value. */
const PG_VALUE_SHORT = new Set('cdEfFhIjlLnNopPRStTUvZ'.split(''));
const PG_VALUE_LONG = new Set([
  '--command', '--dbname', '--file', '--host', '--log-file', '--output', '--port', '--pset',
  '--table-attr', '--username', '--set', '--variable', '--field-separator', '--record-separator',
  '--format', '--jobs', '--schema', '--exclude-schema', '--table', '--exclude-table', '--encoding',
  '--compress', '--superuser', '--index', '--function', '--trigger', '--use-list', '--role',
]);

const REASON_PREFIX = 'Raw database client against a non-dev or unverifiable host';
const REASON_SUFFIX = 'Read non-dev databases through ~/.claude/scripts/db-ro.ps1 (/db); do not retry with another client.';
const denyHost = (host) => ({ decision: 'deny', reason: `${REASON_PREFIX} (${host}). ${REASON_SUFFIX}` });

/** `devHosts` from the registry, lowercased; the fallback when the file is missing or unusable. */
function readDevHosts() {
  try {
    const raw = fs.readFileSync(path.join(os.homedir(), '.claude', 'db-targets.json'), 'utf8');
    const hosts = JSON.parse(raw)?.devHosts;
    if (Array.isArray(hosts) && hosts.length) return hosts.map((h) => String(h).toLowerCase());
  } catch {
    // Missing or unreadable: fall through.
  }
  return FALLBACK_DEV_HOSTS;
}

/** A token as a command name: no directory, no extension, lowercase. */
function baseName(token) {
  return String(token)
    .replace(/^.*[\\/]/, '')
    .replace(/\.(?:exe|cmd|bat|ps1)$/i, '')
    .toLowerCase();
}

/** `tcp:host\inst,1433` -> `host`. */
function sqlServerHost(server) {
  const bare = server.trim().replace(/^(?:tcp|np|lpc):/i, '');
  return bare.split(/[,\\]/)[0].trim().toLowerCase();
}

/** `[::1]:5432` / `db:5432` -> `::1` / `db`; a socket path -> `localhost`. */
function plainHost(host) {
  let h = decodeURIComponent(String(host).trim());
  if (!h) return '';
  if (h.startsWith('/') || h.startsWith('@')) return 'localhost';
  if (h.startsWith('[')) return h.slice(1, h.indexOf(']') > 0 ? h.indexOf(']') : undefined).toLowerCase();
  if ((h.match(/:/g) || []).length === 1) h = h.split(':')[0];
  return h.toLowerCase();
}

/** Hosts named by a `scheme://user:pw@h1:p,h2/db?host=x` URI; [] when it names none. */
function uriHosts(uri) {
  const rest = uri.replace(/^[a-z]+:\/\//i, '');
  const authority = rest.split(/[/?#]/)[0];
  const hostPart = authority.slice(authority.lastIndexOf('@') + 1);
  const hosts = hostPart ? hostPart.split(',') : [];
  const query = rest.includes('?') ? rest.slice(rest.indexOf('?') + 1) : '';
  for (const pair of query.split('&')) {
    const [key, value] = pair.split('=');
    if (/^host(?:addr)?$/i.test(key || '') && value) hosts.push(...value.split(','));
  }
  return hosts.map(plainHost).filter(Boolean);
}

/** `Server=x;Database=y` -> `x`, or null. */
function serverFromConnectionString(text) {
  const match = text.match(/(?:^|;)\s*(?:server|data source|address|addr|network address)\s*=\s*([^;]*)/i);
  return match ? match[1] : null;
}

/** Every server a SQL Server client invocation names. */
function sqlServerServers(tool, tokens) {
  const servers = [];
  const next = (i) => (i + 1 < tokens.length ? tokens[i + 1] : '');

  for (let i = 1; i < tokens.length; i += 1) {
    const t = tokens[i];
    let value = null;

    if (tool === 'sqlcmd' || tool === 'bcp') {
      if (t === '-S' || t === '--server') value = next(i);
      else if (t.startsWith('--server=')) value = t.slice('--server='.length);
      else if (t.startsWith('-S') && !t.startsWith('--')) value = t.slice(2);
    } else if (tool === 'invoke-sqlcmd') {
      const m = t.match(/^-(?:server|serverinstance)(?:[:=](.*))?$/i);
      if (m) value = m[1] !== undefined ? m[1] : next(i);
      else if (/^-connectionstring$/i.test(t)) value = serverFromConnectionString(next(i));
    } else if (tool === 'sqlpackage') {
      const m = t.match(/^[/-]{1,2}(sourceservername|targetservername|ssn|tsn)[:=](.*)$/i);
      const cs = t.match(/^[/-]{1,2}(sourceconnectionstring|targetconnectionstring|scs|tcs)[:=](.*)$/i);
      if (m) value = m[2];
      else if (cs) value = serverFromConnectionString(cs[2]);
    }

    if (value !== null && value !== undefined) servers.push(value);
  }
  return servers.map((s) => s.trim()).filter(Boolean).map(sqlServerHost);
}

/** Hosts in a Postgres connection string: a URI or a `host=x dbname=y` conninfo. */
function pgConnectionHosts(text) {
  if (/^postgres(?:ql)?:\/\//i.test(text)) return uriHosts(text);
  if (!/^\s*\w+\s*=/.test(text)) return [];
  const hosts = [];
  for (const m of text.matchAll(/(?:^|\s)(host|hostaddr|service)\s*=\s*('[^']*'|\S+)/gi)) {
    if (m[1].toLowerCase() === 'service') return null; // a service file the guard cannot read
    hosts.push(...m[2].replace(/'/g, '').split(','));
  }
  return hosts.map(plainHost).filter(Boolean);
}

/** Every host a Postgres client invocation names on its own argv; null = unverifiable. */
function pgArgHosts(tokens) {
  const hosts = [];
  const addConnection = (text) => {
    const found = pgConnectionHosts(text);
    if (found === null) return false;
    hosts.push(...found);
    return true;
  };

  for (let i = 1; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (t === '-h' || t === '--host') { hosts.push(...String(tokens[i + 1] ?? '').split(',')); i += 1; continue; }
    if (t.startsWith('--host=')) { hosts.push(...t.slice(7).split(',')); continue; }
    if (/^-h./.test(t)) { hosts.push(...t.slice(2).split(',')); continue; }
    if (t === '-d' || t === '--dbname') { if (!addConnection(String(tokens[i + 1] ?? ''))) return null; i += 1; continue; }
    if (t.startsWith('--dbname=')) { if (!addConnection(t.slice(9))) return null; continue; }
    if (t.startsWith('--')) { if (!t.includes('=') && PG_VALUE_LONG.has(t)) i += 1; continue; }
    if (t.startsWith('-') && t.length > 1) {
      // `-U` takes the next token; `-Upostgres` and flag clusters (`-At`) do not.
      if (t.length === 2 && PG_VALUE_SHORT.has(t[1])) i += 1;
      continue;
    }
    if (!addConnection(t)) return null; // positional: a dbname, which may be a URI or conninfo
  }
  return hosts.map(plainHost); // an empty `-h ''` stays, and is denied as an empty host
}

/** What `PGHOST=` / `PGHOSTADDR=` assignments on the whole line say; `unknown` when unreadable. */
function pgEnvHosts(command) {
  const hosts = [];
  for (const m of command.matchAll(/\bPGHOST(?:ADDR)?\s*=\s*(['"]?)([^'"\s;|&]*)\1/gi)) hosts.push(plainHost(m[2]));
  const unknown = /\bPGSERVICE(?:FILE)?\b/i.test(command)
    || /--env-file\b/i.test(command)
    || /\bPGHOST(?:ADDR)?\b(?!\s*=)/i.test(command);
  return { hosts, unknown };
}

/** Hosts a redis-cli invocation names; [] = redis-cli's own default (127.0.0.1). */
function redisHosts(tokens) {
  const hosts = [];
  for (let i = 1; i < tokens.length; i += 1) {
    const t = tokens[i];
    if (t === '-h') hosts.push(plainHost(tokens[i + 1] ?? ''));
    else if (t === '-u') hosts.push(...uriHosts(String(tokens[i + 1] ?? '')));
    else if (t === '-s') hosts.push('localhost');
  }
  return hosts;
}

/** The decision for a dev-host redis-cli: the command it runs must be a read. */
function redisCommand(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) {
    const t = tokens[i];
    if (REDIS_OPAQUE_MODES.has(t)) {
      return { decision: 'deny', reason: `redis-cli \`${t}\` runs commands the guard cannot read (stdin, a script, a replica stream or a cluster admin). Only explicit read commands run on a dev cache.` };
    }
    if (REDIS_READ_MODES.has(t)) return null;
    i += REDIS_VALUE_OPTS.has(t) ? 2 : 1;
  }
  if (i >= tokens.length) {
    return { decision: 'deny', reason: 'redis-cli without a command reads its commands from stdin, which the guard cannot see. Pass one read command on the line (GET, SCAN, HGETALL, TTL, INFO, ...).' };
  }

  const name = tokens[i].toUpperCase();
  const sub = REDIS_SUBCOMMAND_HOSTS.has(name) ? `${name} ${String(tokens[i + 1] ?? '').toUpperCase()}` : name;
  if (REDIS_READ.has(sub)) return null;
  if (REDIS_ASK.has(name)) {
    return {
      decision: 'ask',
      reason: `redis-cli ${name}: KEYS blocks the server while it walks the whole keyspace (prefer SCAN), `
        + 'MONITOR streams every command, CONFIG and DEBUG reach server internals. Confirm?',
    };
  }
  return {
    decision: 'deny',
    reason: `redis-cli runs read commands only (${REDIS_READ_COMMANDS.slice(0, 8).join(', ')}, ...): \`${sub}\` is not one. A write to a cache is the user's to type.`,
  };
}

/** The decision for one client invocation (`tokens[0]` is the tool), else null. */
function evaluate(tool, tokens, inContainer, command) {
  if (tokens.slice(1).some((t) => INFO_FLAGS.has(t))) return null;
  const devHosts = readDevHosts();
  const offDev = (hosts) => hosts.find((h) => !devHosts.includes(h));

  if (SQLSERVER_TOOLS.has(tool)) {
    const hosts = sqlServerServers(tool, tokens);
    if (!hosts.length) return inContainer ? null : denyHost('no server given');
    const bad = offDev(hosts);
    return bad !== undefined ? denyHost(bad || 'empty server') : null;
  }

  if (POSTGRES_TOOLS.has(tool)) {
    if (tokens.slice(1).includes('-V')) return null;
    let hosts = pgArgHosts(tokens);
    if (hosts === null) return denyHost('a service file');
    if (!hosts.length) {
      const env = pgEnvHosts(command);
      if (env.unknown && !env.hosts.length) return denyHost('PGHOST or PGSERVICE set where the guard cannot read it');
      hosts = env.hosts;
    }
    if (!hosts.length) return inContainer ? null : denyHost('no host given (-h)');
    const bad = offDev(hosts);
    return bad !== undefined ? denyHost(bad || 'empty host') : null;
  }

  // redis-cli
  if (tokens.slice(1).includes('-v')) return null;
  const hosts = redisHosts(tokens);
  const bad = offDev(hosts.length ? hosts : ['127.0.0.1']);
  if (bad !== undefined) return denyHost(bad || 'empty host');
  return redisCommand(tokens);
}

/** Skip `sudo [-u x]`, `env VAR=x`, `call`, ... until the real command. */
function stripWrappers(tokens) {
  let i = 0;
  while (i < tokens.length) {
    if (ASSIGNMENT.test(tokens[i])) { i += 1; continue; }
    if (!WRAPPERS.has(baseName(tokens[i]))) break;
    i += 1;
    while (i < tokens.length && tokens[i].startsWith('-')) i += WRAPPER_VALUE_OPTS.has(tokens[i]) ? 2 : 1;
  }
  return tokens.slice(i);
}

/** Tokens that follow a shell flag: either one quoted command string, or the command itself. */
function innerCommands(tokens, from) {
  const flag = tokens.findIndex((t, i) => i >= from && SHELL_FLAG.test(t));
  if (flag < 0) return [];
  const rest = tokens.slice(flag + 1);
  if (rest.length === 1 && /\s/.test(rest[0])) return parseSegments(rest[0]);
  return rest.length ? [rest] : [];
}

/** `wsl [-d distro] [-u user] [-e|--exec|--] cmd ...` -> `cmd ...`. */
function afterWsl(tokens) {
  let i = 1;
  while (i < tokens.length && tokens[i].startsWith('-')) {
    const t = tokens[i];
    if (t === '-e' || t === '--exec' || t === '--') { i += 1; break; }
    i += WSL_VALUE_OPTS.has(t) ? 2 : 1;
  }
  return tokens.slice(i);
}

/** The decision for one chained command, else null. `depth` bounds `bash -c "bash -c ..."` chains. */
function scan(tokens, inContainer, depth, command) {
  if (depth > 3) return null;
  const cmd = stripWrappers(tokens);
  if (!cmd.length) return null;

  const name = baseName(cmd[0]);
  if (isTool(name)) return evaluate(name, cmd, inContainer, command);

  if (name === 'wsl') return scan(afterWsl(cmd), inContainer, depth + 1, command);

  if (SHELLS.has(name)) return firstDecision(innerCommands(cmd, 1), inContainer, depth + 1, command);

  const launch = CONTAINER_CLIS.has(name) ? cmd.findIndex((t) => /^(?:exec|run)$/i.test(t)) : -1;
  if (launch < 0) return null;

  // Inside the container the default host is the container itself.
  for (let i = launch + 1; i < cmd.length; i += 1) {
    const before = cmd[i - 1];
    const tool = baseName(cmd[i]);
    if (isTool(tool) && !NOT_LAUNCHERS.has(baseName(before)) && !CONTAINER_VALUE_OPTS.has(before)) {
      return evaluate(tool, cmd.slice(i), true, command);
    }
    if (SHELL_FLAG.test(cmd[i])) return firstDecision(innerCommands(cmd, i), true, depth + 1, command);
  }
  return null;
}

/** A deny from any command wins; otherwise the first ask; otherwise null. */
function firstDecision(commands, inContainer, depth, command) {
  let ask = null;
  for (const tokens of commands) {
    const found = scan(tokens, inContainer, depth, command);
    if (found?.decision === 'deny') return found;
    if (found && !ask) ask = found;
  }
  return ask;
}

/** `{ decision: 'deny' | 'ask', reason }` for a database client the rules above stop, else null. */
function checkSqlTarget(command) {
  try {
    if (typeof command !== 'string' || !TOOL_HINT.test(command)) return null;
    return firstDecision(parseSegments(command), false, 0, command);
  } catch {
    return null;
  }
}

