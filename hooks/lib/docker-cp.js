/**
 * Check: `docker cp` writing a file onto the host outside the working directory.
 *
 * `docker cp <container>:<path> <host path>` overwrites whatever sits at the destination, and the
 * permission list allows `docker cp *` for the everyday case (a file into the project). The shapes
 * worth a confirmation are an absolute host destination outside the cwd and anything under
 * `~/.claude` (settings, hooks, skills): a container can put a file there that a later session runs.
 *
 * Copying INTO a container (`docker cp ./seed.sql db:/tmp`) writes nothing on the host and passes.
 *
 * Pure text analysis, no I/O.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const os = require('os');
const path = require('path');
const { expandSegments, baseName } = require('./shell-parse');

/** `name:/path` — a container reference. A drive letter (`C:\x`) is one letter, so it is not. */
const CONTAINER_REF = /^[\w.-]{2,}:/;
const HOME_PREFIX = /^(?:~|\$HOME|\$env:USERPROFILE|%USERPROFILE%)(?=$|[\\/])/i;

/** The host destination of one `docker cp` call, else null (not a cp, or the destination is a container). */
function hostDestination(tokens) {
  const docker = tokens.findIndex((t) => baseName(t) === 'docker');
  if (docker < 0) return null;
  const rest = tokens.slice(docker + 1);
  const cp = rest.findIndex((t) => t.toLowerCase() === 'cp');
  if (cp < 0 || rest.slice(0, cp).some((t) => !t.startsWith('-') && t.toLowerCase() !== 'container')) return null;
  const operands = rest.slice(cp + 1).filter((t) => !t.startsWith('-'));
  if (operands.length < 2) return null;
  const [source, dest] = [operands[0], operands[operands.length - 1]];
  return CONTAINER_REF.test(source) && !CONTAINER_REF.test(dest) ? dest : null;
}

/** The confirmation reason when a `docker cp` lands on the host outside `cwd`, else null. */
function checkDockerCp(command, cwd) {
  if (!/\bdocker\b[\s\S]*\bcp\b/i.test(command)) return null;
  const home = os.homedir();
  const base = cwd || process.cwd();
  for (const tokens of expandSegments(command)) {
    const dest = hostDestination(tokens);
    if (!dest) continue;
    const resolved = path.resolve(base, dest.replace(HOME_PREFIX, home));
    const rel = path.relative(base, resolved);
    const outside = rel.startsWith('..') || path.isAbsolute(rel);
    const underClaude = !path.relative(path.join(home, '.claude'), resolved).startsWith('..')
      && !path.isAbsolute(path.relative(path.join(home, '.claude'), resolved));
    if (underClaude || outside) {
      return `This copies a file out of a container to ${dest}, ${underClaude ? 'under ~/.claude' : 'outside the working directory'}, `
        + 'overwriting what is there. Confirm?';
    }
  }
  return null;
}

module.exports = { checkDockerCp };
