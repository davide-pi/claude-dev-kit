/**
 * UserPromptSubmit + PostToolUse hook: one node process for both nudges.
 *
 * `context-nudge.js` (UserPromptSubmit) and `edit-nudge.js` (PostToolUse on Write|Edit, and the
 * per-turn counter reset on UserPromptSubmit) each cost a node start at every user prompt. This entry
 * point reads the payload once, hands it to the nudges that belong to the event and prints one
 * `additionalContext` with their lines joined. The nudges keep their own logic and tests; run alone
 * (`node hooks/edit-nudge.js`) each still reads stdin and prints for itself.
 *
 * Always exits 0; any error is silence.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const path = require('path');

// Tells the nudges they are being required by this dispatcher, which calls `run` for them.
global.__nudgesDispatch = true;

const NUDGES = {
  UserPromptSubmit: ['context-nudge.js', 'edit-nudge.js'],
  PostToolUse: ['edit-nudge.js'],
};

try {
  const payload = JSON.parse(fs.readFileSync(0, 'utf8') || '{}');
  const lines = [];
  for (const name of NUDGES[payload.hook_event_name] ?? []) {
    try {
      const line = require(path.join(__dirname, name)).run(payload)?.hookSpecificOutput?.additionalContext;
      if (line) lines.push(line);
    } catch {
      /* one nudge failing never silences the other */
    }
  }
  if (lines.length) {
    process.stdout.write(JSON.stringify({
      hookSpecificOutput: { hookEventName: payload.hook_event_name, additionalContext: lines.join('\n') },
    }));
  }
} catch {
  /* silence */
}
process.exit(0);
