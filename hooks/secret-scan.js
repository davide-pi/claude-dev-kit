/**
 * PreToolUse hook for Write / Edit / MultiEdit / NotebookEdit.
 *
 * A credential that reaches a file is already halfway to the remote: the next `git add -A` takes
 * it, and once it is in the history it stays there. This hook is the last cheap moment to stop it,
 * so unlike the shell guards it does not ask — it **denies** the write and names the pattern and the
 * line, which is all the information needed to fix it.
 *
 * The catalogue is the one tools/validate.mjs already enforces on the kit's own files — provider
 * tokens, a cloud access key id, an API-key-shaped string, a password inside a connection string —
 * plus the shapes a source file can carry that a config repo cannot: a private key block, a signed
 * token, a password in a URL (`scheme://user:secret@host`) and a quoted `"password": "<literal>"` pair.
 * Keeping the two lists in step matters: what the validator rejects in the repo is exactly what must
 * never be written into a project either.
 *
 * Node, not PowerShell: this runs before every Write and Edit, so ~150ms against ~370ms just to
 * start `pwsh`. No subprocess, no file system access beyond stdin — it only reads the text the tool
 * is about to write.
 *
 * Three false positives are the ones that decide whether the hook is bearable, because each one
 * fires on perfectly correct code:
 *
 *   - a *placeholder*: `Password=<your-password>`, `Password=changeme`, `AccountKey=***`.
 *   - a *variable reference*: `Password=$env:DB_PASSWORD`, `Password=${DB_PASSWORD}`,
 *     `Password=" + password`, `Password=%DB_PASS%` — the value is a hole, not a secret. A call
 *     (`get_key(`, a cmdlet such as `Read-Host`) is one too; so is, in a test file, a value that names
 *     itself a fixture (`ValidPassword1!`).
 *   - a *detector*: the regex or the grep that hunts for secrets contains, by construction, the
 *     very shapes it looks for. A line carrying regex syntax is read as a pattern, not a value, and
 *     a scanner file (this one, the validator) is read like any other, so its detector lines
 *     stay writable and a real token in it is still reported.
 *
 * Covered in source: a quoted literal of 8+ characters assigned with `=` or `:` to a name containing
 * password, passwd, pwd, secret, api_key or token (`const password = "…"`, `ApiKey = "…"`, `token: '…'`),
 * and an unquoted YAML scalar. For these three, a value that is a plain name (letters only, with
 * camelCase, kebab or snake separators, no digit or other symbol: `authToken`, `secret-page-route`,
 * `Bearer`) is not read as a secret. Trade-off accepted: a letters-only secret such as
 * `correcthorsebattery` passes there; a digit mixed in (`Xk9fLm2pQ7vR`, `dev-local-key-8f3a91c2`) is denied.
 *
 * Deliberately NOT detected: a high-entropy string with no recognisable shape (`ApiKey = "8f3c…"`).
 * Entropy scoring on every write is a false-positive machine — minified assets, hashes, base64
 * fixtures and GUIDs all score high — and the shapes above cover the credentials that actually
 * leak. `tools/secret-scan.test.mjs` pins every pattern and every exemption above.
 *
 * Always exits 0. The deny is the deliberate block; any internal error lets the write through.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

// A failing scan asks, never approves: the ask is written by hand so it survives a broken lib.
const askRaw = (error) => {
  try { require('./lib/cache').logError('secret-scan', error); } catch { /* the log is as broken as the rest */ }
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'ask', permissionDecisionReason: 'The credential scan failed, so this write could not be checked. Confirm it yourself (details in hook-errors.log).' } }));
  process.exit(0);
};
let approve;
let deny;
let readPayload;
try {
  ({ approve, deny, readPayload } = require('./lib/decision'));
} catch (error) {
  askRaw(error);
}

/**
 * The catalogue. `value` is the capture group holding the part that has to look like a real secret;
 * where there is no group the whole match is the value.
 */
const PATTERNS = [
  {
    label: 'a provider token',
    re: /\b(?:glsa_|ghp_|github_pat_|gho_|ghs_|ghu_|xoxb-|xoxp-|xapp-)[A-Za-z0-9_-]{8,}/g,
  },
  {
    label: 'a cloud access key id',
    re: /\bAKIA[0-9A-Z]{16}\b/g,
  },
  {
    label: 'an API-key-shaped string',
    re: /\bsk-(?:ant|proj|live|test)?-?[A-Za-z0-9_-]{20,}/g,
  },
  {
    label: 'a cloud API key',
    re: /\bAIza[0-9A-Za-z_-]{35}\b/g,
  },
  {
    label: 'a private key block',
    re: /-----BEGIN\s+(?:[A-Z]+\s+)?PRIVATE KEY-----/g,
  },
  {
    label: 'a signed token',
    re: /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}/g,
  },
  {
    label: 'a password in a connection string',
    // `|` is excluded from the value on purpose: a detector reads `Password=|Pwd=`, and a real
    // password never starts with an alternation.
    re: /(?<![A-Za-z0-9])(?:password|passwd|pwd|user\s+password)\s*=\s*(?!<)([^;'"\s|,)}\]]{3,})/gi,
    value: 1,
  },
  {
    label: 'a cloud access key in a connection string',
    re: /(?<![A-Za-z0-9])(?:accountkey|sharedaccesskey|shared_access_key|aws_secret_access_key|client_secret|clientsecret|api_?key|secret_?key)\s*=\s*(?!<)([^;'"\s|,)}\]]{8,})/gi,
    value: 1,
  },
  {
    label: 'a password in a URL',
    re: /\b[a-z][a-z0-9+.-]*:\/\/[^\s:/@'"]+:([^\s@/'"]{3,})@[^\s'"]+/gi,
    value: 1,
  },
  {
    // Only a quoted literal: an unquoted value is as likely a reference or a type name as a secret.
    label: 'a quoted secret value',
    re: /["']?(?<![A-Za-z0-9])(?:password|passwd|pwd|secret|api_?key|token|client_?secret)["']?\s*:\s*["']([^"'\s]{6,})["']/gi,
    value: 1,
    plainName: true,
  },
  {
    // The assignment form of the pair above (`const password = "…"`, `ApiKey = "…"`), in any source language.
    // The name ends with the word: `dbPassword` is read, `tokenUrl` and `passwordPattern` are not.
    // A type annotation or `:=` may sit between name and value; a `…pwd` name holding a path is a folder (`OLDPWD="/usr/app"`).
    label: 'a quoted secret assigned with =',
    re: /["']?\w*?(?:password|passwd|secret|api_?key|token|pwd(?!["']?(?:\s*:\s*[\w<>[\].?]+)?\s*:?=\s*["'](?:\.?\/|~\/|[%$]|[A-Za-z]:[\\/])))["']?(?:\s*:\s*[\w<>[\].?]+)?\s*:?=\s*["']([^"'\s]{8,})["']/gi,
    value: 1,
    plainName: true,
  },
  {
    // An unquoted YAML scalar, only in a YAML file where `password: value` is the whole syntax. In code
    // the same text is as likely a type or a variable (`password: string`, `token: tokenValue`).
    label: 'an unquoted secret value in YAML',
    re: /(?<![A-Za-z0-9])(?:password|passwd|pwd|secret|api_?key|token|client_?secret)\s*:[ \t]+(?!["'!*&|>[{#])([^\s#'"]{6,})/gi,
    value: 1,
    files: /\.ya?ml$/i,
    plainName: true,
  },
  {
    label: 'a secret literal assigned to a variable',
    re: /\$\w*(?:pw|pwd|pass|passwd|password|secret|token|apikey|credential)\w*\s*=\s*["']([^"'\s]{6,})["']/gi,
    value: 1,
  },
];

/**
 * A value that is a hole rather than a secret: an interpolation, an environment lookup, a string
 * concatenation, a mask, or one of the words everybody writes when they mean "put yours here".
 */
// Only the characters that genuinely mark a hole. `(`, `)`, `!` and `+` are deliberately absent:
// they occur in real passwords, and the concatenation case (`"…Password=" + pwd`) is already
// covered because the value may not contain a quote.
// `$` is a hole only as `${`, `$(`, `$env` or a leading `$name`: a password may well contain `Pa$$w0rd`.
const INTERPOLATION = /[<>{}%`\\]|\[\[|::|\$\(|\$env\b|^\$[A-Za-z_]/i;
/** A masked provider token (`ghp_xxxxxxxxxxxx`, `AKIA` + a run of one letter): nothing real has three distinct characters. */
const TOKEN_PREFIX = /^(?:glsa_|ghp_|github_pat_|gho_|ghs_|ghu_|xoxb-|xoxp-|xapp-|sk-(?:ant|proj|live|test)?-?|AKIA|AIza)/;
const looksMasked = (value) => new Set(value.replace(TOKEN_PREFIX, '').toLowerCase()).size <= 3 || MASK.test(value.replace(TOKEN_PREFIX, ''));
/** `@Model.Password`, `config.db.password`: a member access is a reference, not a literal. */
const MEMBER_ACCESS = /^@?[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+$/;
const PLACEHOLDER_WORD = new RegExp(
  '^(?:'
  + 'changeme|change[-_]me|replace(?:[-_]?me)?|todo|tbd|fixme|'
  + 'your[-_\\w]*|my[-_\\w]*|the[-_]\\w+|'
  + 'placeholder|redacted|removed|hidden|masked|omitted|'
  + 'dummy|fake|sample|example[-_\\w]*|test|testing|foo|bar|baz|'
  + 'secret|password|passwd|pwd|pass|token|apikey|api[-_]key|key|value|string|'
  + 'null|none|nil|empty|undefined|'
  // RabbitMQ's built-in local account, documented everywhere.
  + 'guest'
  + ')$',
  'i',
);
/** `example`, `sample`, `redacted`… anywhere in the value: it is documentation, not a credential. */
const EXAMPLE_MARKER = /example|sample|placeholder|redacted|changeme|dummy|myuser|mypassword/i;
/** A test source file: `tests/…`, `__tests__/…`, `*Tests.cs`, `*.test.ts`, `*.spec.js`. */
const TEST_FILE = /(?:^|[\\/])(?:tests?|__tests__|specs?)[\\/]|(?:Tests?|[.-]test|[.-]spec)\.\w+$/i;
/** In a test file, a value that names itself a fixture (`ValidPassword1!`, `wrong-secret`) is test data. */
const fs = require('fs');
const path = require('path');
const KIT_TEST_SHAPE =/(?:^|[\\/])tools[\\/][^\\/]+\.test\.\w+$/i;
/** The kit's own checkout: a `tools/*.test.*` file whose repo also holds this scanner and the validator. Any other project's tools folder is not exempt. */
const KIT_TEST = { test: (file) => KIT_TEST_SHAPE.test(file) && fs.existsSync(path.join(path.dirname(path.dirname(path.resolve(file))), 'hooks', 'secret-scan.js'))
  && fs.existsSync(path.join(path.dirname(path.dirname(path.resolve(file))), 'tools', 'validate.mjs')) };
const FIXTURE_WORD = /valid|wrong|bad|fake|test|password|secret/i;
/** A plain name (`authToken`, `secret-page-route`, `Bearer`): letters only, camelCase/kebab/snake separators, no digit or symbol. */
const PLAIN_NAME = /^[A-Za-z]+(?:[-_][A-Za-z]+)*$/;
/** A mask: `***`, `xxxx`, `…`, `--`. */
const MASK = /^[*x.\-_•…\s]+$/i;

/**
 * `reference` is true only for the `key=value` patterns, where the value is a configuration slot
 * and a reference to it is the correct thing to write. It must NOT apply to the shape-matched
 * patterns: a signed token is three dot-separated word runs, which is exactly the shape of a
 * member access, and treating it as a reference let a real token straight through.
 */
function isPlaceholder(value, reference, inTest = false, kitTest = false) {
  const v = value.trim().replace(/^["'`]|["'`]$/g, '');
  if (!v) return true;
  if (inTest && FIXTURE_WORD.test(v)) return true;
  // The kit's own tests hold the fixtures that prove the scanner: a configuration slot there is a fixture value.
  if (kitTest && reference) return true;
  if (INTERPOLATION.test(v)) return true;
  if (MASK.test(v)) return true;
  if (PLACEHOLDER_WORD.test(v)) return true;
  if (EXAMPLE_MARKER.test(v)) return true;
  if (!reference) return looksMasked(v);
  if (MEMBER_ACCESS.test(v)) return true;
  // A URL is an endpoint, not a credential (a password inside one has its own pattern); `get_key(` is a call.
  if (/^[a-z][a-z0-9+.-]*:\/\//i.test(v) || /^@?[A-Za-z_][\w.]*\(/.test(v)) return true;
  // A PowerShell cmdlet (`Read-Host`, `Get-Secret`) is a call too.
  if (/^[A-Z][a-z]+-[A-Z][A-Za-z]+$/.test(v)) return true;
  // `env:DB_PASSWORD`, `ENV.DB_PASSWORD`, `process.env.DB_PASSWORD`, `Secrets:Db:Password`
  if (/^(?:env[.:]|process\.env|secrets?[.:]|vault[.:])/i.test(v)) return true;
  // A SCREAMING_SNAKE name is a variable, never a password anybody typed.
  if (/^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(v)) return true;
  return false;
}

/**
 * A line that carries regex or search syntax is a *detector*: the pattern that hunts for the
 * secret, not the secret. Skipping it is what keeps a scanner, a test fixture list and a
 * `git grep` recipe writable.
 */
// A `\s`-style escape counts only inside a `/…/` literal: elsewhere it is as likely a Windows path (`C:\sys\d1`).
const DETECTOR_LINE = /\(\?[:<=!]|\[A-Za-z|\[a-zA-Z|\[0-9|\[\^|\{\d+,|matchAll|RegExp|\/[^/\n]*\\[bsdw][^/\n]*\/|^\s*(?:[$>#]\s*)?(?:git\s+grep|grep|egrep|rg|Select-String|sls)\b/i;

/** The text a Write or an Edit is about to introduce — never the text it removes. */
function newText(input) {
  if (typeof input?.content === 'string') return input.content;
  if (typeof input?.new_string === 'string') return input.new_string;
  if (typeof input?.new_source === 'string') return input.new_source;
  if (Array.isArray(input?.edits)) {
    return input.edits.map((e) => (typeof e?.new_string === 'string' ? e.new_string : '')).join('\n');
  }
  return null;
}

/** Show enough to find it, never the whole credential. */
function redact(value) {
  const v = value.trim();
  return v.length <= 10 ? v : `${v.slice(0, 6)}…${v.slice(-2)} (${v.length} chars)`;
}

try {
  const payload = readPayload('secret-scan');
  const filePath = payload?.tool_input?.file_path ?? payload?.tool_input?.notebook_path ?? '';
  const text = newText(payload?.tool_input);
  if (typeof text !== 'string' || !text.trim()) approve();

  const findings = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    // A pattern definition is not a value, but a provider token on the same line is still a token.
    // A minified bundle is not hand-written config either: only the shape-matched tokens are read there.
    const skipValues = line.length > 4000 || DETECTOR_LINE.test(line);

    for (const { label, re, value, files, plainName } of PATTERNS) {
      if (skipValues && value) continue;
      if (files && !files.test(filePath)) continue;
      if (KIT_TEST.test(filePath) && label === 'a private key block') continue; // the scanner's own fixture headers
      re.lastIndex = 0;
      for (const m of line.matchAll(re)) {
        const found = value ? m[value] : m[0];
        if (plainName && PLAIN_NAME.test(found)) continue;
        if (isPlaceholder(found, value !== undefined, TEST_FILE.test(filePath), KIT_TEST.test(filePath))) continue;
        findings.push(`  line ${i + 1}: ${label} — ${redact(found)}`);
        break;                                   // one finding per pattern per line is enough
      }
    }
    if (findings.length >= 8) break;
  }

  if (!findings.length) approve();

  const where = filePath ? ` into ${filePath.replace(/^.*[\\/]/, '')}` : '';
  deny(
    `This write would introduce a credential${where}:\n${findings.join('\n')}\n\n`
    + 'Blocked before it can reach the working tree, because git history keeps whatever it is '
    + 'given. Put the value in the platform\'s secret store (user secrets, a key vault, the '
    + 'pipeline\'s secret variables) and leave a reference in the file — an environment lookup, a '
    + 'configuration key, or an explicit `<placeholder>`. If this really is a placeholder or a '
    + 'detection pattern, make it look like one and the write goes through.',
  );
} catch (error) {
  askRaw(error);
}
