/**
 * The `deliver` perimeter check: `--check` lists the changed files the active perimeter does not cover.
 *
 * `deliver` writes the perimeter of a change into one file per worktree, inside the git directory:
 * `$(git rev-parse --git-dir)/deliver/perimeter.md` (never committed; in a linked worktree that is
 * `<main>/.git/worktrees/<name>/deliver/perimeter.md`):
 *
 *   branch: feat/orders-filter
 *   status: active
 *   - src/Orders/OrdersQuery.cs
 *   - src/Orders/Dto/
 *   - tests/**\/Orders*.cs
 *
 * Entries are repo-relative: a file, a directory (trailing `/`) or a glob (`*` inside a segment, `**`
 * across segments), anchored at the repository root and matched case-insensitively (the same rule as
 * `workflows/impl-review-loop.js`, which a test holds them to). The perimeter counts only while it says
 * `status: active` AND its `branch:` is the branch checked out now; `deliver` overwrites the file at
 * each triage and sets `status: closed` at the verdict. No file, a closed or another branch's
 * perimeter or no git repository above the working directory: no active perimeter.
 *
 * CLI mode, `node hooks/scope-guard.js --check <head> [--dirty a,b]`: the mechanical scope check after a
 * review says OK. It lists, one per line, the files changed since `<head>` (`git diff --name-only <head>` plus
 * the untracked, not ignored ones) that the active perimeter does not cover, ignoring the `--dirty` files
 * (already dirty when the change started). Exit 0 when nothing is outside, 1 when something is, 2 on a usage error, a git failure or no
 * active perimeter (nothing was checked: a note on stderr). git runs through `execFileSync`, never a shell.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { repoRoot, gitDirOf, currentBranch } = require('./lib/git-dir');

const MAX_BYTES = 64 * 1024;

const slashes = (p) => p.replace(/\\/g, '/');

/** A perimeter entry as a regex over a repo-relative, slash-separated path (anchored, case-insensitive). */
function entryRegex(entry) {
  let e = slashes(entry.trim()).replace(/^\.\//, '');
  if (e.endsWith('/')) e += '**';
  const src = e.replace(/[.+^${}()|[\]]/g, '\\$&')
    .replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*').replace(/\?/g, '[^/]');
  return new RegExp(`^${src}$`, 'i');
}

/** Parses the perimeter file: its branch, whether it is active, and its entries. */
function readPerimeter(text) {
  const entries = [];
  let branch = '';
  let active = false;
  for (const raw of text.split(/\r?\n/)) {
    const l = raw.trim();
    const b = /^branch:\s*(.+)$/i.exec(l);
    if (b) branch = b[1].trim();
    else if (/^status:\s*active\s*$/i.test(l)) active = true;
    else if (l.startsWith('- ') && l.slice(2).trim()) entries.push(l.slice(2).trim());
  }
  return { active, branch, entries };
}

/** The active perimeter of the worktree at `root`: its entries and branch, or null (none, closed, another branch). */
function activePerimeter(root) {
  const dir = gitDirOf(root);
  if (!dir) return null;
  let text;
  try { text = fs.readFileSync(path.join(dir, 'deliver', 'perimeter.md'), 'utf8').slice(0, MAX_BYTES); } catch { return null; }
  const p = readPerimeter(text);
  if (!p.active || !p.entries.length || !p.branch || p.branch !== currentBranch(dir)) return null;
  return { entries: p.entries, branch: p.branch };
}

/** The files of `paths` (repo-relative) that no perimeter entry covers and that were not already `dirty`.
 *  A dirty entry ending in `/` is a collapsed untracked directory: it protects every file under it. */
function outsidePerimeter(paths, entries, dirty) {
  const norm = (p) => slashes(p.trim()).replace(/^\.\//, '');
  const skipped = dirty.map((d) => norm(d).toLowerCase());
  const skipFiles = new Set(skipped.filter((d) => !d.endsWith('/')));
  const skipDirs = skipped.filter((d) => d.endsWith('/'));
  const regexes = entries.map(entryRegex);
  const outside = [];
  const seen = new Set();
  for (const p of paths.map(norm)) {
    const lower = p.toLowerCase();
    if (!p || seen.has(p) || /^docs\/plans\//.test(lower) || /^\.git\//.test(lower) || skipFiles.has(lower) || skipDirs.some((d) => lower.startsWith(d)) || regexes.some((r) => r.test(p))) continue;
    seen.add(p);
    outside.push(p);
  }
  return outside;
}

const USAGE = 'usage: scope-guard.js --check <head> [--dirty a,b]\n';

/** `--check`: prints the changed files outside the active perimeter; returns the exit code (0 clean, 1 outside, 2 usage or git error). */
function check(args, cwd) {
  const [head, ...rest] = args;
  if (!head || head.startsWith('-') || (rest.length && (rest.length !== 2 || rest[0] !== '--dirty'))) {
    process.stderr.write(USAGE);
    return 2;
  }
  const dirty = rest.length ? rest[1].split(',').map((d) => d.trim()).filter(Boolean) : [];
  const root = repoRoot(cwd);
  if (!root) {
    process.stderr.write('scope-guard: not inside a git repository\n');
    return 2;
  }
  const perimeter = activePerimeter(root);
  if (!perimeter) {
    // Not checked is not clean: the caller must not read this as "nothing outside".
    process.stderr.write('scope-guard: no active perimeter, nothing checked\n');
    return 2;
  }
  const git = (...a) => execFileSync('git', ['-c', 'core.quotepath=false', ...a], {
    cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'],
  }).split('\0').filter(Boolean);
  let changed;
  try {
    changed = [...git('diff', '--name-only', '--no-renames', '-z', head, '--'), ...git('ls-files', '--others', '--exclude-standard', '-z')];
  } catch (error) {
    process.stderr.write(`scope-guard: git failed: ${String(error.stderr || error.message).trim()}\n`);
    return 2;
  }
  const outside = outsidePerimeter(changed, perimeter.entries, dirty);
  if (outside.length) process.stdout.write(`${outside.join('\n')}\n`);
  return outside.length ? 1 : 0;
}

module.exports = { entryRegex, readPerimeter, outsidePerimeter };

if (require.main === module && process.argv[2] === '--check') {
  process.exitCode = check(process.argv.slice(3), process.cwd());
}
