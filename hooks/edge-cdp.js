/**
 * PreToolUse hook on the browser-use tools: the fast path of `ensure-edge-cdp.ps1`, in node.
 *
 * Almost every call finds Edge's CDP port already open, and starting `pwsh` just to see that cost ~0.4-1 s
 * per browser-use call. This gate probes the port written in `<Edge User Data>/DevToolsActivePort` (and
 * the default 9222) over TCP; when one answers it exits in silence. Only when none does it runs
 * `ensure-edge-cdp.ps1`, which starts Edge or says why the port is closed, and passes its message through.
 *
 * Never blocks the tool call: always exits 0, any error is silence.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const net = require('net');
const path = require('path');
const { spawnSync } = require('child_process');

const DEFAULT_PORT = 9222;
const PROBE_TIMEOUT_MS = 500;
/** Under the hook's 30 s timeout: the script waits up to 20 s for a freshly started Edge. */
const SCRIPT_TIMEOUT_MS = 28_000;

/** The port Edge's main profile wrote, or null when the file is missing or unreadable. */
function writtenPort(userData) {
  try {
    const port = Number(fs.readFileSync(path.join(userData, 'DevToolsActivePort'), 'utf8').split(/\r?\n/)[0].trim());
    return Number.isInteger(port) && port > 0 ? port : null;
  } catch {
    return null;
  }
}

/** True when something accepts a TCP connection on 127.0.0.1:`port` within the probe timeout. */
function portOpen(port) {
  return new Promise((resolve) => {
    const socket = net.connect({ host: '127.0.0.1', port });
    const done = (open) => { socket.destroy(); resolve(open); };
    socket.setTimeout(PROBE_TIMEOUT_MS, () => done(false));
    socket.once('connect', () => done(true));
    socket.once('error', () => done(false));
  });
}

/** The slow path: the PowerShell script, its stdout (a `systemMessage` JSON, or nothing). */
function runScript() {
  const r = spawnSync('pwsh', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', path.join(__dirname, 'ensure-edge-cdp.ps1')], {
    encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true, timeout: SCRIPT_TIMEOUT_MS,
  });
  return (r.stdout || '').trim();
}

/** What the hook prints: '' when a CDP port answers, else the script's output. */
async function run({
  userData = path.join(process.env.LOCALAPPDATA || '', 'Microsoft', 'Edge', 'User Data'),
  defaultPort = DEFAULT_PORT,
  fallback = runScript,
} = {}) {
  const written = writtenPort(userData);
  if (written && await portOpen(written)) return '';
  if (written !== defaultPort && await portOpen(defaultPort)) return '';
  return fallback();
}

module.exports = { run };

if (!global.__edgeCdpLibrary) {
  run()
    .then((out) => { if (out) process.stdout.write(out); })
    .catch(() => { /* silence */ })
    .finally(() => process.exit(0));
}
