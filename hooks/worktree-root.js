/**
 * WorktreeCreate / WorktreeRemove hook: harness worktrees (`EnterWorktree`, agent
 * `isolation: "worktree"`) land under CLAUDE_WORKTREE_ROOT instead of `<repo>\.claude\worktrees\`.
 *
 * On Windows a deep repository plus `.claude\worktrees\<name>` plus `node_modules` or `obj\` runs
 * into the 260-character path limit, and a worktree nested inside the checkout shows up in globs,
 * watchers and test discovery. The house convention is one short root for every worktree,
 * `<root>\<repo>-<name>` (skill `branch-flow`, `references/worktrees.md`). With this hook the
 * native tools follow it, so the git fallback is no longer needed.
 *
 * WorktreeCreate (`name` in the payload): creates the worktree with `git worktree add` and prints
 * its absolute path — the only thing on stdout, since the harness reads the path from there.
 *   - directory: `<CLAUDE_WORKTREE_ROOT>\<repo>-<name>`; root unset → `<repo>\.claude\worktrees\<name>`,
 *     the native layout, so wiring the hook without the variable changes nothing;
 *   - branch: `worktree-<name>`, the native naming; checked out if it exists, else created at the
 *     base the `worktree.baseRef` setting names (project `settings.local.json`, then `settings.json`,
 *     then the user's): `fresh` = the default branch of `origin`, as the native layout does; anything
 *     else, or unset = the HEAD of the *session* (`git -C <cwd>`), not of the main checkout, which
 *     can be on another branch when the session runs inside a worktree. `fresh` with no `origin`
 *     falls back to the session HEAD;
 *   - an existing worktree at that path is reused, any other existing directory is an error.
 * WorktreeRemove (`worktree_path`): `git worktree remove` WITHOUT `--force`, so a dirty tree is
 * refused and kept; the branch is never deleted. Without this half the harness keeps every
 * hook-made worktree.
 *
 * Unlike the guards this hook fails loudly: a non-zero exit with the git error on stderr, because a
 * silent failure would leave the session in a worktree that does not exist.
 *
 * Generated by Claude Code at the user's request.
 */

'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

function git(cwd, args) {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8', windowsHide: true, timeout: 60000 });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')}: ${(result.stderr || result.error?.message || 'failed').trim()}`);
  }
  return result.stdout.trim();
}

/** The main checkout's root, also when `cwd` is inside a linked worktree. */
function mainRoot(cwd) {
  const common = git(cwd, ['rev-parse', '--path-format=absolute', '--git-common-dir']);
  return path.basename(common).toLowerCase() === '.git' ? path.dirname(common) : common.replace(/\.git$/i, '');
}

/** A directory- and branch-safe slug: no separators, no dot segments. */
function slug(name) {
  const s = String(name).trim().replace(/[^\w.-]+/g, '-').replace(/\.{2,}/g, '.').replace(/^[.-]+|[.-]+$/g, '');
  if (!s) throw new Error(`unusable worktree name "${name}"`);
  return s;
}

/** `worktree.baseRef` from the first settings file that sets it: project local, project, user. */
function readBaseRef(repoRoot) {
  const userDir = process.env.CLAUDE_CONFIG_DIR || path.join(os.homedir(), '.claude');
  const files = [
    path.join(repoRoot, '.claude', 'settings.local.json'),
    path.join(repoRoot, '.claude', 'settings.json'),
    path.join(userDir, 'settings.json'),
  ];
  for (const file of files) {
    try {
      const value = JSON.parse(fs.readFileSync(file, 'utf8'))?.worktree?.baseRef;
      if (typeof value === 'string' && value.trim()) return value.trim().toLowerCase();
    } catch {
      /* missing or unreadable: the next one */
    }
  }
  return '';
}

/** `origin/main` and the like: the remote default branch, or null when there is none. */
function originDefault(repoRoot) {
  const head = spawnSync('git', ['symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], {
    cwd: repoRoot, encoding: 'utf8', windowsHide: true,
  });
  if (head.status === 0 && head.stdout.trim()) return head.stdout.trim();
  for (const candidate of ['origin/main', 'origin/master']) {
    const found = spawnSync('git', ['show-ref', '--verify', '--quiet', `refs/remotes/${candidate}`], {
      cwd: repoRoot, windowsHide: true,
    });
    if (found.status === 0) return candidate;
  }
  return null;
}

/** The commit a new worktree branch starts from. */
function baseCommit(repoRoot, cwd) {
  if (readBaseRef(repoRoot) === 'fresh') {
    const remote = originDefault(repoRoot);
    if (remote) return git(repoRoot, ['rev-parse', '--verify', `${remote}^{commit}`]);
  }
  return git(cwd, ['rev-parse', '--verify', 'HEAD^{commit}']);   // the session's HEAD
}

function create(payload) {
  const cwd = payload.cwd || process.cwd();
  const repoRoot = mainRoot(cwd);
  const name = slug(payload.name);
  const configured = (process.env.CLAUDE_WORKTREE_ROOT || '').trim();
  const target = configured
    ? path.resolve(configured, `${path.basename(repoRoot)}-${name}`)
    : path.resolve(repoRoot, '.claude', 'worktrees', name);

  if (fs.existsSync(target)) {
    if (!fs.existsSync(path.join(target, '.git'))) throw new Error(`${target} exists and is not a worktree`);
    return target;
  }
  const branch = `worktree-${name}`;
  const exists = spawnSync('git', ['show-ref', '--verify', '--quiet', `refs/heads/${branch}`], {
    cwd: repoRoot, windowsHide: true,
  }).status === 0;
  git(repoRoot, exists ? ['worktree', 'add', target, branch] : ['worktree', 'add', '-b', branch, target, baseCommit(repoRoot, cwd)]);
  return target;
}

function remove(payload) {
  const target = path.resolve(payload.worktree_path);
  git(mainRoot(target), ['worktree', 'remove', target]);
}

try {
  const payload = JSON.parse(fs.readFileSync(0, 'utf8') || '{}');
  if (payload.hook_event_name === 'WorktreeRemove') remove(payload);
  else process.stdout.write(`${create(payload)}\n`);
  process.exit(0);
} catch (error) {
  process.stderr.write(`worktree-root: ${error.message}\n`);
  process.exit(1);
}
